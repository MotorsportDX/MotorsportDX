std::unique_ptr<ShaderOverrides> ShaderOverrides::Create(const HostConfig& config) {
  std::string path = REXCVAR_GET(shader_override_path);
  std::string generate_path = REXCVAR_GET(shader_override_generate_path);
  std::string mod_path = REXCVAR_GET(shader_mod_path);
  bool use_generated = REXCVAR_GET(shader_override_generated);
  if (path.empty() && generate_path.empty() && mod_path.empty() && !use_generated &&
      REXCVAR_GET(post_pass_path).empty()) {
    return nullptr;
  }
  if (!config.bindless_resources_used || config.edram_rov_used) {
    REXGPU_WARN("Shader overrides need bindless resources and host render targets");
    return nullptr;
  }
  std::unique_ptr<ShaderOverrides> overrides(new ShaderOverrides(config, path));
  if (!overrides->d3d_compile_) {
    REXGPU_ERROR("Shader overrides need D3DCompile from D3DCompiler_47.dll");
    return nullptr;
  }
  overrides->generate_path_ = generate_path;
  overrides->use_generated_ = use_generated;
  overrides->mod_directory_ = mod_path;
  ScanShaderFiles(overrides->mod_directory_, ".mod.hlsli", overrides->mod_shaders_);
  if (REXCVAR_GET(native_shader_contract)) {
    std::filesystem::path manifest_path = overrides->mod_directory_ / kNativeManifestName;
    std::string text, error;
    auto manifest = std::make_unique<native_shader_contract::Manifest>();
    if (!REXCVAR_GET(host_render_native)) {
      REXGPU_ERROR("native_shader_contract needs the native path (host_render_native); off");
    } else if (mod_path.empty()) {
      // A look without mods (the post passes alone): nothing to take.
      REXGPU_INFO("Native shader contract: no shader_mod_path, no entries");
    } else if (!ReadFile(manifest_path, text)) {
      REXGPU_ERROR("native_shader_contract: cannot read {}; off", manifest_path.generic_string());
    } else if (!native_shader_contract::ParseManifest(text, manifest_path.generic_string(),
                                                      *manifest, error)) {
      REXGPU_ERROR("native_shader_contract: {}: {}; off", manifest_path.generic_string(), error);
    } else {
      std::string passes;
      for (uint32_t pass = 0; pass < manifest->PassCount(); ++pass) {
        passes += fmt::format("{}{} {}", pass ? ", " : "", manifest->PassName(pass), pass);
      }
      for (const native_shader_contract::PixelEntry& entry : manifest->pixel) {
        overrides->entry_knobs_ |= !entry.params.empty();
      }
      for (const native_shader_contract::VertexEntry& entry : manifest->vertex) {
        overrides->entry_knobs_ |= !entry.params.empty();
      }
      overrides->native_vertex_all_ = REXCVAR_GET(native_shader_contract_vertex_all);
      REXGPU_INFO("Native shader contract: {} pixel shader entries, {} vertex shader entries{}; "
                  "passes {}",
                  manifest->pixel.size(), manifest->vertex.size(),
                  overrides->native_vertex_all_ ? ", every vertex shader generated" : "", passes);
      overrides->native_ = std::move(manifest);
      overrides->LoadLookFiles();
      overrides->native_pass_debug_ = REXCVAR_GET(native_shader_pass_debug);
      overrides->check_ = REXCVAR_GET(native_shader_contract_check);
      overrides->ab_precise_ = REXCVAR_GET(native_shader_contract_ab_precise);
      overrides->knob_defaults_ = ScanKnobDefaults(overrides->mod_directory_);
    }
  }
  overrides->uses_reactive_mark_ =
      ScanReactiveMark({&overrides->directory_, &overrides->mod_directory_});
  // NAME=VALUE;NAME=VALUE
  overrides->mod_defines_ = ParseDefines(REXCVAR_GET(shader_mod_defines), ";");
  overrides->live_knobs_ = REXCVAR_GET(shader_mod_live_knobs);
  overrides->hot_reload_ = REXCVAR_GET(shader_mod_hot_reload);
  if (overrides->hot_reload_ && !overrides->mod_directory_.empty()) {
    std::string text;
    if (RefreshFileState(overrides->mod_directory_ / kDefinesFile, overrides->defines_file_,
                         &text)) {
      for (const auto& define : ParseDefines(StripComments(text), "; \t\r\n")) {
        SetDefine(overrides->mod_defines_, define.first, define.second);
      }
      REXGPU_INFO("Shader overrides: defines from {}", kDefinesFile);
    }
  }
  {
    std::lock_guard<std::mutex> lock(overrides->knob_mutex_);
    overrides->RebuildCompileDefines();
  }
  const std::string& cache_path = REXCVAR_GET(shader_override_cache_path);
  if (!cache_path.empty()) {
    std::error_code error;
    std::filesystem::create_directories(cache_path, error);
    if (error) {
      REXGPU_WARN("Shader override cache: cannot create '{}': {}", cache_path, error.message());
    } else {
      overrides->cache_directory_ = cache_path;
    }
  }
  if (overrides->native_ && REXCVAR_GET(native_shader_dxil)) {
    overrides->dxil_compiler_ = DxilCompiler::Load();
    overrides->dxil_relaxed_ = REXCVAR_GET(native_shader_dxil_relaxed);
    if (overrides->dxil_compiler_ && !overrides->cache_directory_.empty()) {
      std::error_code error;
      std::filesystem::path dxil_directory = overrides->cache_directory_ / "dxil";
      std::filesystem::create_directories(dxil_directory, error);
      if (!error) {
        overrides->dxil_cache_directory_ = dxil_directory;
      }
    }
    if (overrides->dxil_compiler_) {
      REXGPU_INFO("DXIL shaders: the DXIL world on, DXC {}, {}",
                  overrides->dxil_compiler_->version(),
                  overrides->dxil_relaxed_ ? "relaxed" : "strict");
    }
  }
  overrides->last_poll_ = std::chrono::steady_clock::now();
  REXGPU_INFO("Shader overrides: {} pixel shaders in '{}', {} mods in '{}'{}{}{}{}{}",
              overrides->pixel_shaders_.size(), path, overrides->mod_shaders_.size(), mod_path,
              use_generated ? ", generated HLSL for the others" : "",
              generate_path.empty() ? "" : ", writing generated HLSL to " + generate_path,
              overrides->cache_directory_.empty()
                  ? ""
                  : ", cache in " + overrides->cache_directory_.generic_string(),
              overrides->hot_reload_ ? ", hot reload" : "",
              overrides->live_knobs_ ? fmt::format(", {} live knobs", overrides->knob_slots_.size())
                                     : "");
  std::lock_guard<std::mutex> lock(g_instance_mutex);
  g_instance = overrides.get();
  return overrides;
}

ShaderOverrides::ShaderOverrides(const HostConfig& config, std::filesystem::path directory)
    : config_(config), directory_(std::move(directory)) {
  HMODULE library = LoadLibraryW(L"D3DCompiler_47.dll");
  d3dcompiler_ = library;
  if (library) {
    d3d_compile_ = reinterpret_cast<void*>(GetProcAddress(library, "D3DCompile"));
    // The compiler's identity for the cache key: the size and time of its DLL.
    wchar_t module_path[MAX_PATH];
    DWORD length = GetModuleFileNameW(library, module_path, MAX_PATH);
    if (length && length < MAX_PATH) {
      std::error_code error;
      uint64_t identity[2] = {
          uint64_t(std::filesystem::file_size(module_path, error)),
          uint64_t(std::filesystem::last_write_time(module_path, error).time_since_epoch().count())};
      compiler_id_ = HashBytes(identity, sizeof(identity));
    }
  }
  library_hash_ = HashBytes(kShaderOverrideHlsli, sizeof(kShaderOverrideHlsli));
  // shader_<16 hex digits>[_<16 hex digits>].ps.hlsl
  ScanShaderFiles(directory_, ".ps.hlsl", pixel_shaders_);
}

ShaderOverrides::~ShaderOverrides() {
  {
    std::lock_guard<std::mutex> lock(g_instance_mutex);
    if (g_instance == this) {
      g_instance = nullptr;
    }
  }
  if (d3dcompiler_) {
    FreeLibrary(HMODULE(d3dcompiler_));
  }
}

bool ShaderOverrides::IsAbOffPhase() {
  int32_t period = REXCVAR_GET(shader_override_ab_ms);
  if (period <= 0) {
    return false;
  }
  auto milliseconds = std::chrono::duration_cast<std::chrono::milliseconds>(
                          std::chrono::steady_clock::now().time_since_epoch())
                          .count();
  return ((milliseconds / period) & 1) != 0;
}

bool ShaderOverrides::IsNativeAbClassicPhase() {
  int32_t period = REXCVAR_GET(native_shader_contract_ab_ms);
  if (period <= 0) {
    return false;
  }
  auto milliseconds = std::chrono::duration_cast<std::chrono::milliseconds>(
                          std::chrono::steady_clock::now().time_since_epoch())
                          .count();
  return ((milliseconds / period) & 1) != 0;
}

void ShaderOverrides::RebuildCompileDefines() {
  compile_defines_.clear();
  for (const auto& define : mod_defines_) {
    if (pass_names_.count(define.first)) {
      // The post passes read it (GetDefine), the mods don't.
      continue;
    }
    float value;
    if (live_knobs_ && ParseFloat(define.second, value)) {
      auto slot = knob_slots_.find(define.first);
      if (slot == knob_slots_.end() && knob_slots_.size() < kKnobCount) {
        slot = knob_slots_.emplace(define.first, uint32_t(knob_slots_.size())).first;
        knob_values_[slot->second] = value;
      }
      if (slot != knob_slots_.end()) {
        compile_defines_.emplace_back(define.first, fmt::format("xe_mod_knob({}u)", slot->second));
        continue;
      }
      REXGPU_WARN("Shader mods: more than {} live knobs, {} stays a define", kKnobCount,
                  define.first);
    }
    compile_defines_.push_back(define);
  }
  // The params of the manifest's entries: a knob slot each, with the value of
  // shader_mod_defines or the look files' default.
  if (native_) {
    std::vector<const std::vector<std::string>*> param_lists;
    for (const native_shader_contract::PixelEntry& entry : native_->pixel) {
      param_lists.push_back(&entry.params);
    }
    for (const native_shader_contract::VertexEntry& entry : native_->vertex) {
      param_lists.push_back(&entry.params);
    }
    for (const std::vector<std::string>* params : param_lists) {
      for (const std::string& name : *params) {
        if (knob_slots_.count(name)) {
          continue;
        }
        if (pass_names_.count(name)) {
          REXGPU_WARN("Native shader contract: param {} is a post pass name; stays a define",
                      name);
          continue;
        }
        std::string text;
        auto define = std::find_if(mod_defines_.begin(), mod_defines_.end(),
                                   [&name](const auto& define) { return define.first == name; });
        if (define != mod_defines_.end()) {
          text = define->second;
        } else if (auto fallback = knob_defaults_.find(name); fallback != knob_defaults_.end()) {
          text = fallback->second;
        }
        float value;
        if (!ParseFloat(text, value)) {
          REXGPU_WARN(
              "Native shader contract: param {} has no numeric value ('{}'); stays a define",
              name, text);
          continue;
        }
        if (knob_slots_.size() >= kKnobCount) {
          REXGPU_WARN("Native shader contract: more than {} knobs, {} stays a define",
                      kKnobCount, name);
          continue;
        }
        uint32_t slot = uint32_t(knob_slots_.size());
        knob_slots_.emplace(name, slot);
        knob_values_[slot] = value;
      }
    }
  }
  knob_generation_.fetch_add(1, std::memory_order_release);
  defines_generation_.fetch_add(1, std::memory_order_release);
}

bool ShaderOverrides::GetDefine(const std::string& name, std::string& value_out) const {
  std::lock_guard<std::mutex> lock(knob_mutex_);
  for (const auto& define : mod_defines_) {
    if (define.first == name) {
      value_out = define.second;
      return true;
    }
  }
  return false;
}

void ShaderOverrides::LoadLookFiles() {
  look_files_.clear();
  for (const native_shader_contract::PixelEntry& entry : native_->pixel) {
    for (const native_shader_contract::Resource& resource : entry.srv) {
      if (resource.kind != native_shader_contract::Resource::Kind::kFile ||
          std::any_of(look_files_.begin(), look_files_.end(),
                      [&resource](const LookFile& file) { return file.name == resource.name; })) {
        continue;
      }
      // The manifest has at most kMaxLookFiles names.
      LookFile& file = look_files_.emplace_back();
      file.name = resource.name;
      std::filesystem::path path = mod_directory_ / (resource.name + ".png");
      std::string data, error;
      uint32_t width = 0, height = 0;
      if (!ReadFile(path, data)) {
        error = "cannot be read";
      } else if (native_shader_contract::CheckLookPng(data, width, height, error)) {
        int decoded_width = 0, decoded_height = 0;
        file.rgba = ui::DecodeImageRGBA(reinterpret_cast<const uint8_t*>(data.data()),
                                        data.size(), decoded_width, decoded_height);
        if (file.rgba.empty() || uint32_t(decoded_width) != width ||
            uint32_t(decoded_height) != height) {
          file.rgba.clear();
          error = "cannot be decoded";
        }
      }
      if (file.rgba.empty()) {
        REXGPU_ERROR("Native shader contract: look file {} {}; xe_srv_{} reads 0.5 gray",
                     path.string(), error, file.name);
        file.width = 1;
        file.height = 1;
        file.rgba = {128, 128, 128, 255};
        continue;
      }
      file.width = width;
      file.height = height;
      REXGPU_INFO("Native shader contract: look file {} ({}x{})", path.filename().string(),
                  file.width, file.height);
    }
  }
}

void ShaderOverrides::SetPostTextures(std::vector<std::pair<std::string, uint32_t>> slots) {
  std::lock_guard<std::mutex> lock(knob_mutex_);
  post_texture_slots_.clear();
  post_texture_slots_.insert(slots.begin(), slots.end());
}

void ShaderOverrides::SetPassNames(std::vector<std::string> names) {
  std::lock_guard<std::mutex> lock(knob_mutex_);
  std::unordered_set<std::string> pass_names(names.begin(), names.end());
  if (pass_names == pass_names_) {
    return;
  }
  pass_names_ = std::move(pass_names);
  // The live knob slots of the mods without the pass names (no mod is compiled
  // yet when the passes are created).
  knob_slots_.clear();
  std::memset(knob_values_, 0, sizeof(knob_values_));
  RebuildCompileDefines();
}

bool ShaderOverrides::UpdateKnobs(float* values_out, uint64_t& generation) const {
  if (knob_generation_.load(std::memory_order_acquire) == generation) {
    return false;
  }
  std::lock_guard<std::mutex> lock(knob_mutex_);
  std::memcpy(values_out, knob_values_, sizeof(knob_values_));
  generation = knob_generation_.load(std::memory_order_relaxed);
  return true;
}

void ShaderOverrides::SetDefines(std::string_view text) {
  auto defines = ParseDefines(text, "; \t\r\n");
  std::lock_guard<std::mutex> lock(knob_mutex_);
  if (defines.empty()) {
    for (const auto& define : mod_defines_) {
      auto slot = knob_slots_.find(define.first);
      if (slot != knob_slots_.end()) {
        REXGPU_INFO("shader_mod_set: {}={} (live knob {})", define.first,
                    knob_values_[slot->second], slot->second);
      } else {
        REXGPU_INFO("shader_mod_set: {}={}", define.first, define.second);
      }
    }
    return;
  }
  for (const auto& define : defines) {
    auto same = [&define](const auto& current) {
      return current.first == define.first && current.second == define.second;
    };
    if (std::find_if(mod_defines_.begin(), mod_defines_.end(), same) != mod_defines_.end()) {
      // Back to the value it has: nothing to recompile for it.
      std::erase_if(pending_defines_,
                    [&define](const auto& pending) { return pending.first == define.first; });
      continue;
    }
    if (pass_names_.count(define.first)) {
      SetDefine(mod_defines_, define.first, define.second);
      defines_generation_.fetch_add(1, std::memory_order_release);
      REXGPU_INFO("shader_mod_set: {}={} (post passes)", define.first, define.second);
      continue;
    }
    float value;
    auto slot = knob_slots_.find(define.first);
    if (slot != knob_slots_.end() && ParseFloat(define.second, value)) {
      knob_values_[slot->second] = value;
      SetDefine(mod_defines_, define.first, define.second);
      knob_generation_.fetch_add(1, std::memory_order_release);
      defines_generation_.fetch_add(1, std::memory_order_release);
      REXGPU_INFO("shader_mod_set: {}={} (live)", define.first, value);
    } else if (hot_reload_) {
      SetDefine(pending_defines_, define.first, define.second);
      REXGPU_INFO("shader_mod_set: {}={} (recompiling the mods)", define.first, define.second);
    } else {
      REXGPU_WARN(
          "shader_mod_set: {} is not a live knob; it needs a restart, shader_mod_live_knobs or "
          "shader_mod_hot_reload",
          define.first);
    }
  }
}

const native_shader_contract::PixelEntry* ShaderOverrides::NativeEntry(
    const D3D12Shader::D3D12Translation& translation) const {
  Modification modification(translation.modification());
  // hlsl_override_disabled: also a pipeline of that phase that a build before
  // the contract stored, which the storage loads at startup.
  if (!native_ || modification.pixel.native_classic || modification.pixel.native_plain ||
      modification.pixel.hlsl_override_disabled) {
    return nullptr;
  }
  return native_->FindPixel(translation.shader().ucode_data_hash());
}

// The vertex shader's part of its contract (BuildContract): its registers,
// exports and signatures (StartTranslation, StartVertexOrDomainShader,
// CompleteVertexOrDomainShader, WriteInputSignature, WriteOutputSignature for
// the host vertex stage), its float constants and descriptor slots.
std::string ShaderOverrides::BuildVertexContract(const D3D12Shader::D3D12Translation& translation,
                                                 uint32_t register_count) const {
  const auto& shader = static_cast<const D3D12Shader&>(translation.shader());
  Modification modification(translation.modification());
  std::string out;
  auto line = [&out]<typename... Args>(fmt::format_string<Args...> format, Args&&... args) {
    fmt::format_to(std::back_inserter(out), format, std::forward<Args>(args)...);
    out.push_back('\n');
  };
  const uint32_t interpolator_mask = modification.vertex.interpolator_mask;
  const uint32_t clip_count = modification.GetVertexClipDistanceCount();
  const uint32_t cull_count = modification.GetVertexCullDistanceCount();
  const bool writes_kill = (shader.writes_point_size_edge_flag_kill_vertex() & 0b100) != 0;
  line("#define XE_REGISTER_COUNT {}", register_count);
  line("#define XE_INTERPOLATOR_MASK 0x{:04X}u", interpolator_mask);
  line("#define XE_USER_CLIP_PLANE_COUNT {}u", uint32_t(modification.vertex.user_clip_plane_count));
  // The user clip planes' first distance component: after the clip distances
  // if they cull.
  line("#define XE_USER_CLIP_PLANE_FIRST {}u",
       modification.vertex.user_clip_plane_cull ? clip_count : 0u);
  line("#define XE_WRITES_VERTEX_KILL {}", int(writes_kill));
  line("#define XE_VERTEX_KILL_AND {}", uint32_t(modification.vertex.vertex_kill_and));
  // The AND rule's cull distance: the last component.
  line("#define XE_VERTEX_KILL_DISTANCE {}u",
       clip_count + cull_count ? clip_count + cull_count - 1 : 0u);

  // Float constants, tightly packed like the translator's constant buffer.
  const Shader::ConstantRegisterMap& constants = shader.constant_register_map();
  line("#define XE_FLOAT_CONSTANT_COUNT {}", constants.float_count);
  for (uint32_t i = 0; i < 256; ++i) {
    uint32_t packed = constants.GetPackedFloatConstantIndex(i);
    if (packed != UINT32_MAX) {
      line("#define XE_FLOAT_CONSTANT_{} xe_float_constants[{}]", i, packed);
    }
  }

  // Bindless descriptor index slots (vertex texture fetch).
  const auto& textures = shader.GetTextureBindingsAfterTranslation();
  const auto& samplers = shader.GetSamplerBindingsAfterTranslation();
  uint32_t descriptor_index_count = 0;
  for (const auto& texture : textures) {
    descriptor_index_count =
        std::max(descriptor_index_count, texture.bindless_descriptor_index + 1);
  }
  for (const auto& sampler : samplers) {
    descriptor_index_count =
        std::max(descriptor_index_count, sampler.bindless_descriptor_index + 1);
  }
  line("#define XE_DESCRIPTOR_INDEX_VECTORS {}", (descriptor_index_count + 3) / 4);
  for (const auto& texture : textures) {
    line("#define {} {}u",
         HlslShaderTranslator::TextureSlotName(texture.fetch_constant, texture.dimension,
                                               texture.is_signed),
         texture.bindless_descriptor_index);
  }
  for (const auto& sampler : samplers) {
    line("#define {} {}u", HlslShaderTranslator::SamplerSlotName(sampler),
         sampler.bindless_descriptor_index);
  }

  // Input signature: the vertex index.
  line("struct XeVsInput {{");
  line("  uint xe_vertex_id : SV_VertexID;");
  line("}};");
  // Output signature: the interpolators of the mask, the position, the clip
  // and cull distances (clip first, four components a register), the point
  // size.
  line("struct XeVsOutput {{");
  uint32_t semantic_index = 0;
  std::string store = "#define XE_STORE_OUTPUTS(output, p, distances)";
  for (uint32_t i = 0; i < xenos::kMaxInterpolators; ++i) {
    if (interpolator_mask & (UINT32_C(1) << i)) {
      line("  float4 xe_interpolator{} : TEXCOORD{};", i, semantic_index++);
      store += fmt::format(" output.xe_interpolator{0} = p.o[{0}];", i);
    }
  }
  line("  float4 xe_position : SV_Position;");
  uint32_t clip_parameter = 0, cull_parameter = 0;
  for (uint32_t first = 0; first < clip_count + cull_count; first += 4) {
    uint32_t end = std::min(first + 4, clip_count + cull_count);
    if (first < clip_count) {
      uint32_t count = std::min(end, clip_count) - first;
      line("  float{} xe_clip{} : SV_ClipDistance{};", count == 1 ? std::string() : std::to_string(count),
           clip_parameter, clip_parameter);
      for (uint32_t c = 0; c < count; ++c) {
        store += fmt::format(" output.xe_clip{}{} = distances[{}];", clip_parameter,
                             count == 1 ? std::string() : std::string(".") + "xyzw"[c], first + c);
      }
      ++clip_parameter;
    }
    if (end > clip_count) {
      uint32_t cull_first = std::max(first, clip_count);
      uint32_t count = end - cull_first;
      line("  float{} xe_cull{} : SV_CullDistance{};", count == 1 ? std::string() : std::to_string(count),
           cull_parameter, cull_parameter);
      for (uint32_t c = 0; c < count; ++c) {
        store += fmt::format(" output.xe_cull{}{} = distances[{}];", cull_parameter,
                             count == 1 ? std::string() : std::string(".") + "xyzw"[c],
                             cull_first + c);
      }
      ++cull_parameter;
    }
  }
  if (modification.vertex.output_point_size) {
    line("  float xe_point_size : XEPSIZE;");
    store += " output.xe_point_size = p.point_size_edge_flag_kill.x;";
  }
  line("}};");
  out += store;
  out.push_back('\n');
  return out;
}

std::string ShaderOverrides::BuildContract(
    const D3D12Shader::D3D12Translation& translation,
    const native_shader_contract::PixelEntry* entry,
    const native_shader_contract::VertexEntry* vertex_entry) const {
  const auto& shader = static_cast<const D3D12Shader&>(translation.shader());
  Modification modification(translation.modification());
  // A vertex shader's contract (docs/analysis/shader-contract.md 9): its
  // registers, exports and output signature in place of the pixel shader's.
  const bool vertex = shader.type() == xenos::ShaderType::kVertex;
  std::string out;
  auto line = [&out]<typename... Args>(fmt::format_string<Args...> format, Args&&... args) {
    fmt::format_to(std::back_inserter(out), format, std::forward<Args>(args)...);
    out.push_back('\n');
  };

  line("// Contract of the DXBC translation of {} shader {:016X}, modification {:016X}.",
       vertex ? "vertex" : "pixel", shader.ucode_data_hash(), translation.modification());
  if (vertex) {
    line("#define XE_PIXEL_SHADER 0");
    line("#define XE_VERTEX_SHADER 1");
  } else {
    line("#define XE_PIXEL_SHADER 1");
  }

  // System constants (DxbcShaderTranslator::SystemConstants), the host values
  // and the live knobs after them (also for the params of a manifest entry).
  if (live_knobs_ || (entry && !entry->params.empty()) ||
      (vertex_entry && !vertex_entry->params.empty())) {
    line("#define XE_SYSTEM_CONSTANT_VECTORS {}", (kKnobsOffset + kKnobsSize + 15) / 16);
    line("#define XE_SYS_MOD_KNOBS {}u", kKnobsOffset);
  } else {
    line("#define XE_SYSTEM_CONSTANT_VECTORS {}", (kHostValuesOffset + kHostValuesSize + 15) / 16);
  }
  line("#define XE_SYS_GUEST_VBLANK_RATE {}u", kHostValuesOffset);
  line("#define XE_SYS_GUEST_FRAME_INTERVAL {}u", kHostValuesOffset + 4);
  line("#define XE_SYS_GUEST_DESIGN_FRAME_RATE {}u", kHostValuesOffset + 8);
  if (entry || vertex_entry) {
    // The native shader contract (docs/analysis/shader-contract.md): the draw's
    // pass class in the host values' W, and the classes by name.
    line("#define XE_NATIVE_CONTRACT 1");
    line("#define XE_SYS_NATIVE_PASS {}u", kHostValuesOffset + 12);
    for (uint32_t pass = 0; pass < native_->PassCount(); ++pass) {
      std::string name(native_->PassName(pass));
      std::transform(name.begin(), name.end(), name.begin(),
                     [](char c) { return char(std::toupper(uint8_t(c))); });
      line("#define XE_NATIVE_PASS_{} {}u", name, pass);
    }
  }
  if (entry) {
    if (native_pass_debug_) {
      line("#define XE_NATIVE_PASS_DEBUG 1");
    }
    // The resources the entry reads by name: a look file through its view
    // (xe_look_file), or a post pass texture through its slot
    // (xe_post_texture), 0 without post passes, or if they expose no texture
    // by that name.
    for (const native_shader_contract::Resource& resource : entry->srv) {
      std::string upper(resource.name);
      std::transform(upper.begin(), upper.end(), upper.begin(),
                     [](char c) { return char(std::toupper(uint8_t(c))); });
      line("#define XE_SRV_{} 1", upper);
      if (resource.kind == native_shader_contract::Resource::Kind::kFile) {
        auto file = std::find_if(
            look_files_.begin(), look_files_.end(),
            [&resource](const LookFile& look_file) { return look_file.name == resource.name; });
        if (file != look_files_.end()) {
          uint32_t index = uint32_t(file - look_files_.begin());
          line("#define xe_srv_{}(uv) xe_look_file({}u, uv)", resource.name, index);
          line("#define xe_srv_{}_linear(uv) xe_look_file_linear({}u, uv)", resource.name, index);
        } else {
          line("#define xe_srv_{}(uv) float4(0.0, 0.0, 0.0, 0.0)", resource.name);
          line("#define xe_srv_{}_linear(uv) float4(0.0, 0.0, 0.0, 0.0)", resource.name);
        }
        continue;
      }
      uint32_t slot = UINT32_MAX;
      bool post_passes = false;
      {
        std::lock_guard<std::mutex> lock(knob_mutex_);
        post_passes = !post_texture_slots_.empty();
        auto found = post_texture_slots_.find(resource.name);
        if (found != post_texture_slots_.end()) {
          slot = found->second;
        }
      }
      if (slot != UINT32_MAX) {
        line("#define xe_srv_{}(uv) xe_post_texture({}u, uv)", resource.name, slot);
      } else {
        if (post_passes) {
          REXGPU_WARN("Native shader contract: {:016X}: the post passes expose no texture '{}' "
                      "to mods (a slot in passes.toml); xe_srv_{} reads 0",
                      shader.ucode_data_hash(), resource.name, resource.name);
        }
        line("#define xe_srv_{}(uv) float4(0.0, 0.0, 0.0, 0.0)", resource.name);
      }
    }
  }
  line("#define XE_SYS_FLAGS {}u", offsetof(SystemConstants, flags));
  line("#define XE_SYS_TEXTURE_SWIZZLED_SIGNS {}u",
       offsetof(SystemConstants, texture_swizzled_signs));
  line("#define XE_SYS_TEXTURES_RESOLUTION_SCALED {}u",
       offsetof(SystemConstants, textures_resolution_scaled));
  line("#define XE_SYS_SAMPLE_COUNT_LOG2 {}u", offsetof(SystemConstants, sample_count_log2));
  line("#define XE_SYS_ALPHA_TEST_REFERENCE {}u",
       offsetof(SystemConstants, alpha_test_reference));
  line("#define XE_SYS_ALPHA_TO_MASK {}u", offsetof(SystemConstants, alpha_to_mask));
  line("#define XE_SYS_COLOR_EXP_BIAS {}u", offsetof(SystemConstants, color_exp_bias));
  line("#define XE_SYS_TEXTURE_INTEGER_SCALE_BITS {}u",
       offsetof(SystemConstants, texture_integer_scale_bits));
  line("#define XE_SYSFLAG_PRIMITIVE_POLYGONAL {}u",
       uint32_t(DxbcShaderTranslator::kSysFlag_PrimitivePolygonal));
  line("#define XE_SYSFLAG_PRIMITIVE_LINE_SHIFT {}u",
       uint32_t(DxbcShaderTranslator::kSysFlag_PrimitiveLine_Shift));
  line("#define XE_SYSFLAG_DEPTH_FLOAT24 {}u",
       uint32_t(DxbcShaderTranslator::kSysFlag_DepthFloat24));
  line("#define XE_SYSFLAG_ALPHA_PASS_IF_LESS_SHIFT {}u",
       uint32_t(DxbcShaderTranslator::kSysFlag_AlphaPassIfLess_Shift));
  line("#define XE_SYSFLAG_CONVERT_COLOR0_TO_GAMMA_SHIFT {}u",
       uint32_t(DxbcShaderTranslator::kSysFlag_ConvertColor0ToGamma_Shift));
  if (vertex) {
    // The vertex index, the exports' conventions and the guest-to-host
    // transform (StartVertexShader_LoadVertexIndex, CompleteVertexOrDomainShader).
    line("#define XE_SYS_LINE_LOOP_CLOSING_INDEX {}u",
         offsetof(SystemConstants, line_loop_closing_index));
    line("#define XE_SYS_VERTEX_INDEX_ENDIAN {}u", offsetof(SystemConstants, vertex_index_endian));
    line("#define XE_SYS_VERTEX_INDEX_OFFSET {}u", offsetof(SystemConstants, vertex_index_offset));
    line("#define XE_SYS_VERTEX_INDEX_MIN {}u", offsetof(SystemConstants, vertex_index_min));
    line("#define XE_SYS_VERTEX_INDEX_MAX {}u", offsetof(SystemConstants, vertex_index_max));
    line("#define XE_SYS_USER_CLIP_PLANES {}u", offsetof(SystemConstants, user_clip_planes));
    line("#define XE_SYS_NDC_SCALE {}u", offsetof(SystemConstants, ndc_scale));
    line("#define XE_SYS_NDC_OFFSET {}u", offsetof(SystemConstants, ndc_offset));
    line("#define XE_SYS_POINT_VERTEX_DIAMETER_MIN {}u",
         offsetof(SystemConstants, point_vertex_diameter_min));
    line("#define XE_SYS_POINT_VERTEX_DIAMETER_MAX {}u",
         offsetof(SystemConstants, point_vertex_diameter_max));
    line("#define XE_SYSFLAG_SHARED_MEMORY_IS_UAV {}u",
         uint32_t(DxbcShaderTranslator::kSysFlag_SharedMemoryIsUAV));
    line("#define XE_SYSFLAG_W_NOT_RECIPROCAL {}u",
         uint32_t(DxbcShaderTranslator::kSysFlag_WNotReciprocal));
    line("#define XE_SYSFLAG_XY_DIVIDED_BY_W {}u",
         uint32_t(DxbcShaderTranslator::kSysFlag_XYDividedByW));
    line("#define XE_SYSFLAG_Z_DIVIDED_BY_W {}u",
         uint32_t(DxbcShaderTranslator::kSysFlag_ZDividedByW));
  }

  // Host configuration of the translator. The scene's scale is a pixel shader
  // modification.
  const bool scene_scale = !vertex && modification.pixel.scene_scale;
  const bool scene_input_scale = !vertex && modification.pixel.scene_input_scale;
  uint32_t scale_x = config_.draw_resolution_scale_x, scale_y = config_.draw_resolution_scale_y;
  const DrawScale scene =
      scene_input_scale ? config_.scene_input_scale : config_.scene_draw_scale;
  if (scene_scale && !scene.IsWhole()) {
    // A scene draw at a fractional scale (18.13): the macros as floats.
    line("#define XE_RESOLUTION_SCALE_X ({}.0 / {}.0)", scene.numerator, scene.denominator);
    line("#define XE_RESOLUTION_SCALE_Y ({}.0 / {}.0)", scene.numerator, scene.denominator);
    line("#define XE_REVERT_RESOLUTION_SCALE_AXES {}u",
         REXCVAR_GET(draw_resolution_scaled_texture_offsets) ? 3u : 0u);
  } else {
    if (scene_scale) {
      scale_x = scale_y = scene.Floor();
    }
    line("#define XE_RESOLUTION_SCALE_X {}", scale_x);
    line("#define XE_RESOLUTION_SCALE_Y {}", scale_y);
    line("#define XE_REVERT_RESOLUTION_SCALE_AXES {}u",
         REXCVAR_GET(draw_resolution_scaled_texture_offsets)
             ? uint32_t(scale_x > 1) | (uint32_t(scale_y > 1) << 1)
             : 0u);
  }
  if (scene_scale && scene_input_scale) {
    const float lod_bias =
        DxbcShaderTranslator::SceneInputLodBias(config_.scene_input_scale, config_.scene_draw_scale);
    if (lod_bias != 0.0f) {
      line("#define XE_SCENE_LOD_BIAS {:.9g}", lod_bias);
    }
  }
  line("#define XE_GAMMA_RENDER_TARGET_AS_UNORM8 {}", int(config_.gamma_render_target_as_unorm8));
  line("#define XE_MSAA_2X_SUPPORTED {}", int(config_.msaa_2x_supported));
  line("#define XE_FUZZY_ALPHA_EPSILON {}", int(REXCVAR_GET(use_fuzzy_alpha_epsilon)));
  // The textures the post passes expose to mods in xe_textures_2d
  // (xe_post_texture, xe_post_ao): 0 without post passes and in frames they
  // have not run in.
  line("#define XE_POST_VIEWS {}u",
       uint32_t(D3D12CommandProcessor::SystemBindlessView::kPostPassViewsStart) -
           uint32_t(D3D12CommandProcessor::SystemBindlessView::kUnboundedSRVsStart));
  line("#define XE_POST_VIEW_COUNT {}u", D3D12CommandProcessor::kPostPassViewCount);
  // The look files of the native shader contract's entries (xe_look_file).
  line("#define XE_LOOK_FILE_VIEWS {}u",
       uint32_t(D3D12CommandProcessor::SystemBindlessView::kLookFileViewsStart) -
           uint32_t(D3D12CommandProcessor::SystemBindlessView::kUnboundedSRVsStart));

  // Registers and interpolators (StartTranslation, StartPixelShader).
  uint32_t register_count = shader.register_static_address_bound();
  if (shader.uses_register_dynamic_addressing()) {
    register_count = std::max(
        register_count, uint32_t(vertex ? modification.vertex.dynamic_addressable_register_count
                                        : modification.pixel.dynamic_addressable_register_count));
  }
  if (vertex) {
    return out + BuildVertexContract(translation, std::max(register_count, uint32_t(1)));
  }
  uint32_t interpolator_mask = modification.pixel.interpolator_mask;
  int32_t param_gen_interpolator =
      (modification.pixel.param_gen_enable &&
       modification.pixel.param_gen_interpolator < register_count)
          ? int32_t(modification.pixel.param_gen_interpolator)
          : -1;
  line("#define XE_REGISTER_COUNT {}", std::max(register_count, uint32_t(1)));
  line("#define XE_INTERPOLATOR_MASK 0x{:04X}u", interpolator_mask);
  // FXC evaluates #if -1 >= 0 as true: a separate flag.
  line("#define XE_PARAM_GEN_ENABLED {}", int(param_gen_interpolator >= 0));
  line("#define XE_PARAM_GEN_INTERPOLATOR {}", std::max(param_gen_interpolator, 0));
  line("#define XE_PARAM_GEN_POINT {}", uint32_t(modification.pixel.param_gen_point));

  // Outputs (CompletePixelShader).
  uint32_t color_targets = shader.writes_color_targets();
  bool force_early_depth_stencil =
      modification.pixel.depth_stencil_mode == Modification::DepthStencilMode::kEarlyHint &&
      shader.implicit_early_z_write_allowed();
  line("#define XE_COLOR_TARGETS_WRITTEN 0x{:X}", color_targets);
  line("#define XE_WRITES_DEPTH {}", int(shader.writes_depth()));
  line("#define XE_FORCE_EARLY_DEPTH_STENCIL {}", int(force_early_depth_stencil));
  line("#define XE_PS_ATTRIBUTES {}", force_early_depth_stencil ? "[earlydepthstencil]" : "");

  // Float constants, tightly packed like the translator's constant buffer. A
  // replacement reads them by name only (its inputs below).
  const bool replacement = entry && !entry->shader.empty();
  const Shader::ConstantRegisterMap& constants = shader.constant_register_map();
  line("#define XE_FLOAT_CONSTANT_COUNT {}", constants.float_count);
  for (uint32_t i = 0; i < 256 && !replacement; ++i) {
    uint32_t packed = constants.GetPackedFloatConstantIndex(i);
    if (packed != UINT32_MAX) {
      line("#define XE_FLOAT_CONSTANT_{} xe_float_constants[{}]", i, packed);
    }
  }

  // Bindless descriptor index slots.
  const auto& textures = shader.GetTextureBindingsAfterTranslation();
  const auto& samplers = shader.GetSamplerBindingsAfterTranslation();
  // The translator numbers the slots from 1 (the count after adding a binding).
  uint32_t descriptor_index_count = 0;
  for (const auto& texture : textures) {
    descriptor_index_count =
        std::max(descriptor_index_count, texture.bindless_descriptor_index + 1);
  }
  for (const auto& sampler : samplers) {
    descriptor_index_count =
        std::max(descriptor_index_count, sampler.bindless_descriptor_index + 1);
  }
  line("#define XE_DESCRIPTOR_INDEX_VECTORS {}", (descriptor_index_count + 3) / 4);
  for (const auto& texture : textures) {
    line("#define {} {}u",
         HlslShaderTranslator::TextureSlotName(texture.fetch_constant, texture.dimension,
                                               texture.is_signed),
         texture.bindless_descriptor_index);
  }
  for (const auto& sampler : samplers) {
    line("#define {} {}u", HlslShaderTranslator::SamplerSlotName(sampler),
         sampler.bindless_descriptor_index);
  }

  if (replacement) {
    // A replacement's game inputs by name (docs/analysis/shader-contract.md 8),
    // as CheckInputs found them: XeInputs, which the library fills after the
    // prologue (XE_LOAD_INPUTS), and per texture xe_tex_<name>(coord), the
    // fetch at the dimension and with the sampler of the shader's binding, and
    // XE_TEX_<NAME>, its fetch constant (FXC takes no macro with an empty
    // parameter list).
    line("#define XE_REPLACEMENT 1");
    std::string load = "#define XE_LOAD_INPUTS(xe_in, p, input)";
    // The defines after the struct.
    std::string defines;
    auto define = [&defines]<typename... Args>(fmt::format_string<Args...> format, Args&&... args) {
      fmt::format_to(std::back_inserter(defines), format, std::forward<Args>(args)...);
      defines.push_back('\n');
    };
    line("struct XeInputs {{");
    bool members = false;
    for (const native_shader_contract::Input& input : entry->inputs) {
      using Kind = native_shader_contract::Input::Kind;
      std::string upper(input.name);
      std::transform(upper.begin(), upper.end(), upper.begin(),
                     [](char c) { return char(std::toupper(uint8_t(c))); });
      std::string swizzle = input.swizzle.empty() ? std::string() : "." + input.swizzle;
      std::string vector_type =
          input.swizzle.size() == 1
              ? std::string("float")
              : fmt::format("float{}", input.swizzle.empty() ? size_t(4) : input.swizzle.size());
      switch (input.kind) {
        case Kind::kInterpolator:
          line("  {} {};", vector_type, input.name);
          load += fmt::format(" xe_in.{} = p.r[{}]{};", input.name, input.index, swizzle);
          break;
        case Kind::kFloatConstant:
          line("  {} {};", vector_type, input.name);
          load += fmt::format(" xe_in.{} = xe_float_constants[{}]{};", input.name,
                              constants.GetPackedFloatConstantIndex(input.index), swizzle);
          break;
        case Kind::kBoolConstant:
          line("  bool {};", input.name);
          load += fmt::format(" xe_in.{} = xe_bool_constant({}u);", input.name, input.index);
          break;
        case Kind::kPosition:
          line("  float4 {};", input.name);
          load += fmt::format(" xe_in.{} = input.xe_position;", input.name);
          break;
        case Kind::kFrontFace:
          line("  bool {};", input.name);
          load += fmt::format(" xe_in.{} = input.xe_is_front_face;", input.name);
          break;
        case Kind::kTexture: {
          // 3D (with the stacked 2D array) over cube over 2D (1D as 2D).
          xenos::FetchOpDimension dimension = xenos::FetchOpDimension::k2D;
          for (const auto& texture : textures) {
            if (texture.fetch_constant != input.index) {
              continue;
            }
            if (texture.dimension == xenos::FetchOpDimension::k3DOrStacked ||
                (texture.dimension == xenos::FetchOpDimension::kCube &&
                 dimension == xenos::FetchOpDimension::k2D)) {
              dimension = texture.dimension;
            }
          }
          auto sampler = std::find_if(samplers.begin(), samplers.end(), [&input](const auto& s) {
            return s.fetch_constant == input.index;
          });
          std::string sampler_slot =
              sampler != samplers.end() ? HlslShaderTranslator::SamplerSlotName(*sampler) : "0u";
          auto slot = [&input](xenos::FetchOpDimension slot_dimension, bool is_signed) {
            return HlslShaderTranslator::TextureSlotName(input.index, slot_dimension, is_signed);
          };
          if (dimension == xenos::FetchOpDimension::k3DOrStacked) {
            define("#define xe_tex_{}(coord) xe_tfetch_3d({}u, {}, {}, {}, {}, {}, (coord), 0.0, "
                 "false, XE_LOD_COMPUTED, 0.0, 0.0, XE_FILTER_FETCH_CONSTANT, "
                 "XE_FILTER_FETCH_CONSTANT)",
                 input.name, input.index, slot(dimension, false), slot(dimension, true),
                 slot(xenos::FetchOpDimension::k2D, false),
                 slot(xenos::FetchOpDimension::k2D, true), sampler_slot);
          } else if (dimension == xenos::FetchOpDimension::kCube) {
            define("#define xe_tex_{}(coord) xe_tfetch_cube({}u, {}, {}, {}, (coord), 0.0, false, "
                 "XE_LOD_COMPUTED, 0.0, 0.0)",
                 input.name, input.index, slot(dimension, false), slot(dimension, true),
                 sampler_slot);
          } else {
            define("#define xe_tex_{}(coord) xe_tfetch_2d({}u, {}, {}, {}, (coord), 0.0, false, "
                 "XE_LOD_COMPUTED, 0.0, 0.0)",
                 input.name, input.index, slot(dimension, false), slot(dimension, true),
                 sampler_slot);
          }
          // The fetch constant, for the library's helpers (xe_texture_size_2d).
          define("#define XE_TEX_{} {}u", upper, input.index);
        } break;
      }
      members |= input.kind != Kind::kTexture;
      define("#define XE_IN_{} 1", upper);
    }
    if (!members) {
      line("  uint xe_none;");
    }
    line("}};");
    out += defines;
    line("{}", load);
  }

  // Input signature (WriteInputSignature): all interpolators of the mask, then
  // the point coordinates, the position and the face.
  line("struct XePsInput {{");
  uint32_t semantic_index = 0;
  for (uint32_t i = 0; i < xenos::kMaxInterpolators; ++i) {
    if (interpolator_mask & (UINT32_C(1) << i)) {
      line("  {}float4 xe_interpolator{} : TEXCOORD{};",
           (modification.pixel.interpolators_centroid & (UINT32_C(1) << i)) ? "centroid " : "",
           i, semantic_index++);
    }
  }
  if (modification.pixel.param_gen_point) {
    line("  float2 xe_point_coordinates : XESPRITETEXCOORD;");
  }
  line("  float4 xe_position : SV_Position;");
  line("  bool xe_is_front_face : SV_IsFrontFace;");
  line("}};");

  // Output signature (WriteOutputSignature for host render targets).
  line("struct XePsOutput {{");
  for (uint32_t i = 0; i < xenos::kMaxColorRenderTargets; ++i) {
    if (color_targets & (1u << i)) {
      line("  float4 xe_color{} : SV_Target{};", i, i);
    }
  }
  if ((color_targets & 1) && !force_early_depth_stencil) {
    line("  uint xe_coverage : SV_Coverage;");
  }
  if (shader.writes_depth()) {
    line("  float xe_depth : SV_Depth;");
  }
  line("}};");

  out += "#define XE_LOAD_INTERPOLATORS(p, input)";
  for (uint32_t i = 0; i < std::min(register_count, uint32_t(xenos::kMaxInterpolators)); ++i) {
    if (int32_t(i) != param_gen_interpolator && (interpolator_mask & (UINT32_C(1) << i))) {
      fmt::format_to(std::back_inserter(out), " p.r[{}] = input.xe_interpolator{};", i, i);
    }
  }
  out.push_back('\n');
  return out;
}

std::string ShaderOverrides::CheckInputs(const D3D12Shader::D3D12Translation& translation,
                                         const native_shader_contract::PixelEntry& entry) const {
  using Kind = native_shader_contract::Input::Kind;
  const auto& shader = static_cast<const D3D12Shader&>(translation.shader());
  Modification modification(translation.modification());
  uint32_t register_count = shader.register_static_address_bound();
  if (shader.uses_register_dynamic_addressing()) {
    register_count =
        std::max(register_count, uint32_t(modification.pixel.dynamic_addressable_register_count));
  }
  bool param_gen = modification.pixel.param_gen_enable &&
                   modification.pixel.param_gen_interpolator < register_count;
  for (const native_shader_contract::Input& input : entry.inputs) {
    switch (input.kind) {
      case Kind::kInterpolator:
        // Loaded from the mask, or the param gen register.
        if (input.index >= register_count ||
            (!(modification.pixel.interpolator_mask & (UINT32_C(1) << input.index)) &&
             !(param_gen && input.index == modification.pixel.param_gen_interpolator))) {
          return fmt::format("input '{}': interpolator {} is not one of this translation's",
                             input.name, input.index);
        }
        break;
      case Kind::kFloatConstant:
        if (shader.constant_register_map().GetPackedFloatConstantIndex(input.index) ==
            UINT32_MAX) {
          return fmt::format("input '{}': the shader does not read float constant {}", input.name,
                             input.index);
        }
        break;
      case Kind::kTexture: {
        const auto& textures = shader.GetTextureBindingsAfterTranslation();
        const auto& samplers = shader.GetSamplerBindingsAfterTranslation();
        auto fetches = [&input](const auto& binding) {
          return binding.fetch_constant == input.index;
        };
        if (std::none_of(textures.begin(), textures.end(), fetches) ||
            std::none_of(samplers.begin(), samplers.end(), fetches)) {
          return fmt::format("input '{}': the shader does not fetch texture {}", input.name,
                             input.index);
        }
      } break;
      default:
        break;
    }
  }
  return std::string();
}

uint64_t ShaderOverrides::CacheKey(
    const std::string& source,
    const std::vector<std::pair<std::string, std::string>>& defines, bool dxil) const {
  XXH3_state_t state;
  XXH3_64bits_reset(&state);
  uint64_t header[] = {kCacheVersion, dxil ? dxil_compiler_->identity() : compiler_id_,
                       library_hash_,
                       dxil ? uint64_t(kDxilCacheMagic) + dxil_relaxed_ : uint64_t(kCompileFlags)};
  XXH3_64bits_update(&state, header, sizeof(header));
  if (dxil) {
    XXH3_64bits_update(&state, kDxilTarget, sizeof(kDxilTarget));
  } else {
    XXH3_64bits_update(&state, kTarget, sizeof(kTarget));
  }
  uint64_t source_size = source.size();
  XXH3_64bits_update(&state, &source_size, sizeof(source_size));
  XXH3_64bits_update(&state, source.data(), source.size());
  for (const auto& define : defines) {
    // NUL-terminated, so names and values can't run into each other.
    XXH3_64bits_update(&state, define.first.c_str(), define.first.size() + 1);
    XXH3_64bits_update(&state, define.second.c_str(), define.second.size() + 1);
  }
  return XXH3_64bits_digest(&state);
}

std::filesystem::path ShaderOverrides::CachePath(
    const D3D12Shader::D3D12Translation& translation, uint64_t key, bool dxil) const {
  return (dxil ? dxil_cache_directory_ : cache_directory_) /
         fmt::format("{}_{:016X}_{:016X}_{:016X}.{}",
                     translation.shader().type() == xenos::ShaderType::kVertex ? "vertex" : "shader",
                     translation.shader().ucode_data_hash(), translation.modification(), key,
                     dxil ? "dxil" : "dxbc");
}

std::filesystem::path ShaderOverrides::ResolveInclude(
    const std::string& name, const std::vector<std::filesystem::path>& directories) {
  for (const std::filesystem::path& directory : directories) {
    if (directory.empty()) {
      continue;
    }
    std::ifstream file(directory / name, std::ios::binary);
    if (file) {
      return directory / name;
    }
  }
  return std::filesystem::path();
}

bool ShaderOverrides::LoadCached(const std::filesystem::path& path, uint64_t key,
                                 const std::vector<std::filesystem::path>& directories,
                                 std::vector<uint8_t>& binary_out,
                                 std::vector<Dependency>& files_out, uint32_t magic_expected) const {
  if (!magic_expected) {
    magic_expected = kCacheMagic;
  }
  std::string data;
  if (!ReadFile(path, data)) {
    return false;
  }
  size_t offset = 0;
  auto read = [&data, &offset](void* out, size_t size) {
    if (data.size() - offset < size) {
      return false;
    }
    std::memcpy(out, data.data() + offset, size);
    offset += size;
    return true;
  };
  uint32_t magic, version, count;
  uint64_t stored_key;
  if (!read(&magic, 4) || magic != magic_expected || !read(&version, 4) ||
      version != kCacheVersion || !read(&stored_key, 8) || stored_key != key ||
      !read(&count, 4)) {
    return false;
  }
  std::vector<Dependency> files;
  for (uint32_t i = 0; i < count; ++i) {
    uint32_t length;
    if (!read(&length, 4) || data.size() - offset < length) {
      return false;
    }
    Dependency& file = files.emplace_back();
    file.name.assign(data.data() + offset, length);
    offset += length;
    if (!read(&file.hash, 8)) {
      return false;
    }
    // Still the content it was compiled with, where the include finds it now.
    file.path = ResolveInclude(file.name, directories);
    std::string text;
    if (file.path.empty() || !ReadFile(file.path, text) ||
        HashBytes(text.data(), text.size()) != file.hash) {
      return false;
    }
  }
  uint32_t size;
  if (!read(&size, 4) || data.size() - offset != size) {
    return false;
  }
  binary_out.assign(data.begin() + offset, data.end());
  files_out = std::move(files);
  return true;
}

void ShaderOverrides::StoreCached(const std::filesystem::path& path, uint64_t key,
                                  const std::vector<Dependency>& files,
                                  const std::vector<uint8_t>& binary, uint32_t magic) const {
  std::string data;
  auto write = [&data](const void* in, size_t size) {
    data.append(static_cast<const char*>(in), size);
  };
  uint32_t header[] = {magic ? magic : kCacheMagic, kCacheVersion};
  write(header, sizeof(header));
  write(&key, sizeof(key));
  uint32_t count = uint32_t(files.size());
  write(&count, sizeof(count));
  for (const Dependency& file : files) {
    uint32_t length = uint32_t(file.name.size());
    write(&length, sizeof(length));
    write(file.name.data(), length);
    write(&file.hash, sizeof(file.hash));
  }
  uint32_t size = uint32_t(binary.size());
  write(&size, sizeof(size));
  write(binary.data(), binary.size());
  // Written aside and renamed, so a reader never sees half a file.
  std::filesystem::path temporary = path;
  temporary += fmt::format(".{}.tmp", std::hash<std::thread::id>{}(std::this_thread::get_id()));
  {
    std::ofstream file(temporary, std::ios::binary | std::ios::trunc);
    file.write(data.data(), std::streamsize(data.size()));
    if (!file) {
      REXGPU_WARN("Shader override cache: cannot write {}", temporary.generic_string());
      return;
    }
  }
  std::error_code error;
  std::filesystem::rename(temporary, path, error);
  if (error) {
    REXGPU_WARN("Shader override cache: cannot write {}: {}", path.generic_string(),
                error.message());
    std::filesystem::remove(temporary, error);
  }
}

bool ShaderOverrides::Compile(const D3D12Shader::D3D12Translation& translation,
                              const std::vector<uint8_t>& dxbc, const std::string& contract,
                              const std::string& text, const std::string& name,
                              const std::string& mod,
                              const std::vector<std::string>* params,
                              std::vector<uint8_t>& binary_out,
                              std::vector<Dependency>& files_out,
                              std::unique_ptr<CompileJob>* job_out, bool dxil) const {
  auto job = std::make_unique<CompileJob>();
  job->dxil = dxil;
  job->shader = &translation.shader();
  job->modification = translation.modification();
  job->name = name;
  job->mod = mod;
  // Contract, library (with the default hooks), mod (redefining hooks), the
  // shader, main.
  std::string& source = job->source;
  source = contract;
  source += fmt::format("#include \"{}\"\n", kHlsliName);
  if (!mod.empty()) {
    source += fmt::format("#include \"{}\"\n", mod);
  }
  source += fmt::format("#line 1 \"{}\"\n", name);
  source += text;
  source += fmt::format("\n#define XE_OVERRIDE_MAIN\n#include \"{}\"\n", kHlsliName);

  std::vector<std::pair<std::string, std::string>>& define_values = job->defines;
  {
    std::lock_guard<std::mutex> lock(knob_mutex_);
    define_values = compile_defines_;
    // A manifest entry reads its params from their knob slots.
    if (params) {
      for (const std::string& param : *params) {
        auto slot = knob_slots_.find(param);
        if (slot != knob_slots_.end()) {
          SetDefine(define_values, param, fmt::format("xe_mod_knob({}u)", slot->second));
        }
      }
    }
  }

  if (!(dxil ? dxil_cache_directory_ : cache_directory_).empty()) {
    const uint64_t load_start =
        perf_trace::shader_work_for_draw ? perf_trace::ZoneStart() : 0;
    job->key = CacheKey(source, define_values, dxil);
    job->cache_path = CachePath(translation, job->key, dxil);
    if (LoadCached(job->cache_path, job->key, {mod_directory_, directory_}, binary_out,
                   files_out, dxil ? kDxilCacheMagic : 0)) {
      std::string mismatch =
          CheckSignatures(translation.shader(), translation.modification(), dxbc, binary_out);
      if (mismatch.empty()) {
        if (load_start) {
          perf_trace::AddShaderWork(perf_trace::ShaderWork::kModCacheLoad,
                                    perf_trace::Now() - load_start);
        }
        REXGPU_INFO("Shader override {}{}{} loaded from the {}cache for modification {:016X}",
                    name, mod.empty() ? "" : " with ", mod, dxil ? "DXIL " : "",
                    translation.modification());
        return true;
      }
    }
    files_out.clear();
  }

  if (job_out) {
    // For a worker (shader_override_async).
    job->dxbc = dxbc;
    *job_out = std::move(job);
    return false;
  }
  return RunCompile(*job, dxbc, binary_out, files_out, false);
}

bool ShaderOverrides::RunCompile(const CompileJob& job, const std::vector<uint8_t>& dxbc,
                                 std::vector<uint8_t>& binary_out,
                                 std::vector<Dependency>& files_out, bool on_worker) const {
  const std::string& name = job.name;
  const std::string& mod = job.mod;
  std::vector<D3D_SHADER_MACRO> defines;
  for (const auto& define : job.defines) {
    defines.push_back({define.first.c_str(), define.second.c_str()});
  }
  defines.push_back({nullptr, nullptr});

  OverrideInclude include({mod_directory_, directory_});
  ID3DBlob* code = nullptr;
  ID3DBlob* messages = nullptr;
  const bool vertex = job.shader->type() == xenos::ShaderType::kVertex;
  auto start = std::chrono::steady_clock::now();
  HRESULT result = E_FAIL;
  std::vector<uint8_t> dxil_binary;
  std::string dxil_messages;
  if (job.dxil) {
    // The DXIL world: DXC with IEEE strictness, as FXC's flags, or relaxed
    // (native_shader_dxil_relaxed): no strictness, and precise defined away.
    std::vector<std::pair<std::string, std::string>> dxil_defines = job.defines;
    if (dxil_relaxed_) {
      dxil_defines.emplace_back("precise", "");
    }
    result = dxil_compiler_->Compile(job.source, name, vertex ? kDxilVertexTarget : kDxilTarget,
                                     dxil_defines, &include, !dxil_relaxed_, dxil_binary,
                                     dxil_messages)
                 ? S_OK
                 : E_FAIL;
  } else {
    result = pD3DCompile(d3d_compile_)(job.source.data(), job.source.size(), name.c_str(),
                                       defines.data(), &include, "main",
                                       vertex ? kVertexTarget : kTarget, kCompileFlags, 0, &code,
                                       &messages);
  }
  auto elapsed = std::chrono::steady_clock::now() - start;
  double milliseconds = std::chrono::duration<double, std::milli>(elapsed).count();
  if (on_worker || perf_trace::shader_work_for_draw) {
    perf_trace::AddShaderWork(on_worker ? perf_trace::ShaderWork::kModCompileWorker
                                        : perf_trace::ShaderWork::kModCompile,
                              uint64_t(std::chrono::duration_cast<std::chrono::nanoseconds>(elapsed)
                                           .count()));
  }
  // Every file read once, also of a failed compile (hot reload watches them).
  for (const auto& read : include.read()) {
    auto same = [&read](const Dependency& file) { return file.path == read.path; };
    if (std::find_if(files_out.begin(), files_out.end(), same) == files_out.end()) {
      files_out.push_back({read.name, read.path, read.hash});
    }
  }
  std::string message_text = std::move(dxil_messages);
  if (messages) {
    message_text.assign(static_cast<const char*>(messages->GetBufferPointer()),
                        messages->GetBufferSize());
    messages->Release();
  }
  const char* compiler = job.dxil ? "DXC" : "FXC";
  if (FAILED(result) || (!job.dxil && !code)) {
    REXGPU_ERROR("Shader override {}: {} failed (0x{:08X}):\n{}", name, compiler,
                 uint32_t(result), message_text);
    if (code) {
      code->Release();
    }
    return false;
  }
  if (job.dxil) {
    binary_out = std::move(dxil_binary);
  } else {
    const uint8_t* bytes = static_cast<const uint8_t*>(code->GetBufferPointer());
    binary_out.assign(bytes, bytes + code->GetBufferSize());
    code->Release();
  }
  if (!message_text.empty()) {
    REXGPU_WARN("Shader override {}: {} warnings:\n{}", name, compiler, message_text);
  }
  std::string mismatch = CheckSignatures(*job.shader, job.modification, dxbc, binary_out);
  if (!mismatch.empty()) {
    REXGPU_ERROR("Shader override {}: {}", name, mismatch);
    return false;
  }
  REXGPU_INFO("Shader override {}{}{} compiled by {} for modification {:016X} in {:.1f} ms{}",
              name, mod.empty() ? "" : " with ", mod, compiler, job.modification, milliseconds,
              on_worker ? " on a worker" : "");
  if (!job.cache_path.empty()) {
    StoreCached(job.cache_path, job.key, files_out, binary_out, job.dxil ? kDxilCacheMagic : 0);
  }
  return true;
}

bool ShaderOverrides::CompileProgram(
    const std::string& source, const std::string& name, const std::string& entry,
    const char* target, uint32_t flags,
    const std::vector<std::pair<std::string, std::string>>& defines,
    const std::filesystem::path& directory, const char* library_name, std::string_view library,
    std::vector<uint8_t>& binary_out, std::vector<Dependency>& files_out) const {
  files_out.clear();
  uint64_t key = 0;
  std::filesystem::path cache_path;
  if (!cache_directory_.empty()) {
    XXH3_state_t state;
    XXH3_64bits_reset(&state);
    uint64_t header[] = {kCacheVersion, compiler_id_, HashBytes(library.data(), library.size()),
                         flags};
    XXH3_64bits_update(&state, header, sizeof(header));
    // NUL-terminated, so the strings can't run into each other.
    for (const std::string* text : {&source, &entry}) {
      XXH3_64bits_update(&state, text->c_str(), text->size() + 1);
    }
    XXH3_64bits_update(&state, target, std::strlen(target) + 1);
    for (const auto& define : defines) {
      XXH3_64bits_update(&state, define.first.c_str(), define.first.size() + 1);
      XXH3_64bits_update(&state, define.second.c_str(), define.second.size() + 1);
    }
    key = XXH3_64bits_digest(&state);
    cache_path = cache_directory_ / fmt::format("pass_{:016X}_{:016X}.dxbc",
                                                HashBytes(name.data(), name.size()), key);
    if (LoadCached(cache_path, key, {directory}, binary_out, files_out)) {
      REXGPU_INFO("Post pass {} ({}) loaded from the cache", name, entry);
      return true;
    }
    files_out.clear();
  }

  std::vector<D3D_SHADER_MACRO> macros;
  for (const auto& define : defines) {
    macros.push_back({define.first.c_str(), define.second.c_str()});
  }
  macros.push_back({nullptr, nullptr});
  OverrideInclude include({directory}, library_name, library);
  ID3DBlob* code = nullptr;
  ID3DBlob* messages = nullptr;
  auto start = std::chrono::steady_clock::now();
  HRESULT result =
      pD3DCompile(d3d_compile_)(source.data(), source.size(), name.c_str(), macros.data(),
                                &include, entry.c_str(), target, flags, 0, &code, &messages);
  auto elapsed = std::chrono::steady_clock::now() - start;
  double milliseconds = std::chrono::duration<double, std::milli>(elapsed).count();
  perf_trace::AddShaderWork(
      perf_trace::ShaderWork::kPassCompile,
      uint64_t(std::chrono::duration_cast<std::chrono::nanoseconds>(elapsed).count()));
  for (const auto& read : include.read()) {
    auto same = [&read](const Dependency& file) { return file.path == read.path; };
    if (std::find_if(files_out.begin(), files_out.end(), same) == files_out.end()) {
      files_out.push_back({read.name, read.path, read.hash});
    }
  }
  std::string message_text;
  if (messages) {
    message_text.assign(static_cast<const char*>(messages->GetBufferPointer()),
                        messages->GetBufferSize());
    messages->Release();
  }
  if (FAILED(result) || !code) {
    REXGPU_ERROR("Post pass {} ({}): FXC failed (0x{:08X}):\n{}", name, entry, uint32_t(result),
                 message_text);
    if (code) {
      code->Release();
    }
    return false;
  }
  const uint8_t* bytes = static_cast<const uint8_t*>(code->GetBufferPointer());
  binary_out.assign(bytes, bytes + code->GetBufferSize());
  code->Release();
  if (!message_text.empty()) {
    REXGPU_WARN("Post pass {} ({}): FXC warnings:\n{}", name, entry, message_text);
  }
  REXGPU_INFO("Post pass {} ({}) compiled in {:.1f} ms", name, entry, milliseconds);
  if (!cache_path.empty()) {
    StoreCached(cache_path, key, files_out, binary_out);
  }
  return true;
}

ShaderOverrides::Outcome ShaderOverrides::Build(const D3D12Shader::D3D12Translation& translation,
                                                const std::vector<uint8_t>& dxbc,
                                                std::vector<uint8_t>& binary_out,
                                                std::vector<Dependency>& files_out,
                                                std::unique_ptr<CompileJob>* job_out, bool dxil) {
  Shader& shader = translation.shader();
  if (shader.type() == xenos::ShaderType::kVertex) {
    return BuildVertex(translation, dxbc, binary_out, files_out, job_out, dxil);
  }
  uint64_t hash = shader.ucode_data_hash();
  Modification modification(translation.modification());
  // native_plain: outside the passes of the shader's manifest entry. In the
  // DXIL world such a translation takes its generated HLSL without a mod.
  bool disabled = modification.pixel.hlsl_override_disabled || modification.pixel.native_plain;
  const bool plain = dxil && disabled;
  if (plain) {
    disabled = false;
  }
  const native_shader_contract::PixelEntry* entry = plain ? nullptr : NativeEntry(translation);
  // A replacement entry takes the place of the game shader's HLSL.
  const bool replacement = entry && !entry->shader.empty();
  const std::string& dump_path = dxil ? std::string() : REXCVAR_GET(dump_shaders);

  // A hand-written override, for this modification or for all.
  std::filesystem::path path;
  if (!replacement && pixel_shaders_.find(hash) != pixel_shaders_.end()) {
    std::error_code error;
    path = directory_ / fmt::format("shader_{:016X}_{:016X}.ps.hlsl", hash, modification.value);
    if (!std::filesystem::exists(path, error)) {
      path = directory_ / fmt::format("shader_{:016X}.ps.hlsl", hash);
      if (!std::filesystem::exists(path, error)) {
        path.clear();
      }
    }
  }
  // A mod hooks into the generated HLSL (or into the override file): the
  // manifest entry's, or the classic one of the hash.
  std::string mod;
  if (entry) {
    mod = replacement ? entry->shader : entry->hooks;
  } else if (!plain && mod_shaders_.find(hash) != mod_shaders_.end()) {
    mod = fmt::format("shader_{:016X}.mod.hlsli", hash);
  }
  bool use_generated = use_generated_ || !mod.empty() || dxil;
  bool generate = path.empty() && !disabled && (use_generated || !generate_path_.empty());
  if (path.empty() && !generate && dump_path.empty()) {
    return Outcome::kNone;
  }

  std::string contract = BuildContract(translation, entry);
  if (!dump_path.empty()) {
    std::filesystem::path dump_directory(dump_path);
    std::error_code error;
    std::filesystem::create_directories(dump_directory, error);
    std::ofstream dump(dump_directory / fmt::format("shader_{:016X}_{:016X}.ps.contract.hlsli",
                                                    hash, modification.value),
                       std::ios::binary);
    dump << contract << "\n// Guest ucode:\n";
    std::istringstream ucode(shader.ucode_disassembly());
    for (std::string ucode_line; std::getline(ucode, ucode_line);) {
      dump << "// " << ucode_line << '\n';
    }
  }
  if (disabled || (path.empty() && !generate)) {
    return Outcome::kNone;
  }
  if (modification.pixel.depth_stencil_mode ==
          Modification::DepthStencilMode::kFloat24Truncating ||
      modification.pixel.depth_stencil_mode == Modification::DepthStencilMode::kFloat24Rounding ||
      shader.memexport_eM_written()) {
    REXGPU_WARN(
        "Shader override {:016X}: modification {:016X} uses float24 depth conversion or "
        "memexport, which overrides don't support; keeping the translation",
        hash, modification.value);
    return Outcome::kNone;
  }

  std::string text, name;
  if (replacement) {
    // The replacement file alone, included as a mod is: no game HLSL.
    std::string missing = CheckInputs(translation, *entry);
    if (!missing.empty()) {
      REXGPU_ERROR("Native shader contract: replacement {} of {:016X} modification {:016X}: {}",
                   entry->shader, hash, modification.value, missing);
      return Outcome::kFailed;
    }
    name = (mod_directory_ / entry->shader).generic_string();
  } else if (!path.empty()) {
    if (!ReadFile(path, text)) {
      REXGPU_ERROR("Shader override {}: cannot read the file", path.string());
      return Outcome::kNone;
    }
    name = path.generic_string();
  } else {
    // HLSL doing the operations of the DXBC translation.
    HlslShaderTranslator translator;
    HlslShaderTranslator::Translation generated(shader, modification.value);
    if (!translator.TranslateAnalyzedShader(generated)) {
      REXGPU_WARN("Shader override {:016X}: no HLSL generated for modification {:016X}", hash,
                  modification.value);
      return Outcome::kNone;
    }
    text = generated.GetTranslatedBinaryString();
    std::string file_name = fmt::format("shader_{:016X}_{:016X}.ps.hlsl", hash, modification.value);
    if (!generate_path_.empty()) {
      std::filesystem::path directory(generate_path_);
      std::error_code error;
      std::filesystem::create_directories(directory, error);
      std::ofstream(directory / file_name, std::ios::binary) << text;
      name = (directory / file_name).generic_string();
    } else {
      name = "generated/" + file_name;
    }
    if (!use_generated) {
      return Outcome::kNone;
    }
  }
  files_out.clear();
  std::unique_ptr<CompileJob> job;
  bool compiled = Compile(translation, dxbc, contract, text, name, mod,
                          entry ? &entry->params : nullptr, binary_out, files_out,
                          job_out ? &job : nullptr, dxil);
  if (job) {
    *job_out = std::move(job);
    return Outcome::kQueued;
  }
  if (!path.empty()) {
    files_out.push_back({path.filename().string(), path, HashBytes(text.data(), text.size())});
  }
  return compiled ? Outcome::kCompiled : Outcome::kFailed;
}

const native_shader_contract::VertexEntry* ShaderOverrides::NativeVertexEntry(
    const D3D12Shader::D3D12Translation& translation) const {
  Modification modification(translation.modification());
  if (!native_ || modification.vertex.native_plain || modification.vertex.native_classic) {
    return nullptr;
  }
  return native_->FindVertex(translation.shader().ucode_data_hash());
}

bool ShaderOverrides::GeneratesVertex(const D3D12Shader::D3D12Translation& translation) const {
  Modification modification(translation.modification());
  if (!native_ || translation.shader().type() != xenos::ShaderType::kVertex ||
      modification.vertex.native_plain || modification.vertex.native_classic ||
      modification.vertex.host_vertex_shader_type != Shader::HostVertexShaderType::kVertex ||
      translation.shader().memexport_eM_written()) {
    return false;
  }
  return native_vertex_all_ || native_->FindVertex(translation.shader().ucode_data_hash());
}

ShaderOverrides::Outcome ShaderOverrides::BuildVertex(
    const D3D12Shader::D3D12Translation& translation, const std::vector<uint8_t>& dxbc,
    std::vector<uint8_t>& binary_out, std::vector<Dependency>& files_out,
    std::unique_ptr<CompileJob>* job_out, bool dxil) {
  if (dxil) {
    // The DXIL world: every vertex shader the generator takes, the entry's
    // hooks where it has one (NativeVertexEntry).
    Modification vertex_modification(translation.modification());
    if (translation.shader().type() != xenos::ShaderType::kVertex ||
        vertex_modification.vertex.host_vertex_shader_type !=
            Shader::HostVertexShaderType::kVertex ||
        translation.shader().memexport_eM_written()) {
      return Outcome::kNone;
    }
  } else if (!GeneratesVertex(translation)) {
    return Outcome::kNone;
  }
  Shader& shader = translation.shader();
  const uint64_t hash = shader.ucode_data_hash();
  const uint64_t modification = translation.modification();
  const native_shader_contract::VertexEntry* entry = NativeVertexEntry(translation);
  std::string contract = BuildContract(translation, nullptr, entry);
  // The vertex shader's HLSL doing the operations of its DXBC translation, with
  // the entry's hooks.
  HlslShaderTranslator translator;
  HlslShaderTranslator::Translation generated(shader, modification);
  if (!translator.TranslateAnalyzedShader(generated)) {
    REXGPU_WARN("Native shader contract: vertex shader {:016X}: no HLSL generated for "
                "modification {:016X}",
                hash, modification);
    return Outcome::kFailed;
  }
  std::string text = generated.GetTranslatedBinaryString();
  std::string file_name = fmt::format("vertex_{:016X}_{:016X}.vs.hlsl", hash, modification);
  std::string name;
  if (!generate_path_.empty()) {
    std::filesystem::path directory(generate_path_);
    std::error_code error;
    std::filesystem::create_directories(directory, error);
    std::ofstream(directory / file_name, std::ios::binary) << text;
    name = (directory / file_name).generic_string();
  } else {
    name = "generated/" + file_name;
  }
  files_out.clear();
  std::unique_ptr<CompileJob> job;
  bool compiled = Compile(translation, dxbc, contract, text, name, entry ? entry->hooks : "",
                          entry ? &entry->params : nullptr, binary_out, files_out,
                          job_out ? &job : nullptr, dxil);
  if (job) {
    *job_out = std::move(job);
    return Outcome::kQueued;
  }
  return compiled ? Outcome::kCompiled : Outcome::kFailed;
}

void ShaderOverrides::Record(const D3D12Shader::D3D12Translation& translation,
                             std::vector<uint8_t> dxbc, const std::vector<Dependency>& files,
                             bool overridden) {
  Entry& entry = entries_[&translation];
  entry.dxbc = std::move(dxbc);
  entry.overridden = overridden;
  entry.files.clear();
  for (const Dependency& file : files) {
    entry.files.push_back(file.path);
    auto [state, inserted] = files_.try_emplace(file.path);
    if (inserted) {
      // As read for the compile: a change since then shows at the next poll.
      std::error_code error;
      state->second.exists = true;
      state->second.time = std::filesystem::last_write_time(file.path, error);
      state->second.size = std::filesystem::file_size(file.path, error);
      state->second.hash = file.hash;
    }
  }
}

std::string ShaderOverrides::CheckSignatures(const Shader& shader, uint64_t modification,
                                             const std::vector<uint8_t>& dxbc,
                                             const std::vector<uint8_t>& binary) const {
  if (!dxbc.empty()) {
    return CompareSignatures(dxbc, binary);
  }
  std::vector<SignatureElement> inputs, outputs;
  if (shader.type() == xenos::ShaderType::kVertex) {
    ExpectedVertexSignatures(Modification(modification), inputs, outputs);
  } else {
    ExpectedPixelSignatures(shader, Modification(modification), inputs, outputs);
  }
  return CompareExpectedSignatures(inputs, outputs, binary);
}

bool ShaderOverrides::TranslateEntry(D3D12Shader::D3D12Translation& translation,
                                     ShaderCompileQueue* queue) {
  Shader& shader = translation.shader();
  // A vertex shader's translation takes its generated HLSL with an entry, or
  // with native_shader_contract_vertex_all (docs/analysis/shader-contract.md 9).
  const bool vertex = shader.type() == xenos::ShaderType::kVertex;
  // In the DXIL world every translation keeps the DXBC translator's binary for
  // the DXBC world's pipelines, and Apply builds both.
  if (dxil()) {
    return false;
  }
  if (!native_ || (vertex ? !GeneratesVertex(translation)
                          : shader.type() != xenos::ShaderType::kPixel ||
                                !NativeEntry(translation))) {
    return false;
  }
  Modification modification(translation.modification());
  if (!vertex && (modification.pixel.depth_stencil_mode ==
                      Modification::DepthStencilMode::kFloat24Truncating ||
                  modification.pixel.depth_stencil_mode ==
                      Modification::DepthStencilMode::kFloat24Rounding ||
                  shader.memexport_eM_written())) {
    // Not supported by overrides: the DXBC translation (Build keeps it too).
    return false;
  }
  // The game shader's HLSL, with the bindings, into the translation itself
  // (translated and valid; its binary the HLSL text until the compile replaces
  // it). On any failure the caller translates it with the DXBC translator,
  // which sets every field again.
  auto fallback = [&](const char* reason) {
    uint32_t count = entry_fallbacks_.fetch_add(1, std::memory_order_relaxed) + 1;
    REXGPU_WARN("Native shader contract: {} {:016X} modification {:016X}: DXBC fallback {} "
                "({})",
                vertex ? "vertex shader" : "entry", shader.ucode_data_hash(), modification.value,
                count, reason);
    return false;
  };
  // The generation counts as the pixel shader's translation in the shader
  // work on the draw path (the compile or cache load counts in Compile).
  const uint64_t translate_start = perf_trace::shader_work_for_draw ? perf_trace::ZoneStart() : 0;
  HlslShaderTranslator translator;
  bool generated = translator.TranslateAnalyzedShader(translation);
  if (translate_start) {
    perf_trace::AddShaderWork(vertex ? perf_trace::ShaderWork::kVertexTranslation
                                     : perf_trace::ShaderWork::kPixelTranslation,
                              perf_trace::Now() - translate_start);
  }
  if (!generated) {
    return fallback(vertex ? "no HLSL: an unsupported instruction or export"
                           : "no HLSL: an unsupported fetch");
  }
  auto& dxbc_shader = static_cast<D3D12Shader&>(shader);
  if (!dxbc_shader.SetBindingsOnce(translator.texture_bindings(), translator.sampler_bindings())) {
    REXGPU_ERROR("Native shader contract: {:016X}: the bindings of the HLSL differ from those an "
                 "earlier translation stored",
                 shader.ucode_data_hash());
    return fallback("the bindings differ");
  }
  std::vector<uint8_t> binary;
  std::vector<Dependency> files;
  std::unique_ptr<CompileJob> job;
  Outcome outcome =
      Build(translation, std::vector<uint8_t>(), binary, files, queue ? &job : nullptr);
  if (outcome == Outcome::kQueued) {
    // Not in the cache: no FXC on the thread that issues the draw. The caller's
    // DXBC translation draws until a worker's compile is swapped in, and Apply
    // queues that compile with the DXBC for its signature check. Its source,
    // so its cache file, is this one's: the contract and the HLSL come from
    // the shader's analysis and bindings, not from the DXBC translation.
    uint32_t count = entry_placeholders_.fetch_add(1, std::memory_order_relaxed) + 1;
    REXGPU_INFO("Native shader contract: {} {:016X} modification {:016X} is not in the cache: "
                "its DXBC translation until a worker compiles it ({} so far)",
                vertex ? "vertex shader" : "entry", shader.ucode_data_hash(), modification.value,
                count);
    return false;
  }
  if (outcome != Outcome::kCompiled) {
    return fallback("the compile or its signature check failed");
  }
  translation.ReplaceTranslatedBinary(std::move(binary));
  if (hot_reload_) {
    std::lock_guard<std::mutex> lock(entries_mutex_);
    Record(translation, std::vector<uint8_t>(), files, true);
  }
  return true;
}

void ShaderOverrides::MarkPrecise(D3D12Shader::D3D12Translation& translation) const {
  xenos::ShaderType type = translation.shader().type();
  if (!native_ || !ab_precise_ || !translation.is_valid() ||
      (type != xenos::ShaderType::kVertex && type != xenos::ShaderType::kPixel)) {
    return;
  }
  std::vector<uint8_t> binary = translation.translated_binary();
  if (!::rex::graphics::d3d12::MarkPrecise(binary)) {
    REXGPU_ERROR("native_shader_contract_ab_precise: {:016X}: the DXBC translation cannot be read",
                 translation.shader().ucode_data_hash());
    return;
  }
  translation.ReplaceTranslatedBinary(std::move(binary));
}

void ShaderOverrides::CheckBindings(const D3D12Shader::D3D12Translation& translation) {
  const auto& shader = static_cast<const D3D12Shader&>(translation.shader());
  // Pixel shaders, and vertex shaders of the host vertex stage (the generator
  // takes no domain shader).
  const bool vertex = shader.type() == xenos::ShaderType::kVertex;
  if (vertex) {
    if (Modification(translation.modification()).vertex.host_vertex_shader_type !=
        Shader::HostVertexShaderType::kVertex) {
      return;
    }
  } else if (shader.type() != xenos::ShaderType::kPixel) {
    return;
  }
  if (!translation.is_valid()) {
    return;
  }
  HlslShaderTranslator translator;
  HlslShaderTranslator::Translation generated(translation.shader(), translation.modification());
  bool generated_valid = translator.TranslateAnalyzedShader(generated);
  bool matches = generated_valid &&
                 shader.HasBindings(translator.texture_bindings(), translator.sampler_bindings());
  const char* kind = vertex ? "vertex" : "pixel";
  CheckCounts& counts = checked_[vertex ? 1 : 0];
  std::lock_guard<std::mutex> lock(check_mutex_);
  bool first = counts.shaders.insert(shader.ucode_data_hash()).second;
  if (!generated_valid) {
    // getWeights, getCompTexLOD, getBCF or memexport, or in a vertex shader
    // kill or getGradients (the generator logged which): no HLSL to compare,
    // and an entry of this shader would take the DXBC translation.
    ++counts.without_hlsl;
    if (first) {
      REXGPU_INFO("Native shader contract check: {} shader {:016X}: no HLSL", kind,
                  shader.ucode_data_hash());
    }
    return;
  }
  ++counts.bindings;
  if (!matches) {
    ++counts.mismatches;
    REXGPU_ERROR("Native shader contract check: {} shader {:016X} modification {:016X}: the "
                 "bindings of the HLSL differ from the DXBC translation's ({}; {} mismatches)",
                 kind, shader.ucode_data_hash(), translation.modification(),
                 shader.DescribeBindingDifference(translator.texture_bindings(),
                                                  translator.sampler_bindings()),
                 counts.mismatches);
  } else if (first) {
    REXGPU_INFO("Native shader contract check: {} shader {:016X}: the bindings of its DXBC "
                "translation ({} textures, {} samplers; {} shaders, {} translations compared, {} "
                "mismatches, {} without HLSL)",
                kind, shader.ucode_data_hash(), translator.texture_bindings().size(),
                translator.sampler_bindings().size(), counts.shaders.size(), counts.bindings,
                counts.mismatches, counts.without_hlsl);
  }
}

void ShaderOverrides::CheckEntry(const D3D12Shader::D3D12Translation& translation,
                                 const std::vector<uint8_t>& dxbc) {
  const auto& shader = static_cast<const D3D12Shader&>(translation.shader());
  std::string mismatch = CompareSignatures(dxbc, translation.translated_binary());
  std::vector<SignatureElement> inputs, outputs;
  const bool vertex = shader.type() == xenos::ShaderType::kVertex;
  if (vertex) {
    ExpectedVertexSignatures(Modification(translation.modification()), inputs, outputs);
  } else {
    ExpectedPixelSignatures(shader, Modification(translation.modification()), inputs, outputs);
  }
  std::string expected = CompareExpectedSignatures(inputs, outputs, dxbc);
  if (!expected.empty()) {
    expected = "the DXBC translation against the expected: " + expected;
  }
  // The DXBC translation's PostTranslation compared its bindings with those
  // the entry stored, and counts a mismatch.
  if (uint32_t binding_mismatches = shader.binding_mismatches()) {
    expected += fmt::format("{}{} DXBC translations of the shader with other bindings",
                            expected.empty() ? "" : "; ", binding_mismatches);
  }
  uint32_t count = checked_entries_.fetch_add(1, std::memory_order_relaxed) + 1;
  const char* kind = vertex ? "vertex shader" : "entry";
  if (!mismatch.empty() || !expected.empty()) {
    REXGPU_ERROR("Native shader contract check: {} {:016X} modification {:016X}: {}{}{}", kind,
                 shader.ucode_data_hash(), translation.modification(), mismatch,
                 mismatch.empty() || expected.empty() ? "" : "; ", expected);
    return;
  }
  REXGPU_INFO("Native shader contract check: {} {:016X} modification {:016X} (check {}): the "
              "signatures and bindings of its DXBC translation",
              kind, shader.ucode_data_hash(), translation.modification(), count);
}

void ShaderOverrides::ApplyDxil(D3D12Shader::D3D12Translation& translation,
                                ShaderCompileQueue* queue) {
  xenos::ShaderType type = translation.shader().type();
  if (type != xenos::ShaderType::kVertex && type != xenos::ShaderType::kPixel) {
    return;
  }
  std::vector<uint8_t> binary;
  std::vector<Dependency> files;
  std::unique_ptr<CompileJob> job;
  Outcome outcome = Build(translation, translation.translated_binary(), binary, files,
                          queue ? &job : nullptr, true);
  if (outcome == Outcome::kQueued) {
    // Its pipelines stay in the DXBC world until both of their shaders have
    // DXIL (PipelineCache::SwapCompiledMods).
    std::shared_ptr<CompileJob> shared_job(std::move(job));
    queue->Push(
        &translation,
        [this, shared_job]() {
          std::vector<uint8_t> compiled;
          std::vector<Dependency> compiled_files;
          if (!RunCompile(*shared_job, shared_job->dxbc, compiled, compiled_files, true)) {
            compiled.clear();
          }
          return compiled;
        },
        true);
    return;
  }
  if (outcome == Outcome::kCompiled) {
    translation.SetDxilBinary(std::move(binary));
  }
}

void ShaderOverrides::Apply(D3D12Shader::D3D12Translation& translation,
                            ShaderCompileQueue* queue) {
  if (!translation.is_valid()) {
    return;
  }
  if (dxil()) {
    ApplyDxil(translation, queue);
  }
  if (translation.shader().type() == xenos::ShaderType::kVertex) {
    // A vertex shader whose generated HLSL the cache did not hold.
    if (!GeneratesVertex(translation)) {
      return;
    }
  } else if (translation.shader().type() != xenos::ShaderType::kPixel) {
    return;
  }
  std::vector<uint8_t> binary;
  std::vector<Dependency> files;
  std::unique_ptr<CompileJob> job;
  Outcome outcome = Build(translation, translation.translated_binary(), binary, files,
                          queue ? &job : nullptr);
  if (outcome == Outcome::kQueued) {
    // The translation keeps its DXBC until the pipeline cache swaps the
    // compiled binary in (PipelineCache::SwapCompiledMods).
    std::shared_ptr<CompileJob> shared_job(std::move(job));
    queue->Push(&translation, [this, shared_job]() {
      std::vector<uint8_t> compiled;
      std::vector<Dependency> compiled_files;
      if (!RunCompile(*shared_job, shared_job->dxbc, compiled, compiled_files, true)) {
        compiled.clear();
      }
      return compiled;
    });
    return;
  }
  if (hot_reload_ && outcome != Outcome::kNone) {
    std::lock_guard<std::mutex> lock(entries_mutex_);
    Record(translation, translation.translated_binary(), files, outcome == Outcome::kCompiled);
  }
  if (outcome == Outcome::kCompiled) {
    translation.ReplaceTranslatedBinary(std::move(binary));
  }
}

bool ShaderOverrides::RefreshFileState(const std::filesystem::path& path, FileState& state,
                                       std::string* text_out) {
  std::error_code error;
  FileState current;
  current.time = std::filesystem::last_write_time(path, error);
  current.exists = !error;
  current.size = current.exists ? std::filesystem::file_size(path, error) : 0;
  if (current.exists == state.exists && current.time == state.time &&
      current.size == state.size) {
    return false;
  }
  std::string text;
  if (current.exists && ReadFile(path, text)) {
    current.hash = HashBytes(text.data(), text.size());
  } else {
    current.exists = false;
  }
  // Saved again with the same content: no change.
  bool changed = current.exists != state.exists || current.hash != state.hash;
  state = current;
  if (changed && current.exists && text_out) {
    *text_out = std::move(text);
  }
  return changed;
}

bool ShaderOverrides::PollChanges() {
  if (!hot_reload_) {
    return false;
  }
  auto now = std::chrono::steady_clock::now();
  if (now - last_poll_ < kPollInterval) {
    return false;
  }
  last_poll_ = now;
  changed_shaders_.clear();
  changed_files_.clear();
  defines_changed_ = false;

  // Defines saved in kDefinesFile, as with shader_mod_set (removed lines keep
  // their values).
  if (!mod_directory_.empty()) {
    std::string text;
    if (RefreshFileState(mod_directory_ / kDefinesFile, defines_file_, &text)) {
      text = StripComments(text);
      if (!ParseDefines(text, "; \t\r\n").empty()) {
        REXGPU_INFO("Shader hot reload: {} changed", kDefinesFile);
        SetDefines(text);
      }
    }
  }

  // Defines from shader_mod_set that need a recompile.
  {
    std::lock_guard<std::mutex> lock(knob_mutex_);
    if (!pending_defines_.empty()) {
      for (const auto& define : pending_defines_) {
        SetDefine(mod_defines_, define.first, define.second);
      }
      pending_defines_.clear();
      RebuildCompileDefines();
      defines_changed_ = true;
    }
  }

  // Override and mod files that appeared or disappeared.
  std::unordered_set<uint64_t, rex::IdentityHasher<uint64_t>> pixel_shaders, mod_shaders;
  ScanShaderFiles(directory_, ".ps.hlsl", pixel_shaders);
  ScanShaderFiles(mod_directory_, ".mod.hlsli", mod_shaders);
  auto difference = [this](const auto& from, const auto& to) {
    for (uint64_t hash : from) {
      if (to.find(hash) == to.end()) {
        changed_shaders_.insert(hash);
      }
    }
  };
  difference(pixel_shaders, pixel_shaders_);
  difference(pixel_shaders_, pixel_shaders);
  difference(mod_shaders, mod_shaders_);
  difference(mod_shaders_, mod_shaders);
  pixel_shaders_ = std::move(pixel_shaders);
  mod_shaders_ = std::move(mod_shaders);
  uses_reactive_mark_ = ScanReactiveMark({&directory_, &mod_directory_});

  // The files the overrides were compiled from.
  {
    std::lock_guard<std::mutex> lock(entries_mutex_);
    for (auto& [path, state] : files_) {
      if (RefreshFileState(path, state)) {
        changed_files_.insert(path);
      }
    }
  }
  if (!defines_changed_ && changed_shaders_.empty() && changed_files_.empty()) {
    return false;
  }
  REXGPU_INFO("Shader hot reload: {} files changed, {} shaders gained or lost an override{}",
              changed_files_.size(), changed_shaders_.size(),
              defines_changed_ ? ", defines changed" : "");
  return true;
}

bool ShaderOverrides::NeedsReload(const D3D12Shader::D3D12Translation& translation) const {
  Modification modification(translation.modification());
  if (modification.pixel.hlsl_override_disabled || modification.pixel.native_plain) {
    return false;
  }
  uint64_t hash = translation.shader().ucode_data_hash();
  if (changed_shaders_.find(hash) != changed_shaders_.end()) {
    return true;
  }
  std::lock_guard<std::mutex> lock(entries_mutex_);
  auto entry = entries_.find(&translation);
  if (entry == entries_.end()) {
    return false;
  }
  if (defines_changed_) {
    return true;
  }
  for (const std::filesystem::path& path : entry->second.files) {
    if (changed_files_.find(path) != changed_files_.end()) {
      return true;
    }
  }
  return false;
}

bool ShaderOverrides::Reload(D3D12Shader::D3D12Translation& translation) {
  if (translation.shader().type() != xenos::ShaderType::kPixel || !translation.is_valid()) {
    return false;
  }
  std::vector<uint8_t> dxbc;
  bool overridden = false;
  {
    std::lock_guard<std::mutex> lock(entries_mutex_);
    auto entry = entries_.find(&translation);
    if (entry != entries_.end()) {
      dxbc = entry->second.dxbc;
      overridden = entry->second.overridden;
    } else {
      dxbc = translation.translated_binary();
    }
  }
  std::vector<uint8_t> binary;
  std::vector<Dependency> files;
  Outcome outcome = Build(translation, dxbc, binary, files);
  std::lock_guard<std::mutex> lock(entries_mutex_);
  switch (outcome) {
    case Outcome::kCompiled: {
      bool changed = binary != translation.translated_binary();
      Record(translation, std::move(dxbc), files, true);
      translation.ReplaceTranslatedBinary(std::move(binary));
      return changed;
    }
    case Outcome::kFailed:
      // The last binary that worked stays until the files are fixed.
      Record(translation, std::move(dxbc), files, overridden);
      return false;
    case Outcome::kNone:
    default:
      if (overridden && dxbc.empty()) {
        // An entry translated without the DXBC translator: its override stays
        // until a restart translates the shader again.
        REXGPU_WARN("Shader hot reload: {:016X} lost its entry or mod; its override stays until "
                    "a restart",
                    translation.shader().ucode_data_hash());
        return false;
      }
      entries_.erase(&translation);
      if (overridden) {
        translation.ReplaceTranslatedBinary(std::move(dxbc));
        return true;
      }
      return false;
  }
}

void ShaderOverrides::EndReload() {
  changed_shaders_.clear();
  changed_files_.clear();
  defines_changed_ = false;
}

