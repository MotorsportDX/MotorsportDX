uint32_t ReadU32(const std::vector<uint8_t>& data, size_t offset) {
  uint32_t value = 0;
  if (offset + sizeof(value) <= data.size()) {
    std::memcpy(&value, data.data() + offset, sizeof(value));
  }
  return value;
}

constexpr uint32_t FourCC(char a, char b, char c, char d) {
  return uint32_t(uint8_t(a)) | (uint32_t(uint8_t(b)) << 8) | (uint32_t(uint8_t(c)) << 16) |
         (uint32_t(uint8_t(d)) << 24);
}

// native_shader_contract_ab_precise: the precise flags (bits 19:22 of the
// opcode token, one per component) on every instruction that writes a
// register, as FXC's IEEE strictness sets them on the generated HLSL: not on
// the declarations, which use those bits for other fields, nor on flow control,
// whose first operand is a source. The DXBC translator sets none, and the
// driver may fuse its mul and add where they are not precise, so without the
// flags the DXBC translation is not a deterministic reference for exact code
// (docs/analysis/shader-contract.md 9.7). The container is signed again. False
// if the container cannot be read.
bool MarkPrecise(std::vector<uint8_t>& dxbc) {
  if (dxbc.size() < 32 || std::memcmp(dxbc.data(), "DXBC", 4)) {
    return false;
  }
  using dxbc::Opcode;
  auto marked = [](uint32_t opcode) {
    if ((opcode >= uint32_t(Opcode::kDclResource) && opcode <= uint32_t(Opcode::kDclGlobalFlags)) ||
        // The hull shader's phases and D3D11's declarations.
        (opcode >= 113 && opcode <= 116) ||
        (opcode >= uint32_t(Opcode::kDclStream) && opcode <= 162)) {
      return false;
    }
    switch (Opcode(opcode)) {
      case Opcode::kCallC:
      case Opcode::kCase:
      case Opcode::kDiscard:
      case Opcode::kIf:
      case Opcode::kRetC:
      case Opcode::kSwitch:
      case Opcode(3):  // breakc
      case Opcode(8):  // continuec
        return false;
      default:
        return true;
    }
  };
  uint32_t chunk_count = ReadU32(dxbc, 28);
  for (uint32_t i = 0; i < chunk_count; ++i) {
    size_t chunk = ReadU32(dxbc, 32 + size_t(i) * 4);
    uint32_t fourcc = ReadU32(dxbc, chunk);
    if (fourcc != FourCC('S', 'H', 'E', 'X') && fourcc != FourCC('S', 'H', 'D', 'R')) {
      continue;
    }
    size_t program = chunk + 8;
    size_t end = program + size_t(ReadU32(dxbc, program + 4)) * 4;
    if (end > dxbc.size()) {
      return false;
    }
    for (size_t token = program + 8; token < end;) {
      uint32_t opcode_token = ReadU32(dxbc, token);
      uint32_t opcode = opcode_token & 0x7FF;
      uint32_t length;
      if (opcode == uint32_t(Opcode::kCustomData)) {
        length = ReadU32(dxbc, token + 4);
      } else {
        length = dxbc::GetOpcodeTokenInstructionLength(opcode_token);
        // The first operand follows the extended opcode tokens.
        size_t operand = token + 4;
        for (uint32_t extended = opcode_token; (extended >> 31) && operand < token + length * 4;
             operand += 4) {
          extended = ReadU32(dxbc, operand);
        }
        const size_t instruction_end = token + size_t(length) * 4;
        if (marked(opcode) && operand < instruction_end) {
          uint32_t operand_token = ReadU32(dxbc, operand);
          // A null first destination (sincos, udiv, imul): the second, as FXC.
          size_t next = operand + 4 * (1 + (operand_token >> 31));
          if (((operand_token >> 12) & 0xFF) == 13 && next < instruction_end) {
            operand_token = ReadU32(dxbc, next);
          }
          uint32_t type = (operand_token >> 12) & 0xFF;
          // Temporaries, outputs, indexable temporaries, oDepth, oMask, output
          // control points, the conservative depth outputs and the stencil
          // reference: not resources, UAVs or null.
          bool written = type == 0 || type == 2 || type == 3 || type == 12 || type == 15 ||
                         type == 26 || type == 38 || type == 39 || type == 41;
          uint32_t mask = 0;
          if ((operand_token & 3) == 1) {
            mask = 0b0001;
          } else if ((operand_token & 3) == 2 && ((operand_token >> 2) & 3) == 0) {
            mask = (operand_token >> 4) & 0xF;
          }
          // FXC marks the four components of a texture load or sample.
          if (opcode == uint32_t(Opcode::kLd) || opcode == uint32_t(Opcode::kLdMS) ||
              (opcode >= 69 && opcode <= 74)) {
            mask = 0xF;
          }
          if (written && mask) {
            opcode_token |= mask << 19;
            std::memcpy(dxbc.data() + token, &opcode_token, sizeof(opcode_token));
          }
        }
      }
      if (!length) {
        return false;
      }
      token += size_t(length) * 4;
    }
  }
  uint32_t checksum[4];
  CalculateDXBCChecksum(dxbc.data(), uint32_t(dxbc.size()), checksum);
  std::memcpy(dxbc.data() + 4, checksum, sizeof(checksum));
  return true;
}

// The ISGN/ISG1 or OSGN/OSG1 chunk of a DXBC container.
bool ParseSignature(const std::vector<uint8_t>& dxbc, bool output,
                    std::vector<SignatureElement>& elements_out) {
  elements_out.clear();
  if (dxbc.size() < 32 || std::memcmp(dxbc.data(), "DXBC", 4)) {
    return false;
  }
  uint32_t chunk_count = ReadU32(dxbc, 28);
  for (uint32_t i = 0; i < chunk_count; ++i) {
    size_t chunk = ReadU32(dxbc, 32 + size_t(i) * 4);
    uint32_t fourcc = ReadU32(dxbc, chunk);
    size_t element_size;
    size_t field_offset;
    if (fourcc == (output ? FourCC('O', 'S', 'G', 'N') : FourCC('I', 'S', 'G', 'N'))) {
      element_size = 24;
      field_offset = 0;
    } else if (fourcc == (output ? FourCC('O', 'S', 'G', '1') : FourCC('I', 'S', 'G', '1'))) {
      // Stream index first, minimum precision last.
      element_size = 32;
      field_offset = 4;
    } else {
      continue;
    }
    size_t data = chunk + 8;
    uint32_t count = ReadU32(dxbc, data);
    size_t elements = data + ReadU32(dxbc, data + 4);
    for (uint32_t j = 0; j < count; ++j) {
      size_t element = elements + size_t(j) * element_size + field_offset;
      size_t name = data + ReadU32(dxbc, element);
      SignatureElement& parsed = elements_out.emplace_back();
      while (name < dxbc.size() && dxbc[name]) {
        parsed.name.push_back(char(std::toupper(dxbc[name++])));
      }
      parsed.semantic_index = ReadU32(dxbc, element + 4);
      parsed.component_type = ReadU32(dxbc, element + 12);
      parsed.register_index = ReadU32(dxbc, element + 16);
    }
    return true;
  }
  return false;
}

const SignatureElement* FindElement(const std::vector<SignatureElement>& elements,
                                    const SignatureElement& element) {
  for (const SignatureElement& candidate : elements) {
    if (candidate.name == element.name && candidate.semantic_index == element.semantic_index) {
      return &candidate;
    }
  }
  return nullptr;
}

// The override may read fewer inputs, from the same registers (linkage with the
// vertex or geometry shader), and must write the same outputs.
std::string CompareSignatures(const std::vector<uint8_t>& translated,
                              const std::vector<uint8_t>& override_binary) {
  for (bool output : {false, true}) {
    std::vector<SignatureElement> expected, actual;
    if (!ParseSignature(translated, output, expected) ||
        !ParseSignature(override_binary, output, actual)) {
      return output ? "no output signature" : "no input signature";
    }
    for (const SignatureElement& element : actual) {
      const SignatureElement* match = FindElement(expected, element);
      if (!match || match->register_index != element.register_index ||
          match->component_type != element.component_type) {
        return fmt::format("{} {}{} in register {} is not in the translation's signature",
                           output ? "output" : "input", element.name, element.semantic_index,
                           int32_t(element.register_index));
      }
    }
    if (output) {
      for (const SignatureElement& element : expected) {
        if (!FindElement(actual, element)) {
          return fmt::format("output {}{} is missing", element.name, element.semantic_index);
        }
      }
    }
  }
  return std::string();
}

// The input and output signatures of the DXBC translation of a pixel shader
// for host render targets (DxbcShaderTranslator: StartTranslation's input
// registers, WriteInputSignature, WriteOutputSignature) from its modification
// and the ucode analysis, for an override compiled without the DXBC
// translation. Register UINT32_MAX: not a register (oMask, oDepth).
constexpr uint32_t kComponentUInt32 = 1;
constexpr uint32_t kComponentFloat32 = 3;

void ExpectedPixelSignatures(const Shader& shader, const DxbcShaderTranslator::Modification& modification,
                             std::vector<SignatureElement>& inputs_out,
                             std::vector<SignatureElement>& outputs_out) {
  inputs_out.clear();
  outputs_out.clear();
  uint32_t register_index = 0;
  uint32_t interpolators = modification.pixel.interpolator_mask;
  for (uint32_t i = 0; i < xenos::kMaxInterpolators; ++i) {
    if (interpolators & (UINT32_C(1) << i)) {
      inputs_out.push_back({"TEXCOORD", register_index, kComponentFloat32, register_index});
      ++register_index;
    }
  }
  if (modification.pixel.param_gen_point) {
    inputs_out.push_back({"XESPRITETEXCOORD", 0, kComponentFloat32, register_index++});
  }
  inputs_out.push_back({"SV_POSITION", 0, kComponentFloat32, register_index++});
  inputs_out.push_back({"SV_ISFRONTFACE", 0, kComponentUInt32, register_index++});
  uint32_t color_targets = shader.writes_color_targets();
  for (uint32_t i = 0; i < xenos::kMaxColorRenderTargets; ++i) {
    if (color_targets & (1u << i)) {
      outputs_out.push_back({"SV_TARGET", i, kComponentFloat32, i});
    }
  }
  bool force_early_depth_stencil =
      modification.pixel.depth_stencil_mode ==
          DxbcShaderTranslator::Modification::DepthStencilMode::kEarlyHint &&
      shader.implicit_early_z_write_allowed();
  if ((color_targets & 1) && !force_early_depth_stencil) {
    outputs_out.push_back({"SV_COVERAGE", 0, kComponentUInt32, UINT32_MAX});
  }
  if (shader.writes_depth()) {
    outputs_out.push_back({"SV_DEPTH", 0, kComponentFloat32, UINT32_MAX});
  }
}

// The same for the DXBC translation of a vertex shader of the host vertex stage
// (WriteInputSignature, WriteOutputSignature): the vertex index; the
// interpolators of the mask, the position, the clip and cull distances (clip
// first, four components a register, a parameter per kind and register), the
// point size.
void ExpectedVertexSignatures(const DxbcShaderTranslator::Modification& modification,
                              std::vector<SignatureElement>& inputs_out,
                              std::vector<SignatureElement>& outputs_out) {
  inputs_out.clear();
  outputs_out.clear();
  inputs_out.push_back({"SV_VERTEXID", 0, kComponentUInt32, 0});
  uint32_t register_index = 0;
  uint32_t interpolators = modification.vertex.interpolator_mask;
  for (uint32_t i = 0; i < xenos::kMaxInterpolators; ++i) {
    if (interpolators & (UINT32_C(1) << i)) {
      outputs_out.push_back({"TEXCOORD", register_index, kComponentFloat32, register_index});
      ++register_index;
    }
  }
  outputs_out.push_back({"SV_POSITION", 0, kComponentFloat32, register_index++});
  uint32_t clip_count = modification.GetVertexClipDistanceCount();
  uint32_t cull_count = modification.GetVertexCullDistanceCount();
  uint32_t clip_parameter = 0, cull_parameter = 0;
  for (uint32_t first = 0; first < clip_count + cull_count; first += 4) {
    if (first < clip_count) {
      outputs_out.push_back(
          {"SV_CLIPDISTANCE", clip_parameter++, kComponentFloat32, register_index});
    }
    if (cull_count && first + 4 > clip_count) {
      outputs_out.push_back(
          {"SV_CULLDISTANCE", cull_parameter++, kComponentFloat32, register_index});
    }
    ++register_index;
  }
  if (modification.vertex.output_point_size) {
    outputs_out.push_back({"XEPSIZE", 0, kComponentFloat32, register_index++});
  }
}

// CompareSignatures against expected signatures instead of a DXBC translation.
std::string CompareExpectedSignatures(const std::vector<SignatureElement>& expected_inputs,
                                      const std::vector<SignatureElement>& expected_outputs,
                                      const std::vector<uint8_t>& override_binary) {
  for (bool output : {false, true}) {
    const std::vector<SignatureElement>& expected = output ? expected_outputs : expected_inputs;
    std::vector<SignatureElement> actual;
    if (!ParseSignature(override_binary, output, actual)) {
      return output ? "no output signature" : "no input signature";
    }
    for (const SignatureElement& element : actual) {
      const SignatureElement* match = FindElement(expected, element);
      if (!match || match->register_index != element.register_index ||
          match->component_type != element.component_type) {
        return fmt::format("{} {}{} in register {} is not in the expected signature",
                           output ? "output" : "input", element.name, element.semantic_index,
                           int32_t(element.register_index));
      }
    }
    if (output) {
      for (const SignatureElement& element : expected) {
        if (!FindElement(actual, element)) {
          return fmt::format("output {}{} is missing", element.name, element.semantic_index);
        }
      }
    }
  }
  return std::string();
}

