uint64_t HashBytes(const void* data, size_t size) { return XXH3_64bits(data, size); }

// The steady clock in milliseconds, as e2e captures record it (captures.txt).
int64_t SteadyMilliseconds() {
  return std::chrono::duration_cast<std::chrono::milliseconds>(
             std::chrono::steady_clock::now().time_since_epoch())
      .count();
}

bool ReadFile(const std::filesystem::path& path, std::string& out) {
  std::ifstream file(path, std::ios::binary);
  if (!file) {
    return false;
  }
  out.assign(std::istreambuf_iterator<char>(file), std::istreambuf_iterator<char>());
  return true;
}

// The whole of text as a number.
bool ParseNumber(std::string_view text, double& value_out) {
  while (!text.empty() && std::isspace(uint8_t(text.front()))) text.remove_prefix(1);
  while (!text.empty() && std::isspace(uint8_t(text.back()))) text.remove_suffix(1);
  const char* end = text.data() + text.size();
  auto result = std::from_chars(text.data(), end, value_out);
  return !text.empty() && result.ec == std::errc() && result.ptr == end;
}

