bool PostPasses::IsSkipped(int32_t* variant_index_out) {
  *variant_index_out = -1;
  int32_t period = REXCVAR_GET(post_pass_ab_ms);
  if (period > 0 && ((SteadyMilliseconds() / period) & 1) != 0) {
    return true;
  }
  int32_t variant_period = REXCVAR_GET(post_pass_variant_ms);
  const std::string& variants = REXCVAR_GET(post_pass_variants);
  if (variant_period <= 0 || variants.empty()) {
    return false;
  }
  std::vector<std::string> entries;
  std::istringstream stream(variants);
  for (std::string entry; std::getline(stream, entry, ';');) {
    if (!entry.empty()) entries.push_back(entry);
  }
  if (entries.empty()) {
    return false;
  }
  *variant_index_out = int32_t((SteadyMilliseconds() / variant_period) % int64_t(entries.size()));
  return entries[size_t(*variant_index_out)] == "off";
}

void PostPasses::UpdateParams(int32_t variant_index) {
  uint64_t generation = overrides_.defines_generation();
  if (params_valid_ && params_generation_ == generation && params_variant_ == variant_index) {
    return;
  }
  params_valid_ = true;
  params_generation_ = generation;
  params_variant_ = variant_index;
  const Manifest& manifest = *manifest_;
  std::vector<double> values(manifest.params.size());
  for (size_t i = 0; i < manifest.params.size(); ++i) {
    const ParamDesc& param = manifest.params[i];
    values[i] = param.value;
    std::string text;
    if (overrides_.GetDefine(param.name, text) && !ParseNumber(text, values[i])) {
      REXGPU_WARN("Post passes: {}={} is not a number, using {}", param.name, text, param.value);
      values[i] = param.value;
    }
  }
  // NAME=VALUE,NAME=VALUE of the current post_pass_variants entry.
  if (variant_index >= 0) {
    std::vector<std::string> entries;
    std::istringstream stream(REXCVAR_GET(post_pass_variants));
    for (std::string entry; std::getline(stream, entry, ';');) {
      if (!entry.empty()) entries.push_back(entry);
    }
    if (size_t(variant_index) < entries.size()) {
      std::istringstream fields(entries[size_t(variant_index)]);
      for (std::string field; std::getline(fields, field, ',');) {
        size_t equals = field.find('=');
        double value;
        if (equals == std::string::npos || !ParseNumber(field.substr(equals + 1), value)) continue;
        for (size_t i = 0; i < manifest.params.size(); ++i) {
          if (manifest.params[i].name == field.substr(0, equals)) values[i] = value;
        }
      }
    }
  }
  // FSR=1 without the upscaler (a runtime without REX_FSR, or a context that could not be
  // created): 0, so the manifest's TAA runs instead.
  for (size_t i = 0; i < manifest.params.size(); ++i) {
    if (manifest.params[i].name != "FSR" || values[i] <= 0.0) continue;
    if (!FsrUpscaler::Available() || fsr_failed_) {
      if (!warned_fsr_unavailable_) {
        warned_fsr_unavailable_ = true;
        REXGPU_WARN("Post passes: FSR={} but {}; TAA runs instead", values[i],
                    fsr_failed_ ? "its context could not be created"
                                : "the runtime is built without FSR (REX_FSR)");
      }
      values[i] = 0.0;
    }
  }
  for (size_t i = 0; i < manifest.params.size(); ++i) {
    const ParamDesc& param = manifest.params[i];
    // In float, as the clamps of the cvars of the GTAO pass were.
    float value = std::clamp(float(values[i]), float(param.min), float(param.max));
    param_values_[i] = param.is_uint ? uint32_t(value) : 0;
    if (!param.is_uint) std::memcpy(&param_values_[i], &value, sizeof(value));
  }
}

void PostPasses::FillSceneConstants(post_pass::SceneConstants& constants) const {
  std::memset(&constants, 0, sizeof(constants));
  uint64_t frame = command_processor_.GetCurrentFrame();
  constants.frame = uint32_t(frame);
  constants.time =
      std::chrono::duration<float>(std::chrono::steady_clock::now() - start_time_).count();
  if (scene_frame_ == frame && camera_.valid) {
    const post_pass::Unpack& unpack = camera_.unpack;
    constants.xy_mul_add[0] = unpack.x_mul;
    constants.xy_mul_add[1] = unpack.x_add;
    constants.xy_mul_add[2] = unpack.y_mul;
    constants.xy_mul_add[3] = unpack.y_add;
    constants.size[0] = scene_width_;
    constants.size[1] = scene_height_;
    constants.guest_per_host[0] = float(GuestSceneWidth()) / float(scene_width_);
    constants.guest_per_host[1] = float(GuestSceneHeight()) / float(scene_height_);
    constants.guest_origin[0] = camera_.guest_origin;
    constants.guest_origin[1] = camera_.guest_origin;
    constants.w_numerator = unpack.w_numerator;
    constants.w_depth_mul = unpack.w_depth_mul;
    constants.w_depth_add = unpack.w_depth_add;
    constants.z_from_w = unpack.z_from_w;
    constants.w_far = unpack.w_far;
    constants.focal[0] = unpack.pixels_per_unit_x / constants.guest_per_host[0];
    constants.focal[1] = unpack.pixels_per_unit_y / constants.guest_per_host[1];
    if (jitter_active_) {
      constants.jitter[0] = jitter_[0];
      constants.jitter[1] = jitter_[1];
      constants.jitter_phase = jitter_phase_;
      constants.jitter_phases = jitter_phases_;
      if (jitter_still_) {
        constants.flags |= post_pass::kSceneFlagCameraStill;
        constants.still_frames = still_frames_;
      }
    }
    bool view_known = camera_.view_frame == frame;
    if (view_known) {
      constants.flags |= post_pass::kSceneFlagViewKnown;
      std::memcpy(constants.view_to_world, camera_.view_to_world.m, sizeof(float) * 12);
    }
    // UpdateMotion ran at this frame's first point.
    if (motion_.frame == frame && motion_.valid) {
      constants.flags |= post_pass::kSceneFlagMotionValid;
      // The scene color and depth history if a pass reads it, and the
      // previous frame's copies of the history textures.
      const Manifest& manifest = *manifest_;
      bool uses_scene_history = manifest.uses_previous_color || manifest.uses_previous_depth;
      bool has_history_textures =
          std::any_of(manifest.textures.begin(), manifest.textures.end(),
                      [](const TextureDesc& texture) { return texture.history; });
      bool scene_history = previous_valid_ && previous_width_ == scene_width_ &&
                           previous_height_ == scene_height_;
      if ((uses_scene_history || has_history_textures) &&
          (!uses_scene_history || scene_history) && HistoryTexturesValid()) {
        constants.flags |= post_pass::kSceneFlagHistoryValid;
      }
      std::memcpy(constants.view_to_previous_view, motion_.view_to_previous_view[0],
                  sizeof(constants.view_to_previous_view));
      const post_pass::Unpack& previous = previous_camera_.unpack;
      constants.previous_xy_mul_add[0] = previous.x_mul;
      constants.previous_xy_mul_add[1] = previous.x_add;
      constants.previous_xy_mul_add[2] = previous.y_mul;
      constants.previous_xy_mul_add[3] = previous.y_add;
      constants.previous_w_numerator = previous.w_numerator;
      constants.previous_w_depth_mul = previous.w_depth_mul;
      constants.previous_w_depth_add = previous.w_depth_add;
      constants.previous_z_from_w = previous.z_from_w;
    }
  }
  const Manifest& manifest = *manifest_;
  constants.motion_stencil_scale = 1.0f / float(manifest.motion_stencil_step);
  constants.motion_stencil_limit = manifest.motion_stencil_limit;
  constants.motion_slot_count = manifest.motion_slot_count;
  constants.motion_interior_slot = post_pass::kMotionNoInterior;
  constants.motion_interior_depth =
      manifest.interior_sources.empty() ? -1.0f : manifest.interior_depth;
  if (motion_.frame == frame) {
    constants.motion_slots_own = motion_.slots_own;
    constants.motion_interior_slot = motion_.interior_slot;
    std::memcpy(constants.motion_view_to_previous_view, motion_.view_to_previous_view,
                sizeof(constants.motion_view_to_previous_view));
    std::memcpy(constants.motion_object_origin, motion_.object_origin,
                sizeof(constants.motion_object_origin));
  } else {
    for (auto& rows : constants.motion_view_to_previous_view) {
      for (int i = 0; i < 3; ++i) rows[i][i] = 1.0f;
    }
  }
  if (final_color_.resource) {
    constants.final_size[0] = final_width_;
    constants.final_size[1] = final_height_;
    D3D12_RESOURCE_DESC desc = final_color_.resource->GetDesc();
    constants.final_uv_scale[0] = float(final_width_) / float(desc.Width);
    constants.final_uv_scale[1] = float(final_height_) / float(desc.Height);
  }
}

bool PostPasses::ConditionsHold(const std::vector<Condition>& conditions) const {
  const Manifest& manifest = *manifest_;
  bool enabled = true;
  bool scene = scene_frame_ == command_processor_.GetCurrentFrame() && camera_.valid;
  for (const Condition& condition : conditions) {
    double value = condition.name == "XE_SCENE" && scene ? 1.0 : 0.0;
    for (size_t i = 0; i < manifest.params.size(); ++i) {
      if (manifest.params[i].name != condition.name) continue;
      if (manifest.params[i].is_uint) {
        value = double(param_values_[i]);
      } else {
        float float_value;
        std::memcpy(&float_value, &param_values_[i], sizeof(float_value));
        value = float_value;
      }
    }
    for (const auto& define : manifest.compiled_defines) {
      if (define.first == condition.name) ParseNumber(define.second, value);
    }
    switch (condition.op) {
      case Condition::Op::kEqual:
        enabled &= value == condition.value;
        break;
      case Condition::Op::kNotEqual:
        enabled &= value != condition.value;
        break;
      case Condition::Op::kLess:
        enabled &= value < condition.value;
        break;
      case Condition::Op::kLessEqual:
        enabled &= value <= condition.value;
        break;
      case Condition::Op::kGreater:
        enabled &= value > condition.value;
        break;
      case Condition::Op::kGreaterEqual:
        enabled &= value >= condition.value;
        break;
    }
  }
  return enabled;
}

void PostPasses::RunPoint(Point point) {
  if (point == Point::kFinal) {
    final_pending_ = false;
  }
  if (!manifest_ || !manifest_->uses_point[size_t(point)]) {
    return;
  }
  ReleasePendingDescriptors(false);
  int32_t variant_index;
  if (IsSkipped(&variant_index)) {
    return;
  }
  uint64_t frame = command_processor_.GetCurrentFrame();
  UpdateParams(variant_index);
  // Params that are view lengths in host pixels, for this frame's camera: as
  // the GTAO pass computed its radius in pixels before the framework.
  const Manifest& manifest = *manifest_;
  float guest_per_host_x =
      scene_width_ ? float(GuestSceneWidth()) / float(scene_width_) : 1.0f;
  for (size_t i = 0; i < manifest.params.size(); ++i) {
    uint32_t source = manifest.params[i].focal_length_of;
    if (source == UINT32_MAX) continue;
    float length;
    std::memcpy(&length, &param_values_[source], sizeof(length));
    float pixels = scene_frame_ == frame
                       ? length * camera_.unpack.pixels_per_unit_x / guest_per_host_x
                       : 0.0f;
    std::memcpy(&param_values_[i], &pixels, sizeof(pixels));
  }
  // A point whose passes are all switched off costs nothing (a debug view's
  // final pass, for instance).
  bool any_enabled = false;
  for (const PassDesc& pass : manifest.passes) {
    any_enabled |= pass.point == point && PassEnabled(pass);
  }
  if (!any_enabled) {
    return;
  }
  final_color_ = {};
  scene_stencil_ = {};
  scene_stencil_requested_ = false;
  if (point == Point::kFinal) {
    D3D12RenderTargetCache::LastColorRenderTarget target;
    if (!command_processor_.render_target_cache_->TransitionLastColorRenderTarget(
            0, kShaderResource, target)) {
      if (!warned_final_) {
        warned_final_ = true;
        REXGPU_WARN("Post passes: no single-sampled color render target at the final point");
      }
      return;
    }
    final_color_.resource = target.resource;
    final_color_.rtv = target.rtv;
    final_color_.format = target.format;
    // A private final target at a fractional scene scale (d3d-hle-n5.md
    // 18.13), or while upscaling at any (fsr-plan.md 11, where a whole output
    // scale is not the other surfaces'): its pixels are the scene's.
    const DrawScale scene_scale = command_processor_.texture_cache_->scene_draw_scale();
    if (command_processor_.render_target_cache_->scene_textures() &&
        (!scene_scale.IsWhole() || command_processor_.render_target_cache_->IsSceneUpscaled() ||
         command_processor_.render_target_cache_->scene_logical_width() != 1280 ||
         command_processor_.render_target_cache_->scene_logical_height() != 720)) {
      final_width_ = std::min(
          command_processor_.texture_cache_->SceneTextureHostWidth(final_guest_width_),
          target.width);
      final_height_ = std::min(
          command_processor_.texture_cache_->SceneTextureHostHeight(final_guest_height_),
          target.height);
    } else {
      final_width_ = std::min(
          final_guest_width_ * command_processor_.texture_cache_->draw_resolution_scale_x(),
          target.width);
      final_height_ = std::min(
          final_guest_height_ * command_processor_.texture_cache_->draw_resolution_scale_y(),
          target.height);
    }
    ui::d3d12::util::DescriptorCpuGpuHandlePair descriptor;
    if (!final_width_ || !final_height_ ||
        !command_processor_.RequestOneUseSingleViewDescriptors(1, &descriptor)) {
      final_color_ = {};
      return;
    }
    D3D12_SHADER_RESOURCE_VIEW_DESC srv_desc = {};
    srv_desc.Format = target.format;
    srv_desc.ViewDimension = D3D12_SRV_DIMENSION_TEXTURE2D;
    srv_desc.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING;
    srv_desc.Texture2D.MipLevels = 1;
    command_processor_.GetD3D12Provider().GetDevice()->CreateShaderResourceView(
        target.resource, &srv_desc, descriptor.first);
    final_color_.srv = descriptor.second;
    // The frame's scene inputs, if it had a scene.
    scene_depth_ = {};
    scene_color_ = {};
    if (scene_frame_ == frame) {
      RequestExternal(depth_group_, ExternalKind::kDepth, scene_depth_);
      if (scene_color_frame_ == frame && manifest_->uses_scene_color) {
        RequestExternal(color_group_, ExternalKind::kColor, scene_color_);
      }
      // Passes such as TAA leave the frame as it is when the final size is
      // not the scene's, which no known case has; report each new pair.
      // The scene at its output scale while upscaling (fsr-plan.md 11).
      if ((final_width_ != output_width_ || final_height_ != output_height_) &&
          (final_width_ != mismatch_final_width_ || final_height_ != mismatch_final_height_ ||
           output_width_ != mismatch_scene_width_ || output_height_ != mismatch_scene_height_)) {
        mismatch_final_width_ = final_width_;
        mismatch_final_height_ = final_height_;
        mismatch_scene_width_ = output_width_;
        mismatch_scene_height_ = output_height_;
        REXGPU_ERROR("Post passes: final size {}x{} differs from the scene's {}x{}", final_width_,
                     final_height_, output_width_, output_height_);
      }
    }
  }
  // The objects of the frame are drawn once its scene depth is resolved.
  UpdateMotion();

  post_pass::SceneConstants constants;
  FillSceneConstants(constants);
  D3D12_GPU_VIRTUAL_ADDRESS constants_address;
  uint8_t* mapping = command_processor_.GetConstantBufferPool().Request(
      command_processor_.GetCurrentFrame(), sizeof(constants),
      D3D12_CONSTANT_BUFFER_DATA_PLACEMENT_ALIGNMENT, nullptr, nullptr, &constants_address);
  if (!mapping) {
    return;
  }
  std::memcpy(mapping, &constants, sizeof(constants));

  // Each pass's GPU time in the perf trace, by group (d3d-hle-n4.md 17.24).
  const auto run_timed = [&](PassDesc& pass) {
    const uint32_t timestamp = command_processor_.BeginPostPassTimestamp(pass.name);
    const bool ran = pass.fsr ? RunFsr(pass, constants) : RunPass(pass, constants_address);
    command_processor_.EndPostPassTimestamp(timestamp);
    return ran;
  };
  for (PassDesc& pass : manifest_->passes) {
    if (pass.point == point && PassEnabled(pass) && run_timed(pass) &&
        std::find(manifest.jitter_consumers.begin(), manifest.jitter_consumers.end(),
                  pass.name) != manifest.jitter_consumers.end()) {
      jitter_consumer_frame_ = frame;
      const uint32_t still_valid =
          post_pass::kSceneFlagCameraStill | post_pass::kSceneFlagHistoryValid;
      if ((constants.flags & still_valid) == still_valid) {
        still_consumer_frame_ = frame;
      }
    }
  }
  // Exposed textures as shader mods read them.
  for (size_t i = 0; i < textures_.size(); ++i) {
    if (manifest.textures[i].slot >= 0 && textures_[i].resource) {
      Transition(textures_[i].resource.Get(), textures_[i].state, kShaderResource);
    }
  }
  // The draws after the point may still mark: back to a UAV.
  if (point == Point::kSceneColor && reactive_mark_bound_ && manifest.reactive_mark != UINT32_MAX) {
    Texture& mark = textures_[manifest.reactive_mark];
    if (mark.resource.Get() == reactive_mark_bound_) {
      Transition(mark.resource.Get(), mark.state, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
    }
  }
  command_processor_.SubmitBarriers();
  if (point == Point::kSceneDepth) {
    LogRun(variant_index);
  }
}

void PostPasses::UpdateReactiveMark() {
  const Manifest& manifest = *manifest_;
  ID3D12Resource* bound = nullptr;
  if (manifest.reactive_mark != UINT32_MAX && overrides_.uses_reactive_mark() && scene_width_ &&
      EnsureTexture(manifest.reactive_mark)) {
    Texture& mark = textures_[manifest.reactive_mark];
    bound = mark.resource.Get();
    Transition(bound, mark.state, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
    command_processor_.SubmitBarriers();
    const UINT zero[4] = {};
    command_processor_.GetDeferredCommandList().D3DClearUnorderedAccessViewUint(
        Gpu(mark.uavs[0]), LocalCpu(DescriptorKind::kCpu, mark.clear_uav), bound, zero, 0,
        nullptr);
  }
  if (bound == reactive_mark_bound_) {
    return;
  }
  reactive_mark_bound_ = bound;
  D3D12_UNORDERED_ACCESS_VIEW_DESC desc = {};
  desc.Format = DXGI_FORMAT_R8_UNORM;
  desc.ViewDimension = D3D12_UAV_DIMENSION_TEXTURE2D;
  command_processor_.GetD3D12Provider().GetDevice()->CreateUnorderedAccessView(
      bound, nullptr, &desc,
      command_processor_
          .GetSystemBindlessViewHandlePair(
              D3D12CommandProcessor::SystemBindlessView::kPostPassReactiveMarkUAV)
          .first);
  REXGPU_INFO("Post passes: reactive mark {}", bound ? "bound" : "unbound");
}

bool PostPasses::BindingSize(const Binding& binding, uint32_t& width, uint32_t& height) const {
  switch (binding.builtin) {
    case Builtin::kNone: {
      const Texture& texture =
          (binding.previous ? previous_textures_ : textures_)[binding.texture];
      uint32_t mip = uint32_t(std::max(binding.mip, 0));
      width = std::max(texture.width >> mip, uint32_t(1));
      height = std::max(texture.height >> mip, uint32_t(1));
      return texture.resource != nullptr;
    }
    case Builtin::kFinalColor:
      width = final_width_;
      height = final_height_;
      return final_color_.resource != nullptr;
    default:
      width = scene_width_;
      height = scene_height_;
      return scene_width_ != 0;
  }
}

bool PostPasses::RunPass(PassDesc& pass, D3D12_GPU_VIRTUAL_ADDRESS scene_constants) {
  const Manifest& manifest = *manifest_;
  uint32_t read_index = history_write_ ^ 1;
  D3D12_GPU_DESCRIPTOR_HANDLE null_srv = command_processor_.GetSystemBindlessViewHandlePair(
      D3D12CommandProcessor::SystemBindlessView::kNullTexture2DArray).second;
  D3D12_GPU_DESCRIPTOR_HANDLE srvs[post_pass::kMaxSrvs], uavs[post_pass::kMaxUavs];
  std::fill(std::begin(srvs), std::end(srvs), null_srv);
  // Make sure every texture written exists first (inputs may be sized like it).
  for (const Binding& output : pass.pixel ? pass.rtvs : pass.uavs) {
    if (output.builtin == Builtin::kNone && !EnsureTexture(output.texture)) return false;
  }
  for (size_t i = 0; i < pass.srvs.size(); ++i) {
    const Binding& binding = pass.srvs[i];
    switch (binding.builtin) {
      case Builtin::kNone: {
        if (!EnsureTexture(binding.texture, binding.previous)) return false;
        Texture& texture =
            (binding.previous ? previous_textures_ : textures_)[binding.texture];
        Transition(texture.resource.Get(), texture.state, kShaderResource);
        // A texture too small for its mips has one, viewed by srv.
        srvs[i] = Gpu(binding.mip < 0 || texture.srv_mips[binding.mip] == UINT32_MAX
                          ? texture.srv
                          : texture.srv_mips[binding.mip]);
        break;
      }
      case Builtin::kSceneDepth:
        if (!scene_depth_.resource) return false;
        srvs[i] = scene_depth_.srv;
        break;
      case Builtin::kSceneStencil:
        // Loaded by the texture cache only for the passes that read it, once
        // per point run (before this pass sets its pipeline).
        if (!scene_stencil_requested_) {
          scene_stencil_requested_ = true;
          if (scene_frame_ == command_processor_.GetCurrentFrame()) {
            RequestExternal(depth_group_, ExternalKind::kStencil, scene_stencil_);
          }
        }
        if (!scene_stencil_.resource) return false;
        srvs[i] = scene_stencil_.srv;
        break;
      case Builtin::kSceneColor:
        if (!scene_color_.resource) return false;
        srvs[i] = scene_color_.srv;
        break;
      case Builtin::kPreviousColor:
      case Builtin::kPreviousDepth: {
        // Bound also when invalid (xe_history_valid() tells), once it exists.
        History& history = binding.builtin == Builtin::kPreviousColor
                               ? history_color_[read_index]
                               : history_depth_[read_index];
        if (history.resource) {
          Transition(history.resource.Get(), history.state, kShaderResource);
          srvs[i] = Gpu(history.srv);
        }
        break;
      }
      case Builtin::kFinalColor: {
        // Back to a shader resource after a pass drew into it.
        D3D12RenderTargetCache::LastColorRenderTarget target;
        if (!final_color_.resource ||
            !command_processor_.render_target_cache_->TransitionLastColorRenderTarget(
                0, kShaderResource, target)) {
          return false;
        }
        srvs[i] = final_color_.srv;
        break;
      }
    }
  }
  uint32_t width, height;
  if (!BindingSize(pass.size, width, height)) {
    return false;
  }
  post_pass::PassHeader header = {{width, height}, {1.0f / float(width), 1.0f / float(height)}};
  uint32_t constants[post_pass::kPassConstantCount] = {};
  std::memcpy(constants, &header, sizeof(header));
  std::memcpy(constants + sizeof(header) / sizeof(uint32_t), param_values_.data(),
              manifest.params.size() * sizeof(uint32_t));
  uint32_t constant_count =
      uint32_t(sizeof(header) / sizeof(uint32_t) + std::max(manifest.params.size(), size_t(1)));
  DeferredCommandList& list = command_processor_.GetDeferredCommandList();

  if (!pass.pixel) {
    for (size_t i = 0; i < pass.uavs.size(); ++i) {
      const Binding& binding = pass.uavs[i];
      Texture& texture = textures_[binding.texture];
      Transition(texture.resource.Get(), texture.state, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
      uavs[i] = Gpu(texture.uavs[std::max(binding.mip, 0)]);
      texture.written = true;
      texture.written_frame = command_processor_.GetCurrentFrame();
    }
    for (size_t i = pass.uavs.size(); i < post_pass::kMaxUavs; ++i) {
      uavs[i] = uavs[0];
    }
    command_processor_.SubmitBarriers();
    command_processor_.SetExternalPipeline(pass.pipeline.Get());
    list.D3DSetComputeRootSignature(root_signature_.Get());
    list.D3DSetComputeRootConstantBufferView(post_pass::kRootSceneConstants, scene_constants);
    list.D3DSetComputeRoot32BitConstants(post_pass::kRootPassConstants, constant_count, constants,
                                         0);
    for (uint32_t i = 0; i < post_pass::kMaxSrvs; ++i) {
      list.D3DSetComputeRootDescriptorTable(post_pass::kRootSrvFirst + i, srvs[i]);
    }
    for (uint32_t i = 0; i < post_pass::kMaxUavs; ++i) {
      list.D3DSetComputeRootDescriptorTable(post_pass::kRootUavFirst + i, uavs[i]);
    }
    list.D3DDispatch((width + pass.group[0] - 1) / pass.group[0],
                     (height + pass.group[1] - 1) / pass.group[1], 1);
    return true;
  }

  std::array<DXGI_FORMAT, post_pass::kMaxRenderTargets> formats = {};
  D3D12_CPU_DESCRIPTOR_HANDLE rtvs[post_pass::kMaxRenderTargets];
  for (size_t i = 0; i < pass.rtvs.size(); ++i) {
    const Binding& binding = pass.rtvs[i];
    if (binding.builtin == Builtin::kFinalColor) {
      D3D12RenderTargetCache::LastColorRenderTarget target;
      if (!command_processor_.render_target_cache_->TransitionLastColorRenderTarget(
              0, D3D12_RESOURCE_STATE_RENDER_TARGET, target)) {
        return false;
      }
      formats[i] = target.format;
      rtvs[i] = target.rtv;
      continue;
    }
    Texture& texture = textures_[binding.texture];
    Transition(texture.resource.Get(), texture.state, D3D12_RESOURCE_STATE_RENDER_TARGET);
    formats[i] = manifest.textures[binding.texture].format;
    rtvs[i] = LocalCpu(DescriptorKind::kRtv, texture.rtvs[std::max(binding.mip, 0)]);
    texture.written = true;
    texture.written_frame = command_processor_.GetCurrentFrame();
  }
  ID3D12PipelineState* pipeline = PixelPipeline(pass, formats);
  if (!pipeline) {
    return false;
  }
  command_processor_.SubmitBarriers();
  command_processor_.SetExternalPipeline(pipeline);
  command_processor_.SetExternalGraphicsRootSignature(root_signature_.Get());
  list.D3DSetGraphicsRootConstantBufferView(post_pass::kRootSceneConstants, scene_constants);
  list.D3DSetGraphicsRoot32BitConstants(post_pass::kRootPassConstants, constant_count, constants,
                                        0);
  D3D12_GPU_DESCRIPTOR_HANDLE null_uav = command_processor_.GetSystemBindlessViewHandlePair(
      D3D12CommandProcessor::SystemBindlessView::kNullRawUAV).second;
  for (uint32_t i = 0; i < post_pass::kMaxSrvs; ++i) {
    list.D3DSetGraphicsRootDescriptorTable(post_pass::kRootSrvFirst + i, srvs[i]);
  }
  for (uint32_t i = 0; i < post_pass::kMaxUavs; ++i) {
    list.D3DSetGraphicsRootDescriptorTable(post_pass::kRootUavFirst + i, null_uav);
  }
  list.D3DOMSetRenderTargets(UINT(pass.rtvs.size()), rtvs, FALSE, nullptr);
  // The next guest draw binds its render targets again.
  command_processor_.render_target_cache_->InvalidateCommandListRenderTargets();
  D3D12_VIEWPORT viewport = {0.0f, 0.0f, float(width), float(height), 0.0f, 1.0f};
  command_processor_.SetViewport(viewport);
  D3D12_RECT scissor = {0, 0, LONG(width), LONG(height)};
  command_processor_.SetScissorRect(scissor);
  command_processor_.SetPrimitiveTopology(D3D_PRIMITIVE_TOPOLOGY_TRIANGLELIST);
  // The RTV path keeps a host occlusion query open between the guest's
  // snapshots, summed over its segments: the pass's pixels go between two.
  bool query_open = command_processor_.rtv_occlusion_open_query_ != UINT32_MAX;
  if (query_open) {
    command_processor_.CloseRTVOcclusionQuery();
  }
  list.D3DDrawInstanced(3, 1, 0, 0);
  if (query_open) {
    command_processor_.OpenRTVOcclusionQuery();
  }
  return true;
}

float PostPasses::NamedParam(const char* name, float fallback) const {
  const Manifest& manifest = *manifest_;
  for (size_t i = 0; i < manifest.params.size(); ++i) {
    if (manifest.params[i].name != name) continue;
    if (manifest.params[i].is_uint) return float(param_values_[i]);
    float value;
    std::memcpy(&value, &param_values_[i], sizeof(value));
    return value;
  }
  return fallback;
}

float PostPasses::NamedDefine(const char* name, float fallback) const {
  for (const auto& define : manifest_->compiled_defines) {
    double value;
    if (define.first == name && ParseNumber(define.second, value)) return float(value);
  }
  return fallback;
}

namespace {

// The arguments of FSR's callback in the deferred command list (trivially copyable).
struct FsrCall {
  FsrUpscaler* upscaler;
  FsrUpscaler::Dispatch dispatch;
};

void RecordFsr(ID3D12GraphicsCommandList* command_list, const void* arguments) {
  FsrCall call;
  std::memcpy(&call, arguments, sizeof(call));
  std::string error;
  if (!call.upscaler->Record(command_list, call.dispatch, &error)) {
    static std::atomic<bool> reported = false;
    if (!reported.exchange(true)) {
      REXGPU_ERROR("Post passes: {}", error);
    }
  }
}

}  // namespace

bool PostPasses::RunFsr(PassDesc& pass, const post_pass::SceneConstants& constants) {
  for (const Binding& binding : pass.srvs) {
    if (!EnsureTexture(binding.texture)) return false;
  }
  if (!EnsureTexture(pass.uavs[0].texture)) return false;
  Texture& color = textures_[pass.srvs[0].texture];
  Texture& output = textures_[pass.uavs[0].texture];
  FsrUpscaler::Description description;
  description.render_width = color.width;
  description.render_height = color.height;
  description.output_width = output.width;
  description.output_height = output.height;
  description.fp16 = NamedParam("FSR_FP16", 1.0f) > 0.0f;
  const uint64_t frame = command_processor_.GetCurrentFrame();
  bool reset = false;
  if (!fsr_ || !(fsr_->description() == description)) {
    if (fsr_) {
      retired_fsr_.emplace_back(command_processor_.GetCurrentSubmission(), std::move(fsr_));
    }
    std::string error;
    auto start = std::chrono::steady_clock::now();
    fsr_ = FsrUpscaler::Create(command_processor_.GetD3D12Provider().GetDevice(), description,
                               &error);
    if (!fsr_) {
      REXGPU_ERROR("Post passes: FSR {}x{}: {}", description.render_width,
                   description.render_height, error);
      fsr_failed_ = true;
      params_valid_ = false;
      return false;
    }
    REXGPU_INFO("Post passes: FSR {} at {}x{} to {}x{}{}, created in {:.1f} ms",
                FsrUpscaler::Version(), description.render_width, description.render_height,
                description.output_width, description.output_height,
                description.fp16 ? "" : ", 32-bit shaders",
                std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - start)
                    .count());
    reset = true;
  }
  // Its accumulation restarts where the history breaks: a frame without it before, a scene
  // without a previous one, a camera cut.
  reset |= fsr_frame_ == UINT64_MAX || fsr_frame_ + 1 != frame || !previous_scene_ ||
           IsCameraCut();
  fsr_frame_ = frame;

  FsrCall call = {fsr_.get(), {}};
  FsrUpscaler::Dispatch& dispatch = call.dispatch;
  ID3D12Resource** inputs[] = {&dispatch.color, &dispatch.depth, &dispatch.motion_vectors,
                               &dispatch.reactive, &dispatch.composition};
  for (size_t i = 0; i < pass.srvs.size(); ++i) {
    Texture& texture = textures_[pass.srvs[i].texture];
    Transition(texture.resource.Get(), texture.state,
               D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
    *inputs[i] = texture.resource.Get();
  }
  Transition(output.resource.Get(), output.state, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
  output.written = true;
  output.written_frame = frame;
  dispatch.output = output.resource.Get();
  dispatch.jitter[0] = constants.jitter[0];
  dispatch.jitter[1] = constants.jitter[1];
  dispatch.frame_milliseconds =
      last_frame_seconds_ > 0.0 ? float(std::min(last_frame_seconds_, 0.25) * 1000.0) : 16.7f;
  dispatch.sharpness = std::clamp(NamedParam("FSR_SHARPNESS", 0.0f), 0.0f, 1.0f);
  dispatch.reset = reset;
  dispatch.camera_near_plane = NamedDefine("FSR_DEPTH_NEAR", 0.01f);
  // The vertical field of view from the focal length in host pixels.
  dispatch.vertical_fov =
      constants.focal[1] > 0.0f
          ? 2.0f * std::atan(0.5f * float(description.render_height) / constants.focal[1])
          : 1.0f;
  dispatch.debug_view = NamedParam("FSR_DEBUG", 0.0f) > 0.0f;
  command_processor_.SubmitBarriers();
  command_processor_.GetDeferredCommandList().D3DCallback(RecordFsr, &call, sizeof(call));
  command_processor_.InvalidateCommandListState();
  return true;
}

ID3D12PipelineState* PostPasses::PixelPipeline(
    PassDesc& pass, const std::array<DXGI_FORMAT, post_pass::kMaxRenderTargets>& formats) {
  if (pass.pipeline && pass.pipeline_formats == formats) {
    return pass.pipeline.Get();
  }
  if (pass.pipeline) {
    retired_.emplace_back(command_processor_.GetCurrentSubmission(), std::move(pass.pipeline));
  }
  D3D12_GRAPHICS_PIPELINE_STATE_DESC desc = {};
  desc.pRootSignature = root_signature_.Get();
  desc.VS = {manifest_->vertex_shader.data(), manifest_->vertex_shader.size()};
  desc.PS = {pass.bytecode.data(), pass.bytecode.size()};
  for (size_t i = 0; i < pass.rtvs.size(); ++i) {
    D3D12_RENDER_TARGET_BLEND_DESC& blend = desc.BlendState.RenderTarget[i];
    blend.RenderTargetWriteMask = D3D12_COLOR_WRITE_ENABLE_ALL;
    blend.BlendOpAlpha = blend.BlendOp = D3D12_BLEND_OP_ADD;
    blend.BlendEnable = pass.blend != Blend::kNone;
    switch (pass.blend) {
      case Blend::kAlpha:
        blend.SrcBlend = blend.SrcBlendAlpha = D3D12_BLEND_SRC_ALPHA;
        blend.DestBlend = blend.DestBlendAlpha = D3D12_BLEND_INV_SRC_ALPHA;
        break;
      case Blend::kAdd:
        blend.SrcBlend = blend.SrcBlendAlpha = D3D12_BLEND_ONE;
        blend.DestBlend = blend.DestBlendAlpha = D3D12_BLEND_ONE;
        break;
      case Blend::kMultiply:
        blend.SrcBlend = blend.SrcBlendAlpha = D3D12_BLEND_ZERO;
        blend.DestBlend = D3D12_BLEND_SRC_COLOR;
        blend.DestBlendAlpha = D3D12_BLEND_SRC_ALPHA;
        break;
      default:
        blend.SrcBlend = blend.SrcBlendAlpha = D3D12_BLEND_ONE;
        blend.DestBlend = blend.DestBlendAlpha = D3D12_BLEND_ZERO;
        break;
    }
    desc.RTVFormats[i] = formats[i];
  }
  desc.SampleMask = UINT_MAX;
  desc.RasterizerState.FillMode = D3D12_FILL_MODE_SOLID;
  desc.RasterizerState.CullMode = D3D12_CULL_MODE_NONE;
  desc.RasterizerState.DepthClipEnable = TRUE;
  desc.PrimitiveTopologyType = D3D12_PRIMITIVE_TOPOLOGY_TYPE_TRIANGLE;
  desc.NumRenderTargets = UINT(pass.rtvs.size());
  desc.SampleDesc.Count = 1;
  ID3D12Device* device = command_processor_.GetD3D12Provider().GetDevice();
  if (FAILED(device->CreateGraphicsPipelineState(&desc, IID_PPV_ARGS(&pass.pipeline)))) {
    REXGPU_ERROR("Post passes: failed to create the pipeline of {}", pass.name);
    return nullptr;
  }
  pass.pipeline_formats = formats;
  return pass.pipeline.Get();
}

void PostPasses::CopyHistory() {
  const Manifest& manifest = *manifest_;
  DeferredCommandList& list = command_processor_.GetDeferredCommandList();
  struct Copy {
    bool needed;
    External& source;
    History& history;
  };
  for (const Copy& copy :
       {Copy{manifest.uses_previous_color, scene_color_, history_color_[history_write_]},
        Copy{manifest.uses_previous_depth, scene_depth_, history_depth_[history_write_]}}) {
    if (!copy.needed) continue;
    if (!copy.source.resource ||
        !EnsureHistory(copy.history, copy.source.resource, copy.source.srv_desc)) {
      // Without this frame's copy the next frame has no history.
      history_written_ = false;
      return;
    }
    // The texture cache keeps its textures in kShaderResource.
    command_processor_.PushTransitionBarrier(copy.source.resource, kShaderResource,
                                             D3D12_RESOURCE_STATE_COPY_SOURCE);
    Transition(copy.history.resource.Get(), copy.history.state, D3D12_RESOURCE_STATE_COPY_DEST);
    command_processor_.SubmitBarriers();
    list.D3DCopyResource(copy.history.resource.Get(), copy.source.resource);
    command_processor_.PushTransitionBarrier(copy.source.resource,
                                             D3D12_RESOURCE_STATE_COPY_SOURCE, kShaderResource);
    Transition(copy.history.resource.Get(), copy.history.state, kShaderResource);
  }
  command_processor_.SubmitBarriers();
  history_written_ = true;
}

void PostPasses::LogRun(int32_t variant_index) {
  int32_t log_every = REXCVAR_GET(post_pass_log_every);
  if (runs_ && !(log_every > 0 && runs_ % uint64_t(log_every) == 0)) {
    ++runs_;
    return;
  }
  ++runs_;
  const post_pass::Unpack& unpack = camera_.unpack;
  // W at both ends of the stored depth range (reversed Z: far at 0) and the
  // horizontal field of view of the guest viewport, for checking the camera.
  float w_depth_0 = unpack.w_numerator / unpack.w_depth_add;
  float w_depth_1 = unpack.w_numerator / (unpack.w_depth_mul + unpack.w_depth_add);
  float half_width_pixels = float(GuestSceneWidth()) * 0.5f;
  float fov_x = 2.0f * std::atan(half_width_pixels / unpack.pixels_per_unit_x) * 57.2957795f;
  std::string params;
  for (size_t i = 0; i < manifest_->params.size(); ++i) {
    float value;
    std::memcpy(&value, &param_values_[i], sizeof(value));
    params += manifest_->params[i].is_uint
                  ? fmt::format(" {}={}", manifest_->params[i].name, param_values_[i])
                  : fmt::format(" {}={:.4g}", manifest_->params[i].name, value);
  }
  // Q and Q * near compare with the game's own linearization constants
  // (combineQVals of the DOF final combine, QAndNegNearQAndScale of the motion
  // blur; post_pass_log_constants).
  REXGPU_INFO(
      "Post passes scene {} frame {} ms {} (camera frame {}, view {}{}): scene depth "
      "0x{:08X}-0x{:08X} {}x{} (EDRAM {}), host {}x{}; camera Q {:.7g} Q*near {:.6g} (near "
      "{:.4g}), W(d=0) {:.4g} W(d=1) {:.4g}, far W {:.4g}, depth mul {:.6g} add {:.6g}, x {:.6g} "
      "{:.6g}, y {:.6g} {:.6g}, z/W {:.3g}, focal {:.1f} px (FOV x {:.1f} deg over {} px), origin "
      "{}; history {}; motion {}; jitter {} (camera {}, {:.1f} fps){}; variant {}:{}",
      runs_ - 1, depth_group_.frame, SteadyMilliseconds(), camera_.frame,
      camera_.view_frame == command_processor_.GetCurrentFrame() ? "known" : "unknown",
      camera_.view_frame != command_processor_.GetCurrentFrame() ? std::string()
      : camera_.view_source < manifest_->camera_sources.size()
          ? fmt::format(" from source {}", camera_.view_source)
          : std::string(" from the fallback"),
      depth_group_.base, depth_group_.end, depth_group_.pitch, depth_group_.height,
      depth_group_.edram_base, scene_width_, scene_height_, camera_.q, camera_.q_near,
      camera_.q != 0.0f ? camera_.q_near / camera_.q : 0.0f, w_depth_0, w_depth_1, unpack.w_far,
      unpack.w_depth_mul, unpack.w_depth_add, unpack.x_mul, unpack.x_add, unpack.y_mul,
      unpack.y_add, unpack.z_from_w, unpack.pixels_per_unit_x, fov_x, depth_group_.pitch,
      camera_.guest_origin,
      std::string(previous_valid_ ? (IsCameraCut() ? "cut" : "valid") : "none") +
          HistoryTexturesSummary(),
      MotionSummary(),
      jitter_active_ ? fmt::format("{:.4f},{:.4f}{}", jitter_[0], jitter_[1],
                                   jitter_still_ ? fmt::format(" after {} still", still_frames_)
                                                 : std::string())
                     : std::string("off"),
      motion_.frame == command_processor_.GetCurrentFrame() && motion_.valid
          ? fmt::format("{:.3f} px", motion_.camera_pixels)
          : std::string("unknown"),
      jitter_gate_.FrameRate(), WriteBackSummary(), variant_index, params);
}

std::string PostPasses::WriteBackSummary() const {
  if (write_back_frame_ == UINT64_MAX) {
    return std::string();
  }
  const TextureCache::WriteBackCounts& counts = write_back_counts_;
  std::string summary = fmt::format("; write-back frame {}, before it binds {} reloads {} other {}",
                                    write_back_frame_, counts.binds, counts.reloads,
                                    counts.other_binds);
  if (counts.other_binds) {
    summary += fmt::format(" (key {}x{} pitch {} format {} mips {} packed {} dimension {})",
                           counts.other_width, counts.other_height, counts.other_pitch,
                           counts.other_format, counts.other_mip_max_level,
                           counts.other_packed_mips, counts.other_dimension);
  }
  return summary;
}

double PostPasses::ParamValue(uint32_t index) const {
  if (manifest_->params[index].is_uint) {
    return double(param_values_[index]);
  }
  float value;
  std::memcpy(&value, &param_values_[index], sizeof(value));
  return value;
}

post_pass::JitterGateSettings PostPasses::JitterSettings() const {
  const Manifest& manifest = *manifest_;
  post_pass::JitterGateSettings settings;
  settings.min_motion = manifest.jitter_min_motion_param != UINT32_MAX
                            ? ParamValue(manifest.jitter_min_motion_param)
                            : manifest.jitter_min_motion;
  settings.min_frame_rate = manifest.jitter_min_frame_rate_param != UINT32_MAX
                                ? ParamValue(manifest.jitter_min_frame_rate_param)
                                : manifest.jitter_min_frame_rate;
  settings.hold = manifest.jitter_motion_hold;
  settings.still = (manifest.jitter_still_param != UINT32_MAX
                        ? double(ParamValue(manifest.jitter_still_param))
                        : manifest.jitter_still) > 0.0;
  return settings;
}

void PostPasses::UpdateJitter() {
  jitter_active_ = false;
  jitter_still_ = false;
  jitter_[0] = jitter_[1] = 0.0f;
  jitter_phases_ = 0;
  // The frame time and the camera's motion of every frame, for the gate.
  auto now = std::chrono::steady_clock::now();
  double frame_seconds = last_swap_time_ != std::chrono::steady_clock::time_point()
                             ? std::chrono::duration<double>(now - last_swap_time_).count()
                             : 0.0;
  last_swap_time_ = now;
  last_frame_seconds_ = frame_seconds;
  if (!manifest_) {
    return;
  }
  const Manifest& manifest = *manifest_;
  uint64_t frame = command_processor_.GetCurrentFrame();
  // The still frames in a row: each one jittered at the next phase.
  still_frames_ = still_consumer_frame_ == frame ? still_frames_ + 1 : 0;
  int32_t variant_index;
  bool skipped = IsSkipped(&variant_index);
  UpdateParams(variant_index);
  const post_pass::JitterGateSettings settings = JitterSettings();
  jitter_gate_.EndFrame(motion_.frame == frame && motion_.valid ? motion_.camera_pixels : -1.0,
                        frame_seconds, settings);
  const std::string& mode = REXCVAR_GET(post_pass_jitter);
  if (mode == "off" || skipped) {
    return;
  }
  uint32_t phases = manifest.jitter_phases;
  // While upscaling (docs/analysis/fsr-plan.md 11), the phases FSR asks for at
  // the ratio, 8 ratio^2 (ffxFsr3UpscalerGetJitterPhaseCount), at most 64.
  const RenderTargetCache& rt_cache = *command_processor_.render_target_cache_;
  if (rt_cache.IsSceneUpscaled()) {
    // The ratio as a fraction, exact: out / in = (n_out d_in) / (d_out n_in).
    const uint64_t a = uint64_t(rt_cache.scene_draw_scale().numerator) *
                       rt_cache.scene_input_scale().denominator;
    const uint64_t b = uint64_t(rt_cache.scene_draw_scale().denominator) *
                       rt_cache.scene_input_scale().numerator;
    phases = uint32_t(std::clamp(uint64_t(8) * a * a / (b * b), uint64_t(phases),
                                 uint64_t(post_pass::kMaxJitterPhases)));
  }
  if (mode != "auto" && !mode.empty()) {
    // A number of phases: every frame after one with a scene, without a consumer.
    double forced;
    if (!ParseNumber(mode, forced) ||
        !(forced >= 1.0 && forced <= double(post_pass::kMaxJitterPhases))) {
      if (!warned_jitter_) {
        warned_jitter_ = true;
        REXGPU_WARN("Post passes: post_pass_jitter={} is not auto, off or 1 to {} phases", mode,
                    post_pass::kMaxJitterPhases);
      }
      return;
    }
    phases = uint32_t(forced);
    if (scene_frame_ != frame) {
      return;
    }
  } else {
    // The manifest's: after a frame in which its consumer ran with a known view
    // (every frame without one is a history cut, so a jitter could not
    // accumulate), while its if holds, the camera moves and the frames come
    // fast enough, or with still the camera is still (JitterGate).
    if (!manifest.jitter || jitter_consumer_frame_ != frame || !previous_scene_ ||
        !previous_camera_.view_known) {
      return;
    }
    const bool every_frame = !manifest.jitter_every_frame_conditions.empty() &&
                             ConditionsHold(manifest.jitter_every_frame_conditions);
    if (!ConditionsHold(manifest.jitter_conditions) ||
        !(every_frame || jitter_gate_.Armed(settings))) {
      return;
    }
    jitter_still_ = !every_frame && jitter_gate_.Still(settings);
  }
  // x,y in host pixels, or the Halton (2, 3) sequence.
  const std::string& offset = REXCVAR_GET(post_pass_jitter_offset);
  size_t comma = offset.find(',');
  double x, y;
  if (!offset.empty() && comma != std::string::npos && ParseNumber(offset.substr(0, comma), x) &&
      ParseNumber(offset.substr(comma + 1), y)) {
    jitter_[0] = float(std::clamp(x, -0.5, 0.5));
    jitter_[1] = float(std::clamp(y, -0.5, 0.5));
  } else {
    jitter_phase_ = uint32_t(jitter_count_ % phases);
    jitter_phases_ = phases;
    post_pass::JitterOffset(jitter_phase_, jitter_);
  }
  ++jitter_count_;
  jitter_active_ = true;
}

uint32_t PostPasses::GuestSceneWidth() const {
  const uint32_t logical = command_processor_.render_target_cache_->scene_logical_width();
  return depth_group_.pitch == 1280 && command_processor_.render_target_cache_->scene_textures()
             ? logical
             : depth_group_.pitch;
}

uint32_t PostPasses::GuestSceneHeight() const {
  const uint32_t logical = command_processor_.render_target_cache_->scene_logical_height();
  return depth_group_.height == 720 && command_processor_.render_target_cache_->scene_textures()
             ? logical
             : depth_group_.height;
}

post_pass::Viewport PostPasses::LogicalViewport(post_pass::Viewport viewport) const {
  const RenderTargetCache& cache = *command_processor_.render_target_cache_;
  if (cache.scene_textures()) {
    viewport.x_offset += float(cache.scene_logical_width() - 1280) * 0.5f;
    viewport.y_offset += float(cache.scene_logical_height() - 720) * 0.5f;
  }
  return viewport;
}

bool PostPasses::IsAfterFinal() const {
  // After the final combine's draw itself: once the final point has run.
  return final_frame_ == command_processor_.GetCurrentFrame() && !final_pending_;
}

bool PostPasses::DrawJitter(const RegisterFile& regs, uint64_t vertex_shader_hash,
                            const reg::RB_DEPTHCONTROL& depth_control, bool rectangle,
                            float jitter_out[2]) const {
  if (!jitter_active_ || !manifest_) {
    return false;
  }
  post_pass::JitterDraw draw;
  // The scene camera's test: the depth buffer resolved as the scene depth last.
  const auto depth_info = regs.Get<reg::RB_DEPTH_INFO>();
  draw.depth_base = depth_info.depth_base | depth_info.depth_base_bit_11 << 11;
  draw.scene_depth_known = depth_group_.frame != UINT64_MAX;
  draw.scene_depth_base = depth_group_.edram_base;
  draw.depth_or_stencil = depth_control.z_enable || depth_control.stencil_enable;
  draw.rectangle = rectangle;
  const std::vector<uint64_t>& exclude = manifest_->jitter_exclude;
  draw.excluded = std::find(exclude.begin(), exclude.end(), vertex_shader_hash) != exclude.end();
  draw.after_final = final_frame_ == command_processor_.GetCurrentFrame();
  if (!post_pass::IsJitteredDraw(draw)) {
    return false;
  }
  jitter_out[0] = jitter_[0];
  jitter_out[1] = jitter_[1];
  return true;
}

void PostPasses::OnSwap() {
  if (final_pending_) {
    RunPoint(Point::kFinal);
  }
  DeferredCommandList& list = command_processor_.GetDeferredCommandList();
  if (manifest_) {
    // The exposed outputs are of this frame's scene only.
    const UINT zero[4] = {};
    for (size_t i = 0; i < textures_.size(); ++i) {
      Texture& texture = textures_[i];
      if (!manifest_->textures[i].clear || !texture.written || !texture.resource) continue;
      texture.written = false;
      Transition(texture.resource.Get(), texture.state, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
      command_processor_.SubmitBarriers();
      list.D3DClearUnorderedAccessViewUint(Gpu(texture.uavs[0]),
                                           LocalCpu(DescriptorKind::kCpu, texture.clear_uav),
                                           texture.resource.Get(), zero, 0, nullptr);
      Transition(texture.resource.Get(), texture.state, kShaderResource);
    }
    command_processor_.SubmitBarriers();
    UpdateReactiveMark();
  }
  // This frame's scene becomes the history, or the history ends.
  uint64_t frame = command_processor_.GetCurrentFrame();
  // A history texture written in this frame becomes the previous frame's.
  for (size_t i = 0; manifest_ && i < textures_.size(); ++i) {
    if (!manifest_->textures[i].history) continue;
    bool written = textures_[i].written_frame == frame && textures_[i].resource;
    if (written) std::swap(textures_[i], previous_textures_[i]);
    previous_texture_ready_[i] = written;
  }
  if (history_written_) {
    history_written_ = false;
    history_write_ ^= 1;
    previous_valid_ = true;
    previous_width_ = scene_width_;
    previous_height_ = scene_height_;
  } else {
    previous_valid_ = false;
  }
  // The camera and the motion objects of every frame with a scene, also
  // without history textures.
  previous_scene_ = manifest_ && scene_frame_ == frame && camera_.valid;
  if (previous_scene_) {
    previous_camera_ = camera_;
    previous_camera_.view_known = camera_.view_frame == frame;
    for (uint32_t slot = 0; slot < post_pass::kMotionSlots; ++slot) {
      previous_motion_objects_[slot] =
          motion_objects_[slot].frame == frame ? motion_objects_[slot] : MotionObject();
    }
    previous_interior_ = interior_.frame == frame ? interior_ : MotionObject();
  } else {
    previous_motion_objects_.fill(MotionObject());
    previous_interior_ = MotionObject();
  }

  uint64_t completed = command_processor_.GetCompletedSubmission();
  std::erase_if(retired_, [completed](const auto& retired) { return retired.first <= completed; });
  std::erase_if(retired_fsr_,
                [completed](const auto& retired) { return retired.first <= completed; });
  ReleasePendingDescriptors(false);

  // Defines changed by shader_mod_set: params at once, defines recompile.
  uint64_t generation = overrides_.defines_generation();
  if (generation != defines_generation_) {
    defines_generation_ = generation;
    if (manifest_ && ResolveDefines(*manifest_) != manifest_->compiled_defines) {
      Reload("defines changed");
    }
  }
  if (hot_reload_) {
    PollFiles();
  }
  // After a reload, so that the jitter follows the manifest in use.
  UpdateJitter();
}

