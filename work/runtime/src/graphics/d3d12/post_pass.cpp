bool PostPasses::LoadManifest(Manifest& manifest) {
  std::filesystem::path path = directory_ / kManifestName;
  std::string file_name = path.generic_string();
  auto fail = [&file_name](const std::string& message) {
    REXGPU_ERROR("Post passes: {}: {}", file_name, message);
    return false;
  };
  std::string text;
  if (!ReadFile(path, text)) {
    return fail("cannot read the file");
  }
  manifest.files.push_back({kManifestName, path, HashBytes(text.data(), text.size())});
  toml::table root;
  try {
    root = toml::parse(text, file_name);
  } catch (const toml::parse_error& error) {
    return fail(fmt::format("line {}: {}", error.source().begin.line, error.description()));
  }

  // [scene]
  if (const toml::table* scene = root["scene"].as_table()) {
    if (const toml::array* camera = (*scene)["camera"].as_array()) {
      for (const toml::node& node : *camera) {
        // <hash>:rows:<wvp>:<wv>(:<world>) or <hash>:world:<wvp>:<world>:<view inverse>;
        // the hash * makes it the fallback for other vertex shaders.
        std::string source = node.value_or(std::string());
        std::vector<std::string> fields;
        std::istringstream parts(source);
        for (std::string field; std::getline(parts, field, ':');) fields.push_back(field);
        CameraSource camera_source = {};
        bool valid = fields.size() >= 4;
        if (valid) {
          camera_source.vertex_shader_hash =
              fields[0] == "*" ? 0 : std::strtoull(fields[0].c_str(), nullptr, 16);
          if (fields[1] == "rows" && fields.size() == 4) {
            camera_source.layout = post_pass::CameraLayout::kWvpWvRows;
          } else if (fields[1] == "rows" && fields.size() == 5) {
            camera_source.layout = post_pass::CameraLayout::kWvpWvWorldRows;
          } else if (fields[1] == "world" && fields.size() == 5) {
            camera_source.layout = post_pass::CameraLayout::kWvpWorldViewInverse;
          } else {
            valid = false;
          }
        }
        for (size_t i = 2; valid && i < fields.size(); ++i) {
          camera_source.constants[i - 2] = uint32_t(std::strtoul(fields[i].c_str(), nullptr, 10));
          valid = camera_source.constants[i - 2] < 256;
        }
        if (!valid) {
          return fail(fmt::format("invalid scene camera '{}'", source));
        }
        if (fields[0] == "*") {
          manifest.has_camera_fallback = true;
          manifest.camera_fallback = camera_source;
        } else {
          manifest.camera_sources.push_back(camera_source);
        }
      }
    }
    double min_width;
    if (NodeNumber((*scene)["min_width"].node(), min_width)) {
      manifest.min_width = uint32_t(std::clamp(min_width, 1.0, 8192.0));
    }
    if (const toml::array* finals = (*scene)["final_pixel_shaders"].as_array()) {
      for (const toml::node& node : *finals) {
        manifest.final_pixel_shaders.push_back(
            std::strtoull(node.value_or(std::string()).c_str(), nullptr, 16));
      }
    }
  }
  // [history]
  if (const toml::table* history = root["history"].as_table()) {
    double value;
    if (NodeNumber((*history)["cut_distance"].node(), value)) manifest.cut_distance = float(value);
    if (NodeNumber((*history)["cut_angle"].node(), value)) manifest.cut_angle = float(value);
    if (NodeNumber((*history)["cut_focal"].node(), value)) manifest.cut_focal = float(value);
  }
  // [motion]
  if (const toml::table* motion = root["motion"].as_table()) {
    auto parse_sources = [&](const char* key, std::vector<MotionSource>& sources) {
      const toml::array* objects = (*motion)[key].as_array();
      if (!objects) {
        return true;
      }
      for (const toml::node& node : *objects) {
        // <hash>:rows:<world> or <hash>:columns:<world>.
        std::string text = node.value_or(std::string());
        std::vector<std::string> fields;
        std::istringstream parts(text);
        for (std::string field; std::getline(parts, field, ':');) fields.push_back(field);
        MotionSource source = {};
        bool valid = fields.size() == 3 && (fields[1] == "rows" || fields[1] == "columns");
        if (valid) {
          source.vertex_shader_hash = std::strtoull(fields[0].c_str(), nullptr, 16);
          source.layout = fields[1] == "rows" ? post_pass::WorldLayout::kRows
                                              : post_pass::WorldLayout::kColumns;
          source.constant = uint32_t(std::strtoul(fields[2].c_str(), nullptr, 10));
          valid = source.constant + (fields[1] == "rows" ? 4 : 3) <= 256;
        }
        if (!valid) {
          return fail(fmt::format("invalid motion {} '{}'", key, text));
        }
        sources.push_back(source);
      }
      if (sources.size() > kMaxMotionSources) {
        return fail(fmt::format("more than {} motion {}", kMaxMotionSources, key));
      }
      return true;
    };
    if (!parse_sources("objects", manifest.motion_sources) ||
        !parse_sources("interior", manifest.interior_sources)) {
      return false;
    }
    double interior_depth = 1.0;
    NodeNumber((*motion)["interior_depth"].node(), interior_depth);
    manifest.interior_depth = float(interior_depth);
    double step = 1.0, limit = 256.0;
    NodeNumber((*motion)["stencil_step"].node(), step);
    NodeNumber((*motion)["stencil_limit"].node(), limit);
    if (!(step >= 1.0 && step <= 255.0 && limit >= 1.0 && limit <= 256.0)) {
      return fail("motion: stencil_step is 1 to 255, stencil_limit 1 to 256");
    }
    manifest.motion_stencil_step = uint32_t(step);
    manifest.motion_stencil_limit = uint32_t(limit);
    // The slot of the highest stencil value below the limit.
    uint32_t last = (2 * (manifest.motion_stencil_limit - 1) + manifest.motion_stencil_step) /
                    (2 * manifest.motion_stencil_step);
    // The last slot is the interior's.
    if (last >= post_pass::kMotionInteriorSlot) {
      return fail(fmt::format("motion: stencil values below {} give slots above {}",
                              manifest.motion_stencil_limit, post_pass::kMotionInteriorSlot - 1));
    }
    manifest.motion_slot_count = last + 1;
  }
  // [defines]
  if (const toml::table* defines = root["defines"].as_table()) {
    for (auto&& [key, node] : *defines) {
      std::string value;
      if (!DefineText(node, value)) {
        return fail(fmt::format("define {} is not a number or a string", key.str()));
      }
      manifest.defines.emplace_back(std::string(key.str()), value);
    }
  }
  // [params]
  auto find_param = [&manifest](std::string_view name) -> uint32_t {
    for (size_t i = 0; i < manifest.params.size(); ++i) {
      if (manifest.params[i].name == name) return uint32_t(i);
    }
    return UINT32_MAX;
  };
  std::vector<std::pair<uint32_t, std::string>> focal_sources;
  if (const toml::table* params = root["params"].as_table()) {
    for (auto&& [key, node] : *params) {
      ParamDesc param;
      param.name = key.str();
      const toml::node* value = &node;
      if (const toml::table* fields = node.as_table()) {
        if (auto source = (*fields)["focal_length_of"].value<std::string>()) {
          focal_sources.emplace_back(uint32_t(manifest.params.size()), *source);
        }
        value = (*fields)["value"].node();
        NodeNumber((*fields)["min"].node(), param.min);
        NodeNumber((*fields)["max"].node(), param.max);
      }
      if (value) {
        param.is_uint = value->is_integer();
        if (!NodeNumber(value, param.value) || (param.is_uint && param.value < 0.0)) {
          return fail(fmt::format("param {} is not a number (unsigned if an integer)", param.name));
        }
      } else if (focal_sources.empty() || focal_sources.back().first != manifest.params.size()) {
        return fail(fmt::format("param {} has no value", param.name));
      }
      manifest.params.push_back(param);
    }
  }
  for (const auto& [index, source] : focal_sources) {
    uint32_t source_index = find_param(source);
    if (source_index == UINT32_MAX || manifest.params[source_index].is_uint) {
      return fail(fmt::format("focal_length_of of {} names no float param",
                              manifest.params[index].name));
    }
    manifest.params[index].focal_length_of = source_index;
  }
  if (manifest.params.size() > post_pass::kMaxParams) {
    return fail(fmt::format("more than {} params", post_pass::kMaxParams));
  }
  // [textures.<name>]
  auto find_texture = [&manifest](std::string_view name) -> uint32_t {
    for (size_t i = 0; i < manifest.textures.size(); ++i) {
      if (manifest.textures[i].name == name) return uint32_t(i);
    }
    return UINT32_MAX;
  };
  if (const toml::table* textures = root["textures"].as_table()) {
    for (auto&& [key, node] : *textures) {
      const toml::table* fields = node.as_table();
      if (!fields) {
        return fail(fmt::format("texture {} is not a table", key.str()));
      }
      TextureDesc texture;
      texture.name = key.str();
      std::string format = (*fields)["format"].value_or(std::string());
      for (const FormatName& entry : kFormats) {
        if (format == entry.name) texture.format = entry.format;
      }
      if (texture.format == DXGI_FORMAT_UNKNOWN) {
        return fail(fmt::format("texture {}: unknown format '{}'", texture.name, format));
      }
      double number;
      if (NodeNumber((*fields)["mips"].node(), number)) {
        texture.mips = uint32_t(std::clamp(number, 1.0, double(kMaxMips)));
      }
      if (NodeNumber((*fields)["scale"].node(), number)) {
        if (!(number > 0.0 && number <= 4.0)) {
          return fail(fmt::format("texture {}: scale must be above 0 and at most 4", texture.name));
        }
        texture.scale = float(number);
      }
      std::string size = (*fields)["size"].value_or(std::string("scene"));
      if (size != "scene" && size != "final" && size != "output") {
        return fail(fmt::format("texture {}: size is scene, final or output", texture.name));
      }
      texture.final_size = size == "final";
      texture.output_size = size == "output";
      if (NodeNumber((*fields)["slot"].node(), number)) {
        if (number < 0.0 || number >= double(D3D12CommandProcessor::kPostPassViewCount)) {
          return fail(fmt::format("texture {}: slot must be 0 to {}", texture.name,
                                  D3D12CommandProcessor::kPostPassViewCount - 1));
        }
        texture.slot = int32_t(number);
        for (const TextureDesc& other : manifest.textures) {
          if (other.slot == texture.slot) {
            return fail(fmt::format("textures {} and {} share slot {}", other.name, texture.name,
                                    texture.slot));
          }
        }
      }
      texture.clear = (*fields)["clear"].value_or(false);
      texture.history = (*fields)["history"].value_or(false);
      if (texture.history && (texture.slot >= 0 || texture.clear)) {
        return fail(fmt::format("texture {}: a history texture has no slot and is not cleared",
                                texture.name));
      }
      texture.write_back = (*fields)["write_back"].value_or(false);
      if (texture.write_back &&
          (texture.format != DXGI_FORMAT_R10G10B10A2_UNORM || texture.final_size ||
           texture.scale != 1.0f || texture.mips != 1 || texture.history)) {
        return fail(fmt::format(
            "texture {}: a write_back texture is R10G10B10A2_UNORM, scene or output sized, "
            "unscaled, one mip and no history",
            texture.name));
      }
      manifest.uses_write_back |= texture.write_back;
      texture.reactive_mark = (*fields)["reactive_mark"].value_or(false);
      if (texture.reactive_mark) {
        if (texture.format != DXGI_FORMAT_R8_UNORM || texture.final_size || texture.output_size ||
            texture.scale != 1.0f || texture.mips != 1 || texture.history || texture.slot >= 0 ||
            texture.clear || texture.write_back || manifest.reactive_mark != UINT32_MAX) {
          return fail(fmt::format(
              "texture {}: the reactive_mark texture is R8_UNORM, scene sized, unscaled, one mip, "
              "not history, slot, clear or write_back, and the only one",
              texture.name));
        }
        // Written by the overrides as a UAV, cleared by UpdateReactiveMark.
        texture.uav = texture.clear = true;
        manifest.reactive_mark = uint32_t(manifest.textures.size());
      }
      manifest.textures.push_back(texture);
    }
  }

  // NAME OP NUMBER [&& ...] over params and defines: a pass's if, [jitter] if.
  auto parse_conditions = [&](const std::string& text, std::vector<Condition>& conditions,
                              std::string& error) {
    std::string rest = text;
    while (!rest.empty()) {
      size_t and_position = rest.find("&&");
      std::string term = rest.substr(0, and_position);
      rest = and_position == std::string::npos ? std::string() : rest.substr(and_position + 2);
      static const std::pair<const char*, Condition::Op> kOps[] = {
          {"==", Condition::Op::kEqual},        {"!=", Condition::Op::kNotEqual},
          {"<=", Condition::Op::kLessEqual},    {">=", Condition::Op::kGreaterEqual},
          {"<", Condition::Op::kLess},          {">", Condition::Op::kGreater}};
      Condition parsed;
      size_t op_position = std::string::npos, op_length = 0;
      for (const auto& [op_text, op] : kOps) {
        size_t found = term.find(op_text);
        if (found != std::string::npos) {
          op_position = found;
          op_length = std::strlen(op_text);
          parsed.op = op;
          break;
        }
      }
      if (op_position == std::string::npos) {
        error = fmt::format("if '{}': NAME OP NUMBER [&& ...]", text);
        return false;
      }
      std::string name = term.substr(0, op_position);
      name.erase(std::remove_if(name.begin(), name.end(),
                                [](char c) { return std::isspace(uint8_t(c)); }),
                 name.end());
      // XE_SCENE: 1 in a frame whose scene points ran (a scene with a camera).
      bool known = find_param(name) != UINT32_MAX || name == "XE_SCENE";
      for (const auto& define : manifest.defines) known |= define.first == name;
      if (!known || !ParseNumber(term.substr(op_position + op_length), parsed.value)) {
        error = fmt::format("if '{}': {} is no param or define, or no number", text, name);
        return false;
      }
      parsed.name = name;
      conditions.push_back(parsed);
    }
    return true;
  };

  // [[passes]]
  auto parse_binding = [&](const std::string& text, Binding& binding) {
    // previous:<history texture>, all its mips.
    if (text.rfind("previous:", 0) == 0) {
      binding.texture = find_texture(text.substr(9));
      binding.previous = true;
      return binding.texture != UINT32_MAX && manifest.textures[binding.texture].history;
    }
    std::string name = text;
    size_t colon = text.find(':');
    if (colon != std::string::npos) {
      name = text.substr(0, colon);
      binding.mip = int32_t(std::strtol(text.c_str() + colon + 1, nullptr, 10));
    }
    static const std::pair<const char*, Builtin> kBuiltins[] = {
        {"scene_depth", Builtin::kSceneDepth},       {"scene_stencil", Builtin::kSceneStencil},
        {"scene_color", Builtin::kSceneColor},       {"previous_color", Builtin::kPreviousColor},
        {"previous_depth", Builtin::kPreviousDepth}, {"final_color", Builtin::kFinalColor}};
    for (const auto& [builtin_name, builtin] : kBuiltins) {
      if (name == builtin_name) {
        binding.builtin = builtin;
        return binding.mip <= 0;
      }
    }
    binding.texture = find_texture(name);
    return binding.texture != UINT32_MAX &&
           binding.mip < int32_t(manifest.textures[binding.texture].mips);
  };
  if (const toml::array* passes = root["passes"].as_array()) {
    for (const toml::node& node : *passes) {
      const toml::table* fields = node.as_table();
      if (!fields) {
        return fail("[[passes]] entries must be tables");
      }
      PassDesc pass;
      pass.name = (*fields)["name"].value_or(std::string());
      if (pass.name.empty()) {
        return fail("a pass has no name");
      }
      for (const PassDesc& other : manifest.passes) {
        if (other.name == pass.name) {
          return fail(fmt::format("two passes are named {}", pass.name));
        }
      }
      auto pass_fail = [&](const std::string& message) {
        return fail(fmt::format("pass {}: {}", pass.name, message));
      };
      std::string point = (*fields)["point"].value_or(std::string());
      if (point == "scene_depth") {
        pass.point = Point::kSceneDepth;
      } else if (point == "scene_color") {
        pass.point = Point::kSceneColor;
      } else if (point == "final") {
        pass.point = Point::kFinal;
      } else {
        return pass_fail("point is scene_depth, scene_color or final");
      }
      std::string type = (*fields)["type"].value_or(std::string("compute"));
      if (type != "compute" && type != "pixel" && type != "fsr") {
        return pass_fail("type is compute, pixel or fsr");
      }
      pass.pixel = type == "pixel";
      pass.fsr = type == "fsr";
      pass.shader = (*fields)["shader"].value_or(std::string());
      pass.entry = (*fields)["entry"].value_or(std::string("main"));
      if (pass.shader.empty() && !pass.fsr) {
        return pass_fail("no shader file");
      }
      if (const toml::table* defines = (*fields)["defines"].as_table()) {
        for (auto&& [key, value] : *defines) {
          std::string text_value;
          if (!DefineText(value, text_value)) {
            return pass_fail(fmt::format("define {} is not a number or a string", key.str()));
          }
          pass.defines.emplace_back(std::string(key.str()), text_value);
        }
      }
      struct List {
        const char* key;
        std::vector<Binding>* bindings;
        uint32_t limit;
      };
      for (const List& list : {List{"srv", &pass.srvs, post_pass::kMaxSrvs},
                               List{"uav", &pass.uavs, post_pass::kMaxUavs},
                               List{"rtv", &pass.rtvs, post_pass::kMaxRenderTargets}}) {
        if (const toml::array* names = (*fields)[list.key].as_array()) {
          for (const toml::node& name_node : *names) {
            std::string name = name_node.value_or(std::string());
            Binding binding;
            if (!parse_binding(name, binding)) {
              return pass_fail(fmt::format("{} '{}' is no texture or input (or no such mip)",
                                           list.key, name));
            }
            list.bindings->push_back(binding);
          }
          if (list.bindings->size() > list.limit) {
            return pass_fail(fmt::format("more than {} in {}", list.limit, list.key));
          }
        }
      }
      if (pass.pixel ? (pass.rtvs.empty() || !pass.uavs.empty())
                     : (pass.uavs.empty() || !pass.rtvs.empty())) {
        return pass_fail("a compute pass writes uav, a pixel pass rtv");
      }
      if (pass.fsr) {
        // FSR's inputs and output (fsr.h): textures of the manifest at the scene_color point.
        bool textures_only = true;
        for (const Binding& binding : pass.srvs) {
          textures_only &= binding.builtin == Builtin::kNone && !binding.previous;
        }
        if (pass.point != Point::kSceneColor || pass.srvs.size() < 3 || pass.srvs.size() > 5 ||
            pass.uavs.size() != 1 || !textures_only || pass.uavs[0].builtin != Builtin::kNone) {
          return pass_fail(
              "an fsr pass runs at scene_color on textures of the manifest: srv [color, depth, "
              "motion vectors, reactive, composition] (the last two optional), uav [output]");
        }
      }
      for (const Binding& output : pass.pixel ? pass.rtvs : pass.uavs) {
        bool final_write = output.builtin == Builtin::kFinalColor && pass.pixel &&
                           pass.point == Point::kFinal;
        if (output.builtin != Builtin::kNone && !final_write) {
          return pass_fail("only a pixel pass at the final point writes an input (final_color)");
        }
        if (output.previous) {
          return pass_fail("previous:<texture> is read only");
        }
        for (const Binding& input : pass.srvs) {
          if (input.builtin == output.builtin && input.texture == output.texture &&
              !input.previous) {
            return pass_fail("a texture is both read and written");
          }
        }
        if (output.texture != UINT32_MAX) {
          if (manifest.textures[output.texture].write_back && pass.point != Point::kSceneColor) {
            return pass_fail("a write_back texture is written at the scene_color point only");
          }
          (pass.pixel ? manifest.textures[output.texture].rtv
                      : manifest.textures[output.texture].uav) = true;
        }
      }
      for (const Binding& input : pass.srvs) {
        switch (input.builtin) {
          case Builtin::kSceneColor:
            if (pass.point == Point::kSceneDepth) {
              return pass_fail("scene_color is complete at scene_color and final only");
            }
            manifest.uses_scene_color = true;
            break;
          case Builtin::kFinalColor:
            if (pass.point != Point::kFinal) {
              return pass_fail("final_color is read at the final point only");
            }
            break;
          case Builtin::kPreviousColor:
            manifest.uses_previous_color = true;
            break;
          case Builtin::kPreviousDepth:
            manifest.uses_previous_depth = true;
            break;
          case Builtin::kSceneStencil:
            manifest.uses_scene_stencil = true;
            break;
          default:
            break;
        }
      }
      if (const toml::array* group = (*fields)["group"].as_array()) {
        double x, y;
        if (group->size() != 2 || !NodeNumber(group->get(0), x) || !NodeNumber(group->get(1), y) ||
            x < 1.0 || y < 1.0) {
          return pass_fail("group is [pixels x, pixels y] per thread group");
        }
        pass.group[0] = uint32_t(x);
        pass.group[1] = uint32_t(y);
      }
      if (auto size = (*fields)["size"].value<std::string>()) {
        if (!parse_binding(*size, pass.size)) {
          return pass_fail(fmt::format("size '{}' is no texture or input", *size));
        }
      } else {
        pass.size = pass.pixel ? pass.rtvs[0] : pass.uavs[0];
      }
      if (auto condition = (*fields)["if"].value<std::string>()) {
        std::string error;
        if (!parse_conditions(*condition, pass.conditions, error)) {
          return pass_fail(error);
        }
      }
      std::string blend = (*fields)["blend"].value_or(std::string("none"));
      static const std::pair<const char*, Blend> kBlends[] = {{"none", Blend::kNone},
                                                              {"alpha", Blend::kAlpha},
                                                              {"add", Blend::kAdd},
                                                              {"multiply", Blend::kMultiply}};
      bool blend_known = false;
      for (const auto& [blend_name, blend_mode] : kBlends) {
        if (blend == blend_name) {
          pass.blend = blend_mode;
          blend_known = true;
        }
      }
      if (!blend_known) {
        return pass_fail("blend is none, alpha, add or multiply");
      }
      manifest.uses_point[size_t(pass.point)] = true;
      manifest.passes.push_back(std::move(pass));
    }
  }
  for (const TextureDesc& texture : manifest.textures) {
    if (texture.clear && !texture.uav && !texture.rtv && !texture.reactive_mark) {
      return fail(fmt::format("texture {} is cleared but no pass writes it", texture.name));
    }
  }
  // [jitter]
  if (const toml::table* jitter = root["jitter"].as_table()) {
    manifest.jitter = true;
    double phases = 8.0;
    NodeNumber((*jitter)["phases"].node(), phases);
    if (!(phases >= 1.0 && phases <= double(post_pass::kMaxJitterPhases))) {
      return fail(fmt::format("jitter: phases is 1 to {}", post_pass::kMaxJitterPhases));
    }
    manifest.jitter_phases = uint32_t(phases);
    if (auto condition = (*jitter)["if"].value<std::string>()) {
      std::string error;
      if (!parse_conditions(*condition, manifest.jitter_conditions, error)) {
        return fail("jitter: " + error);
      }
    }
    if (auto condition = (*jitter)["every_frame_if"].value<std::string>()) {
      std::string error;
      if (!parse_conditions(*condition, manifest.jitter_every_frame_conditions, error)) {
        return fail("jitter: " + error);
      }
    }
    // The passes whose run in a frame arms the jitter of the next one: a name
    // or a list of them (one per point TAA can run at).
    if (const toml::array* consumers = (*jitter)["consumer"].as_array()) {
      for (const toml::node& node : *consumers) {
        manifest.jitter_consumers.push_back(node.value_or(std::string()));
      }
    } else {
      manifest.jitter_consumers.push_back((*jitter)["consumer"].value_or(std::string()));
    }
    for (const std::string& consumer : manifest.jitter_consumers) {
      bool consumer_found = false;
      for (const PassDesc& pass : manifest.passes) {
        consumer_found |= pass.name == consumer;
      }
      if (!consumer_found) {
        return fail(fmt::format("jitter: consumer '{}' names no pass", consumer));
      }
    }
    if (const toml::array* exclude = (*jitter)["exclude"].as_array()) {
      for (const toml::node& node : *exclude) {
        manifest.jitter_exclude.push_back(
            std::strtoull(node.value_or(std::string()).c_str(), nullptr, 16));
      }
    }
    // While the camera moves and the frames come fast enough, and with still
    // on a still camera: a number, or a float param that changes live.
    auto threshold = [&](const char* key, double& value, uint32_t& param) {
      const toml::node* node = (*jitter)[key].node();
      if (!node) return true;
      if (const auto* name = node->as_string()) {
        param = find_param(name->get());
        if (param == UINT32_MAX || manifest.params[param].is_uint) {
          return fail(fmt::format("jitter: {} '{}' names no float param", key, name->get()));
        }
        return true;
      }
      if (!NodeNumber(node, value)) {
        return fail(fmt::format("jitter: {} is a number or a param name", key));
      }
      return true;
    };
    if (!threshold("min_motion", manifest.jitter_min_motion, manifest.jitter_min_motion_param) ||
        !threshold("min_frame_rate", manifest.jitter_min_frame_rate,
                   manifest.jitter_min_frame_rate_param) ||
        !threshold("still", manifest.jitter_still, manifest.jitter_still_param)) {
      return false;
    }
    double distance = manifest.jitter_motion_distance, hold = manifest.jitter_motion_hold;
    NodeNumber((*jitter)["motion_distance"].node(), distance);
    NodeNumber((*jitter)["motion_hold"].node(), hold);
    if (!(distance > 0.0) || !(hold >= 1.0 && hold <= 1024.0)) {
      return fail("jitter: motion_distance is above 0, motion_hold 1 to 1024 frames");
    }
    manifest.jitter_motion_distance = distance;
    manifest.jitter_motion_hold = uint32_t(hold);
  }
  return true;
}

std::vector<std::pair<std::string, std::string>> PostPasses::ResolveDefines(
    const Manifest& manifest) const {
  std::vector<std::pair<std::string, std::string>> defines = manifest.defines;
  for (auto& define : defines) {
    overrides_.GetDefine(define.first, define.second);
  }
  return defines;
}

bool PostPasses::CompileManifest(Manifest& manifest) {
  manifest.compiled_defines = ResolveDefines(manifest);
  // The params as fields of b1 (XE_POST_PASS_PARAMS).
  std::string params;
  for (const ParamDesc& param : manifest.params) {
    params += fmt::format(" {} {};", param.is_uint ? "uint" : "float", param.name);
  }
  auto add_files = [&manifest](const std::vector<ShaderOverrides::Dependency>& files) {
    for (const auto& file : files) {
      auto same = [&file](const ShaderOverrides::Dependency& known) {
        return known.path == file.path;
      };
      if (std::find_if(manifest.files.begin(), manifest.files.end(), same) ==
          manifest.files.end()) {
        manifest.files.push_back(file);
      }
    }
  };
  const ui::d3d12::D3D12Provider& provider = command_processor_.GetD3D12Provider();
  ID3D12Device* device = provider.GetDevice();
  auto start = std::chrono::steady_clock::now();
  bool compiled = true;
  bool any_pixel = false;
  for (size_t i = 0; i < manifest.passes.size(); ++i) {
    PassDesc& pass = manifest.passes[i];
    if (pass.fsr) continue;
    any_pixel |= pass.pixel;
    std::vector<std::pair<std::string, std::string>> defines = manifest.compiled_defines;
    for (const auto& define : pass.defines) {
      auto same = [&define](const auto& known) { return known.first == define.first; };
      auto existing = std::find_if(defines.begin(), defines.end(), same);
      if (existing != defines.end()) {
        existing->second = define.second;
      } else {
        defines.push_back(define);
      }
    }
    // The same shader, entry and defines as an earlier pass: the same binary.
    for (size_t j = 0; j < i && pass.bytecode.empty(); ++j) {
      const PassDesc& earlier = manifest.passes[j];
      if (earlier.shader == pass.shader && earlier.entry == pass.entry &&
          earlier.pixel == pass.pixel && earlier.defines == pass.defines &&
          !earlier.bytecode.empty()) {
        pass.bytecode = earlier.bytecode;
      }
    }
    if (pass.bytecode.empty()) {
      std::string source =
          fmt::format("#define XE_POST_PASS_PARAMS{}\n#include \"{}\"\n#include \"{}\"\n", params,
                      kLibraryName, pass.shader);
      std::vector<ShaderOverrides::Dependency> files;
      bool result = overrides_.CompileProgram(
          source, fmt::format("{}:{}", kManifestName, pass.name), pass.entry,
          pass.pixel ? "ps_5_1" : "cs_5_1", kCompileFlags, defines, directory_, kLibraryName,
          Library(), pass.bytecode, files);
      add_files(files);
      if (!result) {
        compiled = false;
        continue;
      }
    }
    if (!pass.pixel) {
      pass.pipeline.Attach(ui::d3d12::util::CreateComputePipeline(
          device, pass.bytecode.data(), pass.bytecode.size(), root_signature_.Get()));
      if (!pass.pipeline) {
        REXGPU_ERROR("Post passes: failed to create the pipeline of {}", pass.name);
        compiled = false;
      }
    }
  }
  if (any_pixel && compiled) {
    std::vector<ShaderOverrides::Dependency> files;
    compiled = overrides_.CompileProgram(
        fmt::format("#include \"{}\"\n", kLibraryName), "xe_post_pass_vs", "xe_post_pass_vs",
        "vs_5_1", kCompileFlags, {{"XE_POST_PASS_VERTEX_SHADER", "1"}}, directory_, kLibraryName,
        Library(), manifest.vertex_shader, files);
  }
  if (!compiled) {
    return false;
  }
  REXGPU_INFO(
      "Post passes: {} passes, {} textures, {} params from {} in {:.1f} ms; {} scene camera "
      "vertex shader{}{}, {} motion object vertex shader{} ({} slots), {} interior{}{}",
      manifest.passes.size(), manifest.textures.size(), manifest.params.size(),
      directory_.generic_string(),
      std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - start).count(),
      manifest.camera_sources.size(), manifest.camera_sources.size() == 1 ? "" : "s",
      manifest.has_camera_fallback ? " and a fallback layout" : "",
      manifest.motion_sources.size(), manifest.motion_sources.size() == 1 ? "" : "s",
      manifest.motion_slot_count, manifest.interior_sources.size(),
      manifest.uses_previous_color || manifest.uses_previous_depth ? ", history" : "",
      manifest.uses_point[size_t(Point::kFinal)] ? ", final point" : "");
  if (manifest.camera_sources.empty() && !manifest.has_camera_fallback) {
    REXGPU_WARN("Post passes: no scene camera vertex shaders, the scene points won't run");
  }
  return true;
}

void PostPasses::Reload(const char* reason) {
  auto manifest = std::make_unique<Manifest>();
  bool loaded = LoadManifest(*manifest) && CompileManifest(*manifest);
  // Watch what this attempt read, so the next save tries again.
  auto files = manifest->files;
  if (!loaded) {
    REXGPU_ERROR("Post passes: reload ({}) failed, {}", reason,
                 manifest_ ? "the previous passes stay" : "no passes");
    for (const auto& file : files) {
      auto same = [&file](const auto& watched) { return watched.first == file.path; };
      if (std::find_if(watched_.begin(), watched_.end(), same) == watched_.end()) {
        ShaderOverrides::FileState state;
        ShaderOverrides::RefreshFileState(file.path, state);
        watched_.emplace_back(file.path, state);
      }
    }
    return;
  }
  // New param and define names reach the passes from shader_mod_defines, but
  // only those known at the start change at once with shader_mod_set.
  uint64_t submission = command_processor_.GetCurrentSubmission();
  if (manifest_) {
    for (PassDesc& pass : manifest_->passes) {
      if (pass.pipeline) retired_.emplace_back(submission, std::move(pass.pipeline));
    }
  }
  ReleaseTextures();
  manifest_ = std::move(manifest);
  textures_.assign(manifest_->textures.size(), Texture());
  previous_textures_.assign(manifest_->textures.size(), Texture());
  previous_texture_ready_.assign(manifest_->textures.size(), false);
  if (!manifest_->uses_previous_color) {
    ReleaseHistory(history_color_[0]);
    ReleaseHistory(history_color_[1]);
  }
  if (!manifest_->uses_previous_depth) {
    ReleaseHistory(history_depth_[0]);
    ReleaseHistory(history_depth_[1]);
  }
  previous_valid_ = false;
  previous_scene_ = false;
  // The slots may have changed.
  motion_objects_.fill(MotionObject());
  previous_motion_objects_.fill(MotionObject());
  interior_ = MotionObject();
  previous_interior_ = MotionObject();
  motion_ = {};
  params_valid_ = false;
  watched_.clear();
  for (const auto& file : files) {
    ShaderOverrides::FileState state;
    ShaderOverrides::RefreshFileState(file.path, state);
    watched_.emplace_back(file.path, state);
  }
  REXGPU_INFO("Post passes: reloaded ({})", reason);
}

void PostPasses::PollFiles() {
  auto now = std::chrono::steady_clock::now();
  if (now - last_poll_ < std::chrono::milliseconds(250)) {
    return;
  }
  last_poll_ = now;
  bool changed = false;
  for (auto& [path, state] : watched_) {
    changed |= ShaderOverrides::RefreshFileState(path, state);
  }
  changed |= ShaderOverrides::RefreshFileState(directory_ / kManifestName, manifest_file_);
  if (changed) {
    Reload("files changed");
  }
}

