void PostPasses::TextureSize(const TextureDesc& desc, uint32_t& width, uint32_t& height) const {
  uint32_t base_width =
      desc.final_size ? final_width_ : (desc.output_size ? output_width_ : scene_width_);
  uint32_t base_height =
      desc.final_size ? final_height_ : (desc.output_size ? output_height_ : scene_height_);
  width = height = 0;
  if (base_width && base_height) {
    width = std::max(uint32_t(std::lround(double(base_width) * desc.scale)), uint32_t(1));
    height = std::max(uint32_t(std::lround(double(base_height) * desc.scale)), uint32_t(1));
  }
}

std::string PostPasses::HistoryTexturesSummary() const {
  // The history textures of the manifest: whether the previous frame wrote each,
  // and its size against the one this frame needs.
  std::string summary;
  for (size_t i = 0; manifest_ && i < previous_textures_.size(); ++i) {
    const TextureDesc& desc = manifest_->textures[i];
    if (!desc.history) continue;
    uint32_t width, height;
    TextureSize(desc, width, height);
    const Texture& previous = previous_textures_[i];
    summary += fmt::format("{}{} {}{} {}x{}/{}x{}", summary.empty() ? " (" : ", ", desc.name,
                           previous_texture_ready_[i] ? "ready" : "not ready",
                           HistoryTexturesReadThisFrame(i) ? "" : " unread", previous.width,
                           previous.height, width, height);
  }
  return summary.empty() ? summary : summary + ")";
}

bool PostPasses::HistoryTexturesReadThisFrame(size_t texture) const {
  for (const PassDesc& pass : manifest_->passes) {
    if (!PassEnabled(pass)) continue;
    for (const Binding& binding : pass.srvs) {
      if (binding.previous && binding.texture == texture) return true;
    }
  }
  return false;
}

bool PostPasses::HistoryTexturesValid() const {
  // Only the history textures that an enabled pass reads as previous:<name>:
  // the others (taa_scene_history and gtao_history with TAA at the final point)
  // are never written, and with them no pass had a history at all.
  for (size_t i = 0; i < previous_textures_.size(); ++i) {
    const TextureDesc& desc = manifest_->textures[i];
    if (!desc.history || !HistoryTexturesReadThisFrame(i)) continue;
    uint32_t width, height;
    TextureSize(desc, width, height);
    const Texture& previous = previous_textures_[i];
    if (!previous_texture_ready_[i] || !previous.resource || previous.width != width ||
        previous.height != height) {
      return false;
    }
  }
  return true;
}

bool PostPasses::EnsureTexture(uint32_t index, bool previous) {
  const TextureDesc& desc = manifest_->textures[index];
  Texture& texture = previous ? previous_textures_[index] : textures_[index];
  uint32_t width, height;
  TextureSize(desc, width, height);
  if (!width || !height) {
    return false;
  }
  if (texture.resource && texture.width == width && texture.height == height) {
    return true;
  }
  ReleaseTexture(texture, &desc);
  uint32_t mips = 1;
  while (mips < desc.mips && (std::max(width, height) >> mips)) ++mips;
  const ui::d3d12::D3D12Provider& provider = command_processor_.GetD3D12Provider();
  ID3D12Device* device = provider.GetDevice();
  D3D12_RESOURCE_DESC resource_desc = {};
  resource_desc.Dimension = D3D12_RESOURCE_DIMENSION_TEXTURE2D;
  resource_desc.Width = width;
  resource_desc.Height = height;
  resource_desc.DepthOrArraySize = 1;
  resource_desc.MipLevels = UINT16(mips);
  resource_desc.Format = desc.format;
  resource_desc.SampleDesc.Count = 1;
  resource_desc.Layout = D3D12_TEXTURE_LAYOUT_UNKNOWN;
  if (desc.uav || desc.clear) resource_desc.Flags |= D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS;
  if (desc.rtv) resource_desc.Flags |= D3D12_RESOURCE_FLAG_ALLOW_RENDER_TARGET;
  // Zeroed: a texture read before its first pass reads 0.
  if (FAILED(device->CreateCommittedResource(&ui::d3d12::util::kHeapPropertiesDefault,
                                             D3D12_HEAP_FLAG_NONE, &resource_desc,
                                             kShaderResource, nullptr,
                                             IID_PPV_ARGS(&texture.resource)))) {
    REXGPU_ERROR("Post passes: failed to create the {}x{} texture {}", width, height, desc.name);
    return false;
  }
  texture.state = kShaderResource;
  texture.width = width;
  texture.height = height;
  auto fail = [&]() {
    ReleaseTexture(texture, &desc);
    return false;
  };
  auto srv = [&](uint32_t& descriptor, uint32_t first_mip, uint32_t mip_count) {
    descriptor = command_processor_.RequestPersistentViewBindlessDescriptor();
    if (descriptor == UINT32_MAX) return false;
    D3D12_SHADER_RESOURCE_VIEW_DESC srv_desc = {};
    srv_desc.Format = desc.format;
    srv_desc.ViewDimension = D3D12_SRV_DIMENSION_TEXTURE2D;
    srv_desc.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING;
    srv_desc.Texture2D.MostDetailedMip = first_mip;
    srv_desc.Texture2D.MipLevels = mip_count;
    device->CreateShaderResourceView(texture.resource.Get(), &srv_desc, Cpu(descriptor));
    return true;
  };
  if (!srv(texture.srv, 0, mips)) return fail();
  for (uint32_t mip = 0; mips > 1 && mip < mips; ++mip) {
    if (!srv(texture.srv_mips[mip], mip, 1)) return fail();
  }
  D3D12_UNORDERED_ACCESS_VIEW_DESC uav_desc = {};
  uav_desc.Format = desc.format;
  uav_desc.ViewDimension = D3D12_UAV_DIMENSION_TEXTURE2D;
  for (uint32_t mip = 0; (desc.uav || desc.clear) && mip < mips; ++mip) {
    texture.uavs[mip] = command_processor_.RequestPersistentViewBindlessDescriptor();
    if (texture.uavs[mip] == UINT32_MAX) return fail();
    uav_desc.Texture2D.MipSlice = mip;
    device->CreateUnorderedAccessView(texture.resource.Get(), nullptr, &uav_desc,
                                      Cpu(texture.uavs[mip]));
  }
  // Mips a small texture doesn't have alias its last one.
  for (uint32_t mip = mips; mip < desc.mips; ++mip) {
    texture.uavs[mip] = texture.uavs[mips - 1];
    texture.srv_mips[mip] = texture.srv_mips[mips - 1];
  }
  if (desc.clear) {
    texture.clear_uav = AllocateLocal(DescriptorKind::kCpu);
    if (texture.clear_uav == UINT32_MAX) return fail();
    uav_desc.Texture2D.MipSlice = 0;
    device->CreateUnorderedAccessView(texture.resource.Get(), nullptr, &uav_desc,
                                      LocalCpu(DescriptorKind::kCpu, texture.clear_uav));
  }
  for (uint32_t mip = 0; desc.rtv && mip < mips; ++mip) {
    texture.rtvs[mip] = AllocateLocal(DescriptorKind::kRtv);
    if (texture.rtvs[mip] == UINT32_MAX) return fail();
    D3D12_RENDER_TARGET_VIEW_DESC rtv_desc = {};
    rtv_desc.Format = desc.format;
    rtv_desc.ViewDimension = D3D12_RTV_DIMENSION_TEXTURE2D;
    rtv_desc.Texture2D.MipSlice = mip;
    device->CreateRenderTargetView(texture.resource.Get(), &rtv_desc,
                                   LocalCpu(DescriptorKind::kRtv, texture.rtvs[mip]));
  }
  // The view shader mods read. Draws still in flight may read the new
  // texture, which is zeroed.
  if (!previous) {
    WriteSlotView(desc.slot, texture.resource.Get(), desc.format);
  }
  REXGPU_INFO("Post passes: texture {}{} {}x{}, {} mip{}", previous ? "previous:" : "", desc.name,
              width, height, mips, mips == 1 ? "" : "s");
  return true;
}

void PostPasses::ReleaseTexture(Texture& texture, const TextureDesc* desc) {
  uint64_t submission = command_processor_.GetCurrentSubmission();
  if (texture.resource) {
    command_processor_.resources_for_deletion_.emplace_back(submission,
                                                            texture.resource.Detach());
  }
  ReleaseDescriptor(DescriptorKind::kBindless, texture.srv);
  for (uint32_t mip = 0; mip < kMaxMips; ++mip) {
    // Aliases of the last mip are released once.
    bool alias = mip > 0 && texture.uavs[mip] == texture.uavs[mip - 1];
    if (!alias) ReleaseDescriptor(DescriptorKind::kBindless, texture.uavs[mip]);
    texture.uavs[mip] = UINT32_MAX;
    alias = mip > 0 && texture.srv_mips[mip] == texture.srv_mips[mip - 1];
    if (!alias) ReleaseDescriptor(DescriptorKind::kBindless, texture.srv_mips[mip]);
    texture.srv_mips[mip] = UINT32_MAX;
    ReleaseDescriptor(DescriptorKind::kRtv, texture.rtvs[mip]);
  }
  ReleaseDescriptor(DescriptorKind::kCpu, texture.clear_uav);
  texture.state = D3D12_RESOURCE_STATE_COMMON;
  texture.width = texture.height = 0;
  texture.written = false;
}

void PostPasses::ReleaseTextures() {
  for (size_t i = 0; i < textures_.size(); ++i) {
    const TextureDesc* desc = manifest_ ? &manifest_->textures[i] : nullptr;
    if (desc && desc->slot >= 0) {
      WriteSlotView(desc->slot, nullptr, DXGI_FORMAT_R8_UNORM);
    }
    ReleaseTexture(textures_[i], desc);
    if (i < previous_textures_.size()) ReleaseTexture(previous_textures_[i], desc);
  }
  textures_.clear();
  previous_textures_.clear();
  previous_texture_ready_.clear();
}

bool PostPasses::EnsureHistory(History& history, ID3D12Resource* source,
                               const D3D12_SHADER_RESOURCE_VIEW_DESC& srv_desc) {
  D3D12_RESOURCE_DESC desc = source->GetDesc();
  if (history.resource) {
    D3D12_RESOURCE_DESC existing = history.resource->GetDesc();
    if (existing.Width == desc.Width && existing.Height == desc.Height &&
        existing.Format == desc.Format && existing.MipLevels == desc.MipLevels &&
        existing.DepthOrArraySize == desc.DepthOrArraySize &&
        !std::memcmp(&history.srv_desc, &srv_desc, sizeof(srv_desc))) {
      return true;
    }
    ReleaseHistory(history);
  }
  desc.Flags = D3D12_RESOURCE_FLAG_NONE;
  ID3D12Device* device = command_processor_.GetD3D12Provider().GetDevice();
  if (FAILED(device->CreateCommittedResource(&ui::d3d12::util::kHeapPropertiesDefault,
                                             D3D12_HEAP_FLAG_NONE, &desc, kShaderResource,
                                             nullptr, IID_PPV_ARGS(&history.resource)))) {
    REXGPU_ERROR("Post passes: failed to create a {}x{} history texture", desc.Width,
                 desc.Height);
    return false;
  }
  history.state = kShaderResource;
  history.srv_desc = srv_desc;
  history.srv = command_processor_.RequestPersistentViewBindlessDescriptor();
  if (history.srv == UINT32_MAX) {
    ReleaseHistory(history);
    return false;
  }
  device->CreateShaderResourceView(history.resource.Get(), &srv_desc, Cpu(history.srv));
  REXGPU_INFO("Post passes: history texture {}x{} (DXGI format {})", desc.Width, desc.Height,
              uint32_t(desc.Format));
  return true;
}

void PostPasses::ReleaseHistory(History& history) {
  if (history.resource) {
    command_processor_.resources_for_deletion_.emplace_back(
        command_processor_.GetCurrentSubmission(), history.resource.Detach());
  }
  ReleaseDescriptor(DescriptorKind::kBindless, history.srv);
  history.state = D3D12_RESOURCE_STATE_COMMON;
}

void PostPasses::Transition(ID3D12Resource* resource, D3D12_RESOURCE_STATES& state,
                            D3D12_RESOURCE_STATES new_state) {
  if (state != new_state) {
    command_processor_.PushTransitionBarrier(resource, state, new_state);
    state = new_state;
  }
}

D3D12_GPU_DESCRIPTOR_HANDLE PostPasses::Gpu(uint32_t descriptor) const {
  return command_processor_.GetD3D12Provider().OffsetViewDescriptor(
      command_processor_.GetViewBindlessHeapGPUStart(), descriptor);
}

D3D12_CPU_DESCRIPTOR_HANDLE PostPasses::Cpu(uint32_t descriptor) const {
  return command_processor_.GetD3D12Provider().OffsetViewDescriptor(
      command_processor_.GetViewBindlessHeapCPUStart(), descriptor);
}

D3D12_CPU_DESCRIPTOR_HANDLE PostPasses::LocalCpu(DescriptorKind kind, uint32_t descriptor) const {
  bool rtv = kind == DescriptorKind::kRtv;
  D3D12_CPU_DESCRIPTOR_HANDLE handle =
      (rtv ? rtv_heap_ : cpu_heap_)->GetCPUDescriptorHandleForHeapStart();
  handle.ptr += SIZE_T(descriptor) * (rtv ? rtv_increment_ : cpu_increment_);
  return handle;
}

uint32_t PostPasses::AllocateLocal(DescriptorKind kind) {
  std::vector<uint32_t>& free = kind == DescriptorKind::kRtv ? free_rtvs_ : free_cpu_;
  if (free.empty()) {
    REXGPU_ERROR("Post passes: more than {} local descriptors", kLocalDescriptorCount);
    return UINT32_MAX;
  }
  uint32_t index = free.back();
  free.pop_back();
  return index;
}

void PostPasses::ReleaseDescriptor(DescriptorKind kind, uint32_t& index) {
  if (index != UINT32_MAX) {
    pending_descriptors_.push_back({kind, index, command_processor_.GetCurrentSubmission()});
    index = UINT32_MAX;
  }
}

void PostPasses::ReleasePendingDescriptors(bool all) {
  uint64_t completed = command_processor_.GetCompletedSubmission();
  std::erase_if(pending_descriptors_, [&](const PendingDescriptor& pending) {
    if (!all && pending.submission > completed) return false;
    switch (pending.kind) {
      case DescriptorKind::kBindless:
        command_processor_.ReleaseViewBindlessDescriptorImmediately(pending.index);
        break;
      case DescriptorKind::kRtv:
        free_rtvs_.push_back(pending.index);
        break;
      case DescriptorKind::kCpu:
        free_cpu_.push_back(pending.index);
        break;
    }
    return true;
  });
}

void PostPasses::WriteSlotView(int32_t slot, ID3D12Resource* resource, DXGI_FORMAT format) {
  if (slot < 0) {
    return;
  }
  D3D12_SHADER_RESOURCE_VIEW_DESC srv_desc = {};
  srv_desc.Format = format;
  srv_desc.ViewDimension = D3D12_SRV_DIMENSION_TEXTURE2DARRAY;
  srv_desc.Shader4ComponentMapping =
      resource ? D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING
               : D3D12_ENCODE_SHADER_4_COMPONENT_MAPPING(
                     D3D12_SHADER_COMPONENT_MAPPING_FORCE_VALUE_0,
                     D3D12_SHADER_COMPONENT_MAPPING_FORCE_VALUE_0,
                     D3D12_SHADER_COMPONENT_MAPPING_FORCE_VALUE_0,
                     D3D12_SHADER_COMPONENT_MAPPING_FORCE_VALUE_0);
  srv_desc.Texture2DArray.MipLevels = 1;
  srv_desc.Texture2DArray.ArraySize = 1;
  command_processor_.GetD3D12Provider().GetDevice()->CreateShaderResourceView(
      resource, &srv_desc,
      command_processor_
          .GetSystemBindlessViewHandlePair(D3D12CommandProcessor::SystemBindlessView(
              uint32_t(D3D12CommandProcessor::SystemBindlessView::kPostPassViewsStart) +
              uint32_t(slot)))
          .first);
}

