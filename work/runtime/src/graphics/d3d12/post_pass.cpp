// A define's value as FXC gets it.
bool DefineText(const toml::node& node, std::string& out) {
  if (auto value = node.value_exact<int64_t>()) {
    out = std::to_string(*value);
  } else if (auto number = node.value_exact<double>()) {
    out = fmt::format("{}", *number);
  } else if (auto flag = node.value_exact<bool>()) {
    out = *flag ? "1" : "0";
  } else if (auto text = node.value_exact<std::string>()) {
    out = *text;
  } else {
    return false;
  }
  return true;
}

bool NodeNumber(const toml::node* node, double& out) {
  if (!node) return false;
  if (auto value = node->value_exact<int64_t>()) {
    out = double(*value);
    return true;
  }
  if (auto value = node->value_exact<double>()) {
    out = *value;
    return true;
  }
  return false;
}

