std::unique_ptr<PostPasses> PostPasses::Create(D3D12CommandProcessor& command_processor) {
  if (REXCVAR_GET(post_pass_path).empty()) {
    return nullptr;
  }
  if (!command_processor.bindless_resources_used_ ||
      command_processor.render_target_cache_->GetPath() !=
          RenderTargetCache::Path::kHostRenderTargets) {
    // The consumers are shader mods, which need both too.
    REXGPU_WARN("Post passes need bindless resources and host render targets");
    return nullptr;
  }
  ShaderOverrides* overrides = command_processor.pipeline_cache_->shader_overrides();
  if (!overrides) {
    REXGPU_ERROR("Post passes need the shader overrides for FXC");
    return nullptr;
  }
  std::unique_ptr<PostPasses> passes(new PostPasses(command_processor, *overrides));
  if (!passes->Initialize()) {
    return nullptr;
  }
  return passes;
}

PostPasses::PostPasses(D3D12CommandProcessor& command_processor, ShaderOverrides& overrides)
    : command_processor_(command_processor), overrides_(overrides) {}

PostPasses::~PostPasses() {
  // The command processor awaits the GPU before shutting down.
  ReleaseTextures();
  for (History* history :
       {&history_color_[0], &history_color_[1], &history_depth_[0], &history_depth_[1]}) {
    ReleaseHistory(*history);
  }
  ReleasePendingDescriptors(true);
}

bool PostPasses::Initialize() {
  directory_ = REXCVAR_GET(post_pass_path);
  hot_reload_ = overrides_.hot_reload();
  start_time_ = last_poll_ = std::chrono::steady_clock::now();
  // <hash>:<constant>;...
  std::istringstream logged(REXCVAR_GET(post_pass_log_constants));
  for (std::string entry; std::getline(logged, entry, ';');) {
    size_t colon = entry.find(':');
    if (colon == std::string::npos) continue;
    LoggedConstant constant = {std::strtoull(entry.substr(0, colon).c_str(), nullptr, 16),
                               uint32_t(std::strtoul(entry.c_str() + colon + 1, nullptr, 10)), 0};
    if (constant.constant < 256) logged_constants_.push_back(constant);
  }
  // <hash>:<constant>:<slots>;...
  std::istringstream checks(REXCVAR_GET(post_pass_motion_check));
  for (std::string entry; std::getline(checks, entry, ';');) {
    size_t colon = entry.find(':'), second = entry.find(':', colon + 1);
    if (colon == std::string::npos || second == std::string::npos) continue;
    MotionCheck check = {std::strtoull(entry.substr(0, colon).c_str(), nullptr, 16),
                         uint32_t(std::strtoul(entry.c_str() + colon + 1, nullptr, 10)),
                         uint32_t(std::strtoul(entry.c_str() + second + 1, nullptr, 10)), 0};
    check.slots = std::min(check.slots, post_pass::kMotionSlots);
    if (check.constant + check.slots * 4 <= 256) motion_checks_.push_back(check);
  }
  motion_first_worlds_.resize(post_pass::kMotionSlots);

  const ui::d3d12::D3D12Provider& provider = command_processor_.GetD3D12Provider();
  ID3D12Device* device = provider.GetDevice();

  // post_pass_layout.h.
  D3D12_ROOT_PARAMETER parameters[post_pass::kRootParameterCount];
  D3D12_DESCRIPTOR_RANGE ranges[post_pass::kMaxSrvs + post_pass::kMaxUavs];
  parameters[post_pass::kRootSceneConstants].ParameterType = D3D12_ROOT_PARAMETER_TYPE_CBV;
  parameters[post_pass::kRootSceneConstants].Descriptor.ShaderRegister = 0;
  parameters[post_pass::kRootSceneConstants].Descriptor.RegisterSpace = 0;
  parameters[post_pass::kRootSceneConstants].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
  parameters[post_pass::kRootPassConstants].ParameterType =
      D3D12_ROOT_PARAMETER_TYPE_32BIT_CONSTANTS;
  parameters[post_pass::kRootPassConstants].Constants.ShaderRegister = 1;
  parameters[post_pass::kRootPassConstants].Constants.RegisterSpace = 0;
  parameters[post_pass::kRootPassConstants].Constants.Num32BitValues =
      post_pass::kPassConstantCount;
  parameters[post_pass::kRootPassConstants].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
  for (uint32_t i = 0; i < post_pass::kMaxSrvs + post_pass::kMaxUavs; ++i) {
    bool srv = i < post_pass::kMaxSrvs;
    D3D12_DESCRIPTOR_RANGE& range = ranges[i];
    range.RangeType = srv ? D3D12_DESCRIPTOR_RANGE_TYPE_SRV : D3D12_DESCRIPTOR_RANGE_TYPE_UAV;
    range.NumDescriptors = 1;
    range.BaseShaderRegister = srv ? i : i - post_pass::kMaxSrvs;
    range.RegisterSpace = 0;
    range.OffsetInDescriptorsFromTableStart = 0;
    D3D12_ROOT_PARAMETER& parameter = parameters[post_pass::kRootSrvFirst + i];
    parameter.ParameterType = D3D12_ROOT_PARAMETER_TYPE_DESCRIPTOR_TABLE;
    parameter.DescriptorTable.NumDescriptorRanges = 1;
    parameter.DescriptorTable.pDescriptorRanges = &range;
    parameter.ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
  }
  D3D12_STATIC_SAMPLER_DESC samplers[3] = {};
  const D3D12_FILTER filters[3] = {D3D12_FILTER_MIN_MAG_LINEAR_MIP_POINT,
                                   D3D12_FILTER_MIN_MAG_MIP_POINT,
                                   D3D12_FILTER_MIN_MAG_MIP_LINEAR};
  for (uint32_t i = 0; i < 3; ++i) {
    samplers[i].Filter = filters[i];
    samplers[i].AddressU = samplers[i].AddressV = samplers[i].AddressW =
        D3D12_TEXTURE_ADDRESS_MODE_CLAMP;
    samplers[i].MaxLOD = D3D12_FLOAT32_MAX;
    samplers[i].ShaderRegister = i;
    samplers[i].RegisterSpace = 0;
    samplers[i].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
  }
  D3D12_ROOT_SIGNATURE_DESC root_signature_desc;
  root_signature_desc.NumParameters = post_pass::kRootParameterCount;
  root_signature_desc.pParameters = parameters;
  root_signature_desc.NumStaticSamplers = 3;
  root_signature_desc.pStaticSamplers = samplers;
  root_signature_desc.Flags = D3D12_ROOT_SIGNATURE_FLAG_NONE;
  *(root_signature_.ReleaseAndGetAddressOf()) =
      ui::d3d12::util::CreateRootSignature(provider, root_signature_desc);
  if (!root_signature_) {
    REXGPU_ERROR("Post passes: failed to create the root signature");
    return false;
  }

  // Render target views, and views for clearing.
  D3D12_DESCRIPTOR_HEAP_DESC heap_desc = {};
  heap_desc.NumDescriptors = kLocalDescriptorCount;
  heap_desc.Type = D3D12_DESCRIPTOR_HEAP_TYPE_RTV;
  heap_desc.Flags = D3D12_DESCRIPTOR_HEAP_FLAG_NONE;
  if (FAILED(device->CreateDescriptorHeap(&heap_desc, IID_PPV_ARGS(&rtv_heap_)))) {
    REXGPU_ERROR("Post passes: failed to create the render target view heap");
    return false;
  }
  heap_desc.Type = D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV;
  if (FAILED(device->CreateDescriptorHeap(&heap_desc, IID_PPV_ARGS(&cpu_heap_)))) {
    REXGPU_ERROR("Post passes: failed to create the view heap");
    return false;
  }
  rtv_increment_ = device->GetDescriptorHandleIncrementSize(D3D12_DESCRIPTOR_HEAP_TYPE_RTV);
  cpu_increment_ = device->GetDescriptorHandleIncrementSize(D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV);
  for (uint32_t i = kLocalDescriptorCount; i-- > 0;) {
    free_rtvs_.push_back(i);
    free_cpu_.push_back(i);
  }

  auto manifest = std::make_unique<Manifest>();
  bool loaded = LoadManifest(*manifest);
  if (loaded) {
    // The names shader_mod_set changes for the passes (and the mods don't
    // see), before any mod is compiled.
    std::vector<std::string> names;
    for (const auto& define : manifest->defines) names.push_back(define.first);
    for (const ParamDesc& param : manifest->params) names.push_back(param.name);
    overrides_.SetPassNames(std::move(names));
  }
  defines_generation_ = overrides_.defines_generation();
  ShaderOverrides::RefreshFileState(directory_ / kManifestName, manifest_file_);
  if (!loaded || !CompileManifest(*manifest)) {
    watched_.clear();
    for (const auto& file : manifest->files) {
      ShaderOverrides::FileState state;
      ShaderOverrides::RefreshFileState(file.path, state);
      watched_.emplace_back(file.path, state);
    }
    if (!hot_reload_) {
      return false;
    }
    REXGPU_WARN("Post passes: none until {} is fixed (hot reload)",
                (directory_ / kManifestName).generic_string());
    return true;
  }
  manifest_ = std::move(manifest);
  textures_.assign(manifest_->textures.size(), Texture());
  previous_textures_.assign(manifest_->textures.size(), Texture());
  previous_texture_ready_.assign(manifest_->textures.size(), false);
  watched_.clear();
  for (const auto& file : manifest_->files) {
    ShaderOverrides::FileState state;
    ShaderOverrides::RefreshFileState(file.path, state);
    watched_.emplace_back(file.path, state);
  }
  return true;
}

